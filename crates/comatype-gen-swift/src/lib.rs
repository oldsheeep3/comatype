struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    Json,
    Wire,
    Plain,
}

fn strip_null(t: &Type) -> (&Type, bool) {
    if let Type::Union { variants } = t {
        let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
        if non_null.len() == 1 && non_null.len() != variants.len() {
            return (non_null[0], true);
        }
    }
    (t, false)
}

fn literal_union(t: &Type) -> Option<Vec<String>> {
    match t {
        Type::Literal { value } => Some(vec![value.clone()]),
        Type::Union { variants } if variants.iter().all(|v| matches!(v, Type::Literal { .. })) => {
            Some(variants.iter().map(|v| if let Type::Literal { value } = v { value.clone() } else { String::new() }).collect())
        }
        _ => None,
    }
}

fn scalar_ty(name: &str) -> &'static str {
    match name {
        "string" => "String",
        "bool" => "Bool",
        "int" => "Int",
        "int64" => "Int64",
        "email" => "Email",
        "phone" => "Phone",
        "uuid" | "uuidv4" | "uuidv7" => "UUID",
        "date" => "LocalDate",
        "datetime" => "Date",
        "time" => "LocalTime",
        "decimal" => "Decimal",
        "url" => "URL",
        "bytes" => "Data",
        _ => "JSON",
    }
}

impl<'a> Gen<'a> {
    fn is_enum(&self, id: &str) -> bool {
        self.names.contains_key(&format!("enum:{id}"))
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    fn sty(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<String, String> {
        match t {
            Type::Scalar { name, .. } => {
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                Ok(scalar_ty(name).to_string())
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(name.clone())
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.struct_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(name)
            }
            Type::Array { item } => {
                if strip_null(item).1 {
                    return Err("null を含む配列の要素は Swift では未対応です".into());
                }
                Ok(format!("[{}]", self.sty(item, &format!("{hint}Item"), mode)?))
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if literal_union(t).is_some() {
                    return Ok("String".into());
                }
                Err("Swift ではユニオン型を表せません（`T | null` と、文字列リテラルだけのユニオンに対応しています）".into())
            }
            Type::Null => Err("null だけの型は Swift では未対応です".into()),
        }
    }

    fn dec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "Codec.string",
                "bool" => "Codec.bool",
                "int" => "Codec.integer",
                "int64" => "Codec.int64",
                "email" => "Codec.email",
                "phone" => "Codec.phone",
                "uuid" => "Codec.uuid",
                "uuidv4" => "Codec.uuidv4",
                "uuidv7" => "Codec.uuidv7",
                "date" => "Codec.date",
                "datetime" => "Codec.datetime",
                "time" => "Codec.time",
                "decimal" => "Codec.decimal",
                "url" => "Codec.url",
                "bytes" => "Codec.bytes",
                _ => "Codec.json",
            }
            .to_string(),
            Type::Ref { id, .. } => format!("{}.decode", self.names.get(id).cloned().unwrap_or_default()),
            Type::Array { item } => format!("{{ j, p in try Codec.list(j, p, {}) }}", self.dec(item)),
            _ => "Codec.string".into(),
        }
    }

    fn wdec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "Wire.string",
                "bool" => "Wire.bool",
                "int" => "Wire.integer",
                "int64" => "Wire.int64",
                "email" => "Wire.email",
                "phone" => "Wire.phone",
                "uuid" => "Wire.uuid",
                "uuidv4" => "Wire.uuidv4",
                "uuidv7" => "Wire.uuidv7",
                "date" => "Wire.date",
                "datetime" => "Wire.datetime",
                "time" => "Wire.time",
                "decimal" => "Wire.decimal",
                "url" => "Wire.url",
                _ => "Wire.string",
            }
            .to_string(),
            Type::Ref { id, .. } => format!("{}.parse", self.names.get(id).cloned().unwrap_or_default()),
            _ => "Wire.string".into(),
        }
    }

    /// Expression that turns a Swift value into JSON (`e` is assumed non-nil)
    fn enc(&self, t: &Type, e: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => format!(".string({e})"),
                "bool" => format!(".bool({e})"),
                "int" => format!(".int(Int64({e}))"),
                "int64" => format!(".string(String({e}))"),
                "email" | "phone" => format!(".string({e}.value)"),
                "uuid" | "uuidv4" | "uuidv7" => format!(".string({e}.wireString)"),
                "date" | "time" => format!(".string({e}.description)"),
                "datetime" => format!(".string(Codec.formatDatetime({e}))"),
                "decimal" => format!(".string(Codec.formatDecimal({e}))"),
                "url" => format!(".string({e}.absoluteString)"),
                "bytes" => format!(".string({e}.base64EncodedString())"),
                _ => e.to_string(),
            },
            Type::Ref { .. } | Type::Object { .. } => format!("{e}.encode()"),
            Type::Array { item } => {
                let x = format!("x{depth}");
                format!(".array({e}.map {{ {x} in {} }})", self.enc(item, &x, depth + 1))
            }
            _ => format!(".string({e})"),
        }
    }

    fn vstmts(&self, t: &Type, var: &str, path: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, constraint } => {
                let mut s = String::new();
                match name.as_str() {
                    "email" | "phone" => s.push_str(&format!("try {var}.validate(path: {path})\n")),
                    "uuidv4" => s.push_str(&format!("try Check.uuidVersion({path}, {var}, 4)\n")),
                    "uuidv7" => s.push_str(&format!("try Check.uuidVersion({path}, {var}, 7)\n")),
                    _ => {}
                }
                match constraint {
                    Some(Constraint::Range { min, max }) => {
                        let opt = |v: &Option<i64>| v.map_or("nil".to_string(), |n| n.to_string());
                        match name.as_str() {
                            "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" => {
                                s.push_str(&format!("try Check.len({path}, Wire.str({var}), {}, {})\n", opt(min), opt(max)))
                            }
                            "int" | "int64" => s.push_str(&format!("try Check.range({path}, Double({var}), {}, {})\n", opt(min), opt(max))),
                            "decimal" => s.push_str(&format!("try Check.range({path}, {var}, {}, {})\n", opt(min), opt(max))),
                            _ => {}
                        }
                    }
                    Some(Constraint::Pattern { value }) => {
                        if matches!(
                            name.as_str(),
                            "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" | "decimal"
                        ) {
                            s.push_str(&format!("try Check.pattern({path}, Wire.str({var}), {})\n", sstr(value)));
                        }
                    }
                    None => {}
                }
                s
            }
            Type::Ref { id, .. } => {
                if self.is_enum(id) {
                    String::new()
                } else {
                    format!("try {var}.validate(path: {path})\n")
                }
            }
            Type::Object { .. } => format!("try {var}.validate(path: {path})\n"),
            Type::Array { item } => {
                let (i, it) = (format!("i{depth}"), format!("item{depth}"));
                let inner = self.vstmts(item, &it, &format!("{path} + \"[\\({i})]\""), depth + 1);
                if inner.is_empty() {
                    String::new()
                } else {
                    format!("for ({i}, {it}) in {var}.enumerated() {{\n{inner}}}\n")
                }
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if let Some(vals) = literal_union(t) {
                    let list = vals.iter().map(|v| sstr(v)).collect::<Vec<_>>().join(", ");
                    return format!("try Check.oneOf({path}, {var}, [{list}])\n");
                }
                String::new()
            }
            Type::Null => String::new(),
        }
    }

    fn struct_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut props = String::new();
        let mut init_params = Vec::new();
        let mut init_body = String::new();
        let mut checks = String::new();
        let mut puts = String::new();
        let mut args = Vec::new();
        let mut seen = BTreeSet::new();
        for f in fields {
            let fname = camel(&f.name);
            if !seen.insert(fname.clone()) {
                return Err(format!("{name}: フィールド名 {fname} が重複します（{}）", f.name));
            }
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let ty = self.sty(inner, &format!("{name}{}", pascal(&f.name)), mode).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            let q = if opt { "?" } else { "" };
            props.push_str(&format!("public var {fname}: {ty}{q}\n"));
            let default = if f.optional { " = nil" } else { "" };
            init_params.push(format!("{fname}: {ty}{q}{default}"));
            init_body.push_str(&format!("self.{fname} = {fname}\n"));
            let path = format!("ValidationError.join(path, {})", sstr(&f.name));
            let body = self.vstmts(inner, "v", &path, 0);
            if !body.is_empty() {
                if opt {
                    checks.push_str(&format!("if let v = {fname} {{\n{body}}}\n"));
                } else {
                    checks.push_str(&format!("do {{\nlet v = {fname}\n{body}}}\n"));
                }
            }
            if mode == Mode::Json {
                let e = self.enc(inner, "v", 0);
                if f.optional {
                    puts.push_str(&format!("if let v = {fname} {{ m.append(({}, {e})) }}\n", sstr(&f.name)));
                } else if nullable {
                    puts.push_str(&format!(
                        "if let v = {fname} {{ m.append(({}, {e})) }} else {{ m.append(({}, .null)) }}\n",
                        sstr(&f.name),
                        sstr(&f.name)
                    ));
                } else {
                    puts.push_str(&format!("do {{\nlet v = {fname}\nm.append(({}, {e}))\n}}\n", sstr(&f.name)));
                }
                let d = self.dec(inner);
                let call = if f.optional {
                    format!("try Codec.opt(m, {}, path, {d})", sstr(&f.name))
                } else if nullable {
                    format!("try Codec.req(m, {}, path, Codec.nullable({d}))", sstr(&f.name))
                } else {
                    format!("try Codec.req(m, {}, path, {d})", sstr(&f.name))
                };
                args.push(format!("{fname}: {call}"));
            }
        }
        let conforms = if mode == Mode::Json { ": JsonType" } else { "" };
        let mut body = String::new();
        body.push_str(&props);
        body.push_str(&format!("\npublic init({}) {{\n{}}}\n", init_params.join(", "), indent(init_body.trim_end())));
        if mode == Mode::Json {
            body.push_str(&format!("\npublic func validate(path: String) throws {{\n{}}}\n", indent(&checks)));
            body.push_str(&format!(
                "\npublic func encode() -> JSON {{\nvar m: [(key: String, value: JSON)] = []\n{}return .object(m)\n}}\n",
                puts.lines().map(|l| format!("{l}\n")).collect::<String>().lines().map(|l| format!("{l}\n")).collect::<String>()
            ));
            body.push_str(&format!(
                "\npublic static func decode(_ j: JSON, _ path: String) throws -> {name} {{\nlet m = try Codec.object(j, path)\nlet v = {name}({})\ntry v.validate(path: path)\nreturn v\n}}\n",
                args.join(", ")
            ));
        } else if mode == Mode::Wire {
            body.push_str(&format!("\npublic func validate(path: String) throws {{\n{}}}\n", indent(&checks)));
        }
        Ok(format!("public struct {name}{conforms} {{\n{}}}\n", indent(body.trim_end())))
    }

    fn named_object(&mut self, name: &str, t: &Type) -> Result<Option<String>, String> {
        self.used_names.insert(name.to_string());
        match t {
            Type::Object { fields } => {
                let decl = self.struct_decl(name, fields, Mode::Json)?;
                let mut out = String::new();
                for e in self.extra.drain(..) {
                    out.push_str(&e);
                    out.push('\n');
                }
                out.push_str(&decl);
                Ok(Some(out))
            }
            _ => Ok(None),
        }
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        let name = cap(&nt.name);
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("Swift の型名 `{name}` が {prev} と {id} で重複しています"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

fn indent(s: &str) -> String {
    s.lines().map(|l| if l.is_empty() { String::new() } else { format!("    {l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

// ---- Types.swift ----

fn types_file(svc: &Service, names: &BTreeMap<String, String>) -> Result<String, String> {
    let mut g = Gen { names, extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = g.struct_decl(name, fields, Mode::Json)?;
                for e in g.extra.drain(..) {
                    body.push_str(&e);
                    body.push('\n');
                }
                body.push_str(&decl);
                body.push('\n');
            }
            TypeDef::Enum { values } => {
                let mut cases = String::new();
                let mut seen = BTreeSet::new();
                for v in values {
                    let c = camel(v);
                    if !seen.insert(c.clone()) {
                        return Err(format!("{name}: enum の値 {c} が重複します（{v}）"));
                    }
                    cases.push_str(&format!("case {c} = {}\n", sstr(v)));
                }
                let all = values.join(" | ");
                body.push_str(&format!(
                    "public enum {name}: String, WireString, CaseIterable {{\n{}\n    public func validate(path: String) throws {{}}\n\n    public func encode() -> JSON {{ .string(rawValue) }}\n\n\
                     \x20   public static func parse(_ s: String) throws -> {name} {{\n        guard let v = {name}(rawValue: s) else {{ throw ValidationError(path: \"\", reason: {}) }}\n        return v\n    }}\n\n\
                     \x20   public static func decode(_ j: JSON, _ path: String) throws -> {name} {{\n        do {{\n            return try parse(try Codec.string(j, path))\n        }} catch let e as ValidationError where e.path.isEmpty {{\n            throw ValidationError(path: path, reason: e.reason)\n        }}\n    }}\n}}\n\n",
                    indent(cases.trim_end()),
                    sstr(&format!("{all} のどれかにしてください"))
                ));
            }
        }
    }
    Ok(format!("{HEADER}\n{}", body.trim_end().to_string() + "\n"))
}

