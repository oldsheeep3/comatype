//! Generates Swift code from the IR (structs + enums; the runtime is the `Comatype` module).
//!
//! Output (under `<out>`; `<out>` is the directory of the Swift Package target `ComatypeGen`; default `Sources/ComatypeGen`):
//!   Types.swift         named types (structs, enums)
//!   Init.swift          `ComatypeInit`: wrappers, ctx, wrapper statuses
//!   <Module>.swift      one per endpoint (e.g. UserPutId.swift; the module name is a PascalCase enum)
//!
//! The contents of Init and the endpoints differ between client and server (matching the runtime's C / S).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "// Code generated by comatype generate. DO NOT EDIT.\nimport Foundation\nimport Comatype\n";

pub fn generate(svc: &Service, role: Role) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut files = vec![
        GenFile { path: "Types.swift".into(), content: types_file(svc, &names)? },
        GenFile { path: "Init.swift".into(), content: init_file(svc, &names, role)? },
    ];
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let m = module_class(&ep.module);
        if m == "ComatypeInit" || names.values().any(|n| *n == m) {
            return Err(format!("{} は Swift では生成先の名前 `{m}` が他の型（ComatypeInit や宣言した型）と衝突します（ファイルかディレクトリの名前を変えてください）", ep.file));
        }
        if let Some(prev) = seen.insert(m.clone(), &ep.file) {
            return Err(format!("{} と {prev} が同じ名前 `{m}` になります", ep.file));
        }
        files.push(GenFile { path: format!("{m}.swift"), content: endpoint_file(svc, &names, ep, role)? });
    }
    for f in &mut files {
        f.content = reindent(&f.content);
    }
    Ok(files)
}

/// Fixes indentation by brace depth (the generated fragments carry no indentation for nesting)
fn reindent(code: &str) -> String {
    let mut depth: i32 = 0;
    let mut out = String::new();
    for line in code.lines() {
        let t = line.trim();
        if t.is_empty() {
            out.push('\n');
            continue;
        }
        let opens = t.matches('{').count() as i32;
        let closes = t.matches('}').count() as i32;
        let leading = t.chars().take_while(|c| *c == '}' || *c == ')').filter(|c| *c == '}').count() as i32;
        let d = (depth - leading).max(0);
        // Comment lines (/// and * ) are aligned to their own column
        out.push_str(&"    ".repeat(d as usize));
        out.push_str(if t.starts_with('*') { &line.trim_end()[line.len() - line.trim_start().len()..] } else { t });
        out.push('\n');
        depth = (depth + opens - closes).max(0);
    }
    out
}

