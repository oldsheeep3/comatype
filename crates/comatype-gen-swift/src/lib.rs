fn cookie_def_swift(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("nil".to_string(), sstr);
    format!(
        "CookieDef(name: {}, httpOnly: {}, secure: {}, sameSite: {}, path: {}, domain: {}, maxAge: {})",
        sstr(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("nil".to_string(), |v| v.to_string()),
    )
}

fn body_codec(g: &mut Gen, label: &str, t: &Type, ty: &str) -> String {
    let (inner, _) = strip_null(t);
    let v = g.vstmts(inner, "v", "\"\"", 0);
    let enc = g.enc(inner, "v", 0);
    let dec = match inner {
        Type::Object { .. } => format!("{ty}.decode"),
        _ => g.dec(inner),
    };
    format!(
        "private static func encode{label}(_ v: {ty}) throws -> Data {{\n{}    return Codec.encodeValue({enc})\n}}\n\n\
         private static func decode{label}(_ b: Data, _ path: String) throws -> {ty} {{\n    try Codec.decode(b, path, {dec})\n}}\n\n",
        v.lines().map(|l| format!("    {l}\n")).collect::<String>()
    )
}

fn wire_pairs(fields: &[Field], var: &str) -> String {
    format!(
        "[{}]",
        fields.iter().map(|f| format!("({}, Wire.strs({var}.{}))", sstr(&f.name), camel(&f.name))).collect::<Vec<_>>().join(", ")
    )
}

fn wire_build(name: &str, fields: &[Field], g: &Gen, values: &str, split: bool) -> String {
    let args: Vec<String> = fields
        .iter()
        .map(|f| {
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let vals = values.replace("{}", &sstr(&f.name));
            let call = match inner {
                Type::Array { item } => {
                    format!("try Wire.readList{}({vals}, {}, {split}, {})", if opt { "Opt" } else { "" }, sstr(&f.name), g.wdec(item))
                }
                _ if opt => format!("try Wire.readOpt({vals}, {}, {split}, {})", sstr(&f.name), g.wdec(inner)),
                _ => format!("try Wire.read({vals}, {}, {split}, {})", sstr(&f.name), g.wdec(inner)),
            };
            format!("{}: {call}", camel(&f.name))
        })
        .collect();
    format!("{name}({})", args.join(", "))
}

/// The `cache` setting (GET / QUERY only)
fn cache_swift(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let spec = match &ep.cache {
        None => return String::new(),
        Some(CacheMode::Off) => "CacheSpec(.off)".to_string(),
        Some(CacheMode::Memory { ttl_ms }) => format!("CacheSpec(.memory, ttlMs: {ttl_ms})"),
        Some(CacheMode::Cookie { ttl_ms }) => format!("CacheSpec(.cookie, ttlMs: {ttl_ms})"),
    };
    let names: Vec<String> = ep.request_headers.iter().map(|h| sstr(&h.name)).collect();
    format!(", cache: {spec}, cacheHeaders: [{}]", names.join(", "))
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role) -> Result<String, String> {
    let class = module_class(&ep.module);
    let mut g = Gen { names, extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();
    let mut codecs = String::new();
    let has_req_headers = !ep.request_headers.is_empty();
    let all_optional = |fs: &[Field]| fs.iter().all(|f| f.optional || strip_null(&f.ty).1);

    if !ep.params.is_empty() {
        body.push_str(&g.struct_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    if !ep.search.is_empty() {
        body.push_str(&g.struct_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let mut body_ty = String::new();
    if let Some(b) = &ep.body {
        g.used_names.insert("Body".into());
        if let Some(decl) = g.named_object("Body", b).map_err(ctx)? {
            body.push_str(&decl);
            body.push('\n');
            body_ty = "Body".into();
        } else {
            let (inner, _) = strip_null(b);
            body_ty = g.sty(inner, "Body", Mode::Json).map_err(ctx)?;
        }
        codecs.push_str(&body_codec(&mut g, "Body", b, &body_ty));
    }
    if has_req_headers {
        body.push_str(&g.struct_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let props: String =
            ctx_wrappers.iter().map(|w| format!("public var {}: ComatypeInit.{}Ctx\n", camel(&w.name), pascal(&w.name))).collect();
        let params: Vec<String> = ctx_wrappers.iter().map(|w| format!("{}: ComatypeInit.{}Ctx", camel(&w.name), pascal(&w.name))).collect();
        let inits: String = ctx_wrappers.iter().map(|w| format!("self.{0} = {0}\n", camel(&w.name))).collect();
        body.push_str(&format!(
            "/// 有効なラッパーが足した値\npublic struct Ctx {{\n{}\n    public init({}) {{\n{}    }}\n}}\n\n",
            indent(props.trim_end()),
            params.join(", "),
            indent(&indent(&inits))
        ));
    }
    // Whole request
    let mut req_comps: Vec<(&str, String, String)> = Vec::new(); // (name, type, default)
    if !ep.params.is_empty() {
        req_comps.push(("params", "Params".into(), String::new()));
    }
    if !ep.search.is_empty() {
        req_comps.push(("search", "Search".into(), if all_optional(&ep.search) { " = Search()".into() } else { String::new() }));
    }
    if has_req_headers {
        req_comps.push((
            "headers",
            "RequestHeaders".into(),
            if all_optional(&ep.request_headers) { " = RequestHeaders()".into() } else { String::new() },
        ));
    }
    if ep.body.is_some() {
        req_comps.push(("body", body_ty.clone(), String::new()));
    }
    if role == Role::Server {
        req_comps.push(("ctx", "Ctx".into(), String::new()));
    }
    let has = |n: &str| req_comps.iter().any(|(f, _, _)| *f == n);
    let props: String = req_comps.iter().map(|(n, t, _)| format!("public var {n}: {t}\n")).collect();
    let params: Vec<String> = req_comps.iter().map(|(n, t, d)| format!("{n}: {t}{d}")).collect();
    let inits: String = req_comps.iter().map(|(n, _, _)| format!("self.{n} = {n}\n")).collect();
    body.push_str(&format!(
        "/// リクエスト全体\npublic struct Request {{\n{}\n    public init({}) {{\n{}    }}\n}}\n\n",
        indent(props.trim_end()),
        params.join(", "),
        indent(&indent(&inits))
    ));

    let cookie = ep.cookie && svc.cookie.is_some();
    let mut cases = String::new();
    for r in &ep.responses {
        let c = r.status;
        let mut comps = Vec::new();
        if let Some(b) = &r.body {
            let label = format!("S{c}Res");
            let (inner, _) = strip_null(b);
            let ty = if let Some(decl) = g.named_object(&label, b).map_err(ctx)? {
                body.push_str(&decl);
                body.push('\n');
                label.clone()
            } else {
                g.sty(inner, &label, Mode::Json).map_err(ctx)?
            };
            codecs.push_str(&body_codec(&mut g, &format!("S{c}"), b, &ty));
            comps.push(format!("body: {ty}"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.struct_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            body.push('\n');
            let d = if all_optional(&r.headers) { format!(" = S{c}Headers()") } else { String::new() };
            comps.push(format!("headers: S{c}Headers{d}"));
        }
        cases.push_str(&if comps.is_empty() { format!("case s{c}\n") } else { format!("case s{c}({})\n", comps.join(", ")) });
    }
    body.push_str(&format!("/// 全ステータスのレスポンス\npublic enum Response {{\n{}}}\n\n", indent(&cases)));

    let arg = if has("params") || has("search") || has("headers") {
        "Request".to_string()
    } else if ep.body.is_some() {
        body_ty.clone()
    } else {
        "NoArg".to_string()
    };
    let res_ty = if role == Role::Server && cookie { "S.Reply<Response>".to_string() } else { "Response".to_string() };
    let wraps = format!("[{}]", ep.wraps.iter().map(|w| sstr(w)).collect::<Vec<_>>().join(", "));
    let base = svc.base_url.as_ref().map_or("nil".to_string(), |u| sstr(u));
    let cd = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_swift(c),
        _ => "nil".to_string(),
    };
    let common = format!(
        "method: {}, path: {}, module: {}, baseURL: {base}, wraps: {wraps}, cookie: {}, cookieDef: {cd}{}",
        sstr(&ep.method),
        sstr(&ep.path),
        sstr(&ep.module),
        ep.cookie,
        cache_swift(ep)
    );
    match role {
        Role::Client => body.push_str(&format!(
            "/// path とメソッド\npublic static let endpoint = Endpoint<{arg}, Never, Response>(\n    {common},\n    buildRequest: {{ try {class}.buildRequest($0) }}, parseResponse: {{ try {class}.parseResponse($0) }})\n\n"
        )),
        Role::Server => body.push_str(&format!(
            "/// path とメソッド\npublic static let endpoint = Endpoint<Never, Request, {res_ty}>(\n    {common},\n    parseRequest: {{ try {class}.parseRequest($0) }}, buildResponse: {{ try {class}.buildResponse($0) }})\n\n"
        )),
    }
    body.push_str(&codecs);

    match role {
        Role::Client => {
            let mut f = format!(
                "private static func buildRequest(_ arg: {arg}) throws -> RawRequest {{\n    var raw = RawRequest(method: {}, path: {})\n",
                sstr(&ep.method),
                sstr(&ep.path)
            );
            if arg == "Request" {
                if has("params") {
                    f.push_str(&format!(
                        "    try arg.params.validate(path: \"\")\n    try Wire.fillPath(&raw, {})\n",
                        wire_pairs(&ep.params, "arg.params")
                    ));
                }
                if has("search") {
                    f.push_str(&format!(
                        "    try arg.search.validate(path: \"\")\n    Wire.addQuery(&raw, {})\n",
                        wire_pairs(&ep.search, "arg.search")
                    ));
                }
                if has("headers") {
                    f.push_str(&format!(
                        "    try arg.headers.validate(path: \"\")\n    Wire.setHeaders(&raw.headers, {})\n",
                        wire_pairs(&ep.request_headers, "arg.headers")
                    ));
                }
                if has("body") {
                    f.push_str("    raw.body = try encodeBody(arg.body)\n    raw.headers.set(\"Content-Type\", \"application/json\")\n");
                }
            } else if arg != "NoArg" {
                f.push_str("    raw.body = try encodeBody(arg)\n    raw.headers.set(\"Content-Type\", \"application/json\")\n");
            }
            f.push_str("    return raw\n}\n\n");
            body.push_str(&f);

            let mut p =
                String::from("private static func parseResponse(_ raw: RawResponse) throws -> Response {\n    switch raw.status {\n");
            for r in &ep.responses {
                let c = r.status;
                let mut inner = String::new();
                let mut args = Vec::new();
                if r.body.is_some() {
                    inner.push_str(&format!("if raw.body.isEmpty {{ throw ValidationError(path: \"body\", reason: \"必須です\") }}\nlet body = try decodeS{c}(raw.body, \"body\")\n"));
                    args.push("body: body");
                }
                if !r.headers.is_empty() {
                    inner.push_str(&format!(
                        "let headers = {}\ntry headers.validate(path: \"\")\n",
                        wire_build(&format!("S{c}Headers"), &r.headers, &g, "Wire.headerValues(raw.headers, {})", true)
                    ));
                    args.push("headers: headers");
                }
                let ctor = if args.is_empty() { format!(".s{c}") } else { format!(".s{c}({})", args.join(", ")) };
                p.push_str(&format!(
                    "    case {c}:\n{}        return {ctor}\n",
                    inner.lines().map(|l| format!("        {l}\n")).collect::<String>()
                ));
            }
            p.push_str("    default:\n        throw ComatypeError.unexpectedStatus(status: raw.status, body: raw.body)\n    }\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            let mut f = String::from("private static func parseRequest(_ raw: RawRequest) throws -> Request {\n");
            let mut inits = Vec::new();
            if has("params") {
                f.push_str(&format!(
                    "    let params = {}\n    try params.validate(path: \"\")\n",
                    wire_build("Params", &ep.params, &g, "Wire.paramValues(raw, {})", false)
                ));
                inits.push("params: params");
            }
            if has("search") {
                f.push_str(&format!(
                    "    let search = {}\n    try search.validate(path: \"\")\n",
                    wire_build("Search", &ep.search, &g, "Wire.queryValues(raw, {})", false)
                ));
                inits.push("search: search");
            }
            if has("headers") {
                f.push_str(&format!(
                    "    let headers = {}\n    try headers.validate(path: \"\")\n",
                    wire_build("RequestHeaders", &ep.request_headers, &g, "Wire.headerValues(raw.headers, {})", true)
                ));
                inits.push("headers: headers");
            }
            if has("body") {
                f.push_str("    if raw.body.isEmpty { throw ValidationError(path: \"body\", reason: \"必須です\") }\n    let body = try decodeBody(raw.body, \"body\")\n");
                inits.push("body: body");
            }
            if has("ctx") {
                let cs: Vec<String> = ctx_wrappers
                    .iter()
                    .map(|w| format!("{}: try S.ctx(raw, {}, ComatypeInit.{}Ctx.self)", camel(&w.name), sstr(&w.name), pascal(&w.name)))
                    .collect();
                f.push_str(&format!("    let ctx = Ctx({})\n", cs.join(", ")));
                inits.push("ctx: ctx");
            }
            f.push_str(&format!("    return Request({})\n}}\n\n", inits.join(", ")));
            body.push_str(&f);

            let mut b = format!("private static func buildResponse(_ reply: {res_ty}) throws -> RawResponse {{\n");
            b.push_str(if cookie { "    let res = reply.response\n" } else { "    let res = reply\n" });
            b.push_str("    var out: RawResponse\n    switch res {\n");
            for r in &ep.responses {
                let c = r.status;
                let mut pat = Vec::new();
                let mut st = format!("out = RawResponse(status: {c})\n");
                if r.body.is_some() {
                    pat.push("let body");
                    st.push_str(&format!("out.body = try encodeS{c}(body)\nout.headers.set(\"Content-Type\", \"application/json\")\n"));
                }
                if !r.headers.is_empty() {
                    pat.push("let headers");
                    st.push_str(&format!(
                        "try headers.validate(path: \"\")\nWire.setHeaders(&out.headers, {})\n",
                        wire_pairs(&r.headers, "headers")
                    ));
                }
                let pattern = if pat.is_empty() { format!(".s{c}") } else { format!(".s{c}({})", pat.join(", ")) };
                b.push_str(&format!("    case {pattern}:\n{}", st.lines().map(|l| format!("        {l}\n")).collect::<String>()));
            }
            b.push_str("    }\n");
            if cookie {
                b.push_str(&format!("    try S.applyCookie(&out, {class}.endpoint.cookieDef, reply.cookie)\n"));
            }
            b.push_str("    return out\n}\n");
            body.push_str(&b);
        }
    }

    Ok(format!(
        "{HEADER}\n/// {} — {} {}\npublic enum {class} {{\n{}}}\n",
        ep.file,
        ep.method.to_uppercase(),
        ep.path,
        indent(body.trim_end())
    ))
}

