fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role) -> Result<String, String> {
    let mut g = Gen { names, extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut props = String::new();
    let mut params = Vec::new();
    let mut assigns = String::new();
    let mut entries = Vec::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let (p, f) = (pascal(&w.name), camel(&w.name));
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("/// ラッパー {} が足す値（ハンドラの req.ctx.{f}）\n", w.name));
                body.push_str(&g.struct_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            let label = format!("S{c}Res");
                            let (inner, _) = strip_null(b);
                            let ty = if let Some(decl) = g.named_object(&label, b)? {
                                body.push_str(&decl);
                                body.push('\n');
                                label.clone()
                            } else {
                                g.sty(inner, &label, Mode::Json)?
                            };
                            let v = g.vstmts(inner, "body", "\"\"", 0);
                            let enc = g.enc(inner, "body", 0);
                            body.push_str(&format!(
                                "/// ラッパー {} が返せるステータス {c} のレスポンス\npublic static func s{c}(_ body: {ty}) -> RawResponse {{\n    do {{\n{}        var r = RawResponse(status: {c})\n        r.body = Codec.encodeValue({enc})\n        r.headers.set(\"Content-Type\", \"application/json\")\n        return r\n    }} catch {{\n        return RawResponse.error(\"\\(error)\")\n    }}\n}}\n\n",
                                w.name,
                                v.lines().map(|l| format!("        {l}\n")).collect::<String>()
                            ));
                        }
                        None => body.push_str(&format!("/// ラッパー {} が返せるステータス {c} のレスポンス\npublic static func s{c}() -> RawResponse {{ RawResponse(status: {c}) }}\n\n", w.name)),
                    }
                }
                props.push_str(&format!("public var {f}: S.ComatypeWrap<{ctx_name}>\n"));
                params.push(format!("{f}: @escaping S.ComatypeWrap<{ctx_name}>"));
                entries.push(format!("{}: S.adapt({}, {f})", sstr(&w.name), sstr(&w.name)));
            }
            Role::Client => {
                props.push_str(&format!("public var {f}: C.ComatypeWrap\n"));
                params.push(format!("{f}: @escaping C.ComatypeWrap"));
                entries.push(format!("{}: {f}", sstr(&w.name)));
            }
        }
        assigns.push_str(&format!("self.{f} = {f}\n"));
    }
    let (set, wrap_ty) = match role {
        Role::Server => ("S", "S.ServerWrap"),
        Role::Client => ("C", "C.ComatypeWrap"),
    };
    let dict = if entries.is_empty() { "[:]".to_string() } else { format!("[{}]", entries.join(", ")) };
    body.push_str(&format!(
        "/// init.comat の `wrapper` ごとの実装。{set}.initialize に渡す\npublic struct Wrappers: {set}.WrapperSet {{\n{}\n    public init({}) {{\n{}    }}\n\n    public func comatypeWrappers() -> [String: {wrap_ty}] {{\n        {dict}\n    }}\n}}\n",
        indent(props.trim_end()),
        params.join(", "),
        indent(&indent(&assigns))
    ));
    Ok(format!("{HEADER}\n/// init.comat から生成\npublic enum ComatypeInit {{\n{}}}\n", indent(body.trim_end())))
}

