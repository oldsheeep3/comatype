pub fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            continue;
        }
        let prev_lower = i > 0 && chars[i - 1].is_ascii_lowercase();
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
        let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
        if c.is_ascii_uppercase() && !cur.is_empty() && (prev_lower || (prev_upper && next_lower)) {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

fn cap(w: &str) -> String {
    let mut cs = w.chars();
    cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
}

/// `user/put__id` → `UserPutId`
pub fn module_class(module: &str) -> String {
    let out: String = module.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()).map(cap).collect();
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("M{out}")
    } else {
        out
    }
}

/// `user/put__id` → `user_put_id` (file name)
pub fn snake_module(module: &str) -> String {
    let n = module
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| w.to_ascii_lowercase())
        .collect::<Vec<_>>()
        .join("_");
    if n.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("m_{n}")
    } else {
        n
    }
}

/// Attribute name (snake_case)
pub fn attr(s: &str) -> String {
    let n = words(s).iter().map(|w| w.to_ascii_lowercase()).collect::<Vec<_>>().join("_");
    let n = if n.chars().next().is_none_or(|c| c.is_ascii_digit()) { format!("f_{n}") } else { n };
    if RESERVED_ATTRS.contains(&n.as_str()) {
        format!("{n}_")
    } else {
        n
    }
}

fn rstr(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '#' => o.push_str("\\#"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

// ---- Type descriptors ----

struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    /// Prefix of an expression that refers to a named type. Inside types.rb it is a lambda, for forward references
    in_types: bool,
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    Json,
    Wire,
}

impl<'a> Gen<'a> {
    fn is_enum(&self, id: &str) -> bool {
        self.names.contains_key(&format!("enum:{id}"))
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    fn desc(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<String, String> {
        match t {
            Type::Scalar { name, constraint } => {
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                Ok(match constraint {
                    None => format!(":{name}"),
                    Some(Constraint::Range { min, max }) => {
                        let mut parts = Vec::new();
                        if let Some(m) = min {
                            parts.push(format!("min: {m}"));
                        }
                        if let Some(m) = max {
                            parts.push(format!("max: {m}"));
                        }
                        format!("[:{name}, {{{}}}]", parts.join(", "))
                    }
                    Some(Constraint::Pattern { value }) => format!("[:{name}, {{pattern: {}}}]", rstr(value)),
                })
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(if self.in_types { format!("[:ref, -> {{ {name} }}]") } else { format!("[:ref, ComatypeGen::Types::{name}]") })
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.class_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(format!("[:ref, {name}]"))
            }
            Type::Array { item } => Ok(format!("[:array, {}]", self.desc(item, &format!("{hint}Item"), mode)?)),
            Type::Union { variants } => {
                let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
                if non_null.len() == 1 && non_null.len() != variants.len() {
                    return Ok(format!("[:nullable, {}]", self.desc(non_null[0], hint, mode)?));
                }
                if let Some(vals) = literal_union(t) {
                    return Ok(format!("[:literal, [{}]]", vals.iter().map(|v| rstr(v)).collect::<Vec<_>>().join(", ")));
                }
                Err("Ruby ではユニオン型を表せません（`T | null` と、文字列リテラルだけのユニオンに対応しています）".into())
            }
            Type::Literal { value } => Ok(format!("[:literal, [{}]]", rstr(value))),
            Type::Null => Err("null だけの型は Ruby では未対応です".into()),
        }
    }

    fn class_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut lines = String::new();
        let mut seen = BTreeSet::new();
        for f in fields {
            let a = attr(&f.name);
            if !seen.insert(a.clone()) {
                return Err(format!("{name}: フィールド名 {a} が重複します（{}）", f.name));
            }
            let d =
                self.desc(&f.ty, &format!("{name}{}", cap(&a.replace('_', ""))), mode).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            lines.push_str(&format!("  field :{a}, {}, {d}{}\n", rstr(&f.name), if f.optional { ", optional: true" } else { "" }));
        }
        let mut out = String::new();
        for e in self.extra.drain(..) {
            out.push_str(&e);
        }
        out.push_str(&format!("class {name} < Comatype::Model\n{lines}end\n\n"));
        Ok(out)
    }
}

fn literal_union(t: &Type) -> Option<Vec<String>> {
    match t {
        Type::Literal { value } => Some(vec![value.clone()]),
        Type::Union { variants } if variants.iter().all(|v| matches!(v, Type::Literal { .. })) => {
            Some(variants.iter().map(|v| if let Type::Literal { value } = v { value.clone() } else { String::new() }).collect())
        }
        _ => None,
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        let name = cap(&nt.name);
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("Ruby の型名 `{name}` が {prev} と {id} で重複しています"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

fn indent(s: &str, n: usize) -> String {
    let pad = " ".repeat(n);
    s.lines().map(|l| if l.is_empty() { String::new() } else { format!("{pad}{l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

fn wrap_module(name: &str, doc: &str, body: &str) -> String {
    format!("{HEADER}\nmodule ComatypeGen\n  # {doc}\n  module {name}\n{}  end\nend\n", indent(body.trim_end(), 4))
}

// ---- types.rb ----

fn types_file(svc: &Service, names: &BTreeMap<String, String>) -> Result<String, String> {
    let mut g = Gen { names, in_types: true, extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => body.push_str(&g.class_decl(name, fields, Mode::Json)?),
            TypeDef::Enum { values } => {
                body.push_str(&format!(
                    "class {name} < Comatype::Enum\n  values {}\nend\n\n",
                    values.iter().map(|v| rstr(v)).collect::<Vec<_>>().join(", ")
                ));
            }
        }
    }
    Ok(wrap_module("Types", "名前付きの型", &body))
}

// ---- Endpoints ----

fn cookie_def_rb(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("nil".to_string(), rstr);
    format!(
        "Comatype::CookieDef.new(name: {}, http_only: {}, secure: {}, same_site: {}, path: {}, domain: {}, max_age: {})",
        rstr(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("nil".to_string(), |v| v.to_string()),
    )
}

/// The `cache` setting (GET / QUERY only)
fn cache_rb(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let (mode, ttl) = match &ep.cache {
        None => return String::new(),
        Some(CacheMode::Off) => ("off", 0),
        Some(CacheMode::Memory { ttl_ms }) => ("memory", *ttl_ms),
        Some(CacheMode::Cookie { ttl_ms }) => ("cookie", *ttl_ms),
    };
    let names: Vec<String> = ep.request_headers.iter().map(|h| rstr(&h.name)).collect();
    format!("  cache: Comatype::CacheSpec.new(:{mode}, {ttl}),\n  cache_headers: [{}],\n", names.join(", "))
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint) -> Result<String, String> {
    let class = module_class(&ep.module);
    let mut g = Gen { names, in_types: false, extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();

    let model = |g: &mut Gen, name: &str, fields: &[Field], body: &mut String| -> Result<(), String> {
        g.used_names.insert(name.to_string());
        body.push_str(&g.class_decl(name, fields, Mode::Wire).map_err(ctx)?);
        Ok(())
    };
    if !ep.params.is_empty() {
        model(&mut g, "Params", &ep.params, &mut body)?;
    }
    if !ep.search.is_empty() {
        model(&mut g, "Search", &ep.search, &mut body)?;
    }
    if !ep.request_headers.is_empty() {
        model(&mut g, "RequestHeaders", &ep.request_headers, &mut body)?;
    }
    let body_desc = match &ep.body {
        Some(Type::Object { fields }) => {
            g.used_names.insert("Body".into());
            body.push_str(&g.class_decl("Body", fields, Mode::Json).map_err(ctx)?);
            Some("[:ref, Body]".to_string())
        }
        Some(t) => Some(g.desc(t, "Body", Mode::Json).map_err(ctx)?),
        None => None,
    };
    let mut resp_classes = Vec::new();
    for r in &ep.responses {
        let c = r.status;
        let mut cls = format!("class S{c} < Comatype::Response\n  status {c}\n");
        if let Some(b) = &r.body {
            g.used_names.insert(format!("S{c}Res"));
            let d = match b {
                Type::Object { fields } => {
                    body.push_str(&g.class_decl(&format!("S{c}Res"), fields, Mode::Json).map_err(ctx)?);
                    format!("[:ref, S{c}Res]")
                }
                t => g.desc(t, &format!("S{c}Res"), Mode::Json).map_err(ctx)?,
            };
            cls.push_str(&format!("  body_type {d}\n"));
        }
        if !r.headers.is_empty() {
            g.used_names.insert(format!("S{c}Headers"));
            body.push_str(&g.class_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            cls.push_str(&format!("  headers_class S{c}Headers\n"));
        }
        cls.push_str("end\n\n");
        body.push_str(&cls);
        resp_classes.push(format!("S{c}"));
    }
    let cookie_def = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_rb(c),
        _ => "nil".to_string(),
    };
    body.push_str(&format!(
        "# path とメソッド\nENDPOINT = Comatype::Endpoint.new(\n  method: {},\n  path: {},\n  module_name: {},\n  base_url: {},\n  wraps: [{}],\n  cookie: {},\n  cookie_def: {cookie_def},\n{}  params: {},\n  search: {},\n  headers: {},\n  body: {},\n  responses: [{}]\n)\n",
        rstr(&ep.method),
        rstr(&ep.path),
        rstr(&ep.module),
        svc.base_url.as_ref().map_or("nil".to_string(), |u| rstr(u)),
        ep.wraps.iter().map(|w| rstr(w)).collect::<Vec<_>>().join(", "),
        ep.cookie,
        cache_rb(ep),
        if ep.params.is_empty() { "nil" } else { "Params" },
        if ep.search.is_empty() { "nil" } else { "Search" },
        if ep.request_headers.is_empty() { "nil" } else { "RequestHeaders" },
        body_desc.unwrap_or_else(|| "nil".into()),
        resp_classes.join(", "),
    ));
    let mut out = String::new();
    for e in g.extra.drain(..) {
        out.push_str(&e);
    }
    out.push_str(&body);
    Ok(wrap_module(&class, &format!("{} — {} {}", ep.file, ep.method.to_uppercase(), ep.path), &out)
        .replace("require \"comatype\"\n", "require \"comatype\"\nrequire_relative \"types\"\n"))
}

// ---- init.rb ----

fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role) -> Result<String, String> {
    let mut g = Gen { names, in_types: false, extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut kw = Vec::new();
    let mut entries = Vec::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let a = attr(&w.name);
        kw.push(format!("{a}:"));
        entries.push(format!("{} => {a}", rstr(&w.name)));
        if role == Role::Server {
            let ctx_name = format!("{}Ctx", cap(&w.name));
            g.used_names.insert(ctx_name.clone());
            body.push_str(&format!("# ラッパー {} が足す値（ラッパーが req.ctx[:{}] に入れ、ハンドラが読む）\n", w.name, w.name));
            body.push_str(&g.class_decl(&ctx_name, &w.ctx, Mode::Json)?);
            for r in &w.responses {
                if let Some(prev) = seen_status.insert(r.status, &w.name) {
                    return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                }
                let c = r.status;
                let mut cls = format!("class S{c} < Comatype::Response\n  status {c}\n");
                if let Some(b) = &r.body {
                    g.used_names.insert(format!("S{c}Res"));
                    let d = match b {
                        Type::Object { fields } => {
                            body.push_str(&g.class_decl(&format!("S{c}Res"), fields, Mode::Json)?);
                            format!("[:ref, S{c}Res]")
                        }
                        t => g.desc(t, &format!("S{c}Res"), Mode::Json)?,
                    };
                    cls.push_str(&format!("  body_type {d}\n"));
                }
                cls.push_str("end\n\n");
                body.push_str(&cls);
                body.push_str(&format!(
                    "# ラッパー {} が返せるステータス {c} のレスポンス（RawResponse）\ndef self.s{c}({})\n  S{c}.raw({})\nend\n\n",
                    w.name,
                    if r.body.is_some() { "body" } else { "" },
                    if r.body.is_some() { "body" } else { "" }
                ));
            }
        }
    }
    let sig = if kw.is_empty() { String::new() } else { format!("({})", kw.join(", ")) };
    body.push_str(&format!(
        "# init.comat の `wrapper` ごとの実装を、名前で束ねる（足りないと ArgumentError）。{}\ndef self.wrappers{sig}\n  {{ {} }}\nend\n",
        if role == Role::Server { "Comatype::S#init に渡す" } else { "Comatype::C.init に渡す" },
        entries.join(", ")
    ));
    let mut out = String::new();
    for e in g.extra.drain(..) {
        out.push_str(&e);
    }
    out.push_str(&body);
    Ok(wrap_module("Init", "init.comat から生成", &out)
        .replace("require \"comatype\"\n", "require \"comatype\"\nrequire_relative \"types\"\n"))
}

