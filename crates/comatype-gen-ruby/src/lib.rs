//! Generates Ruby code from the IR. Types are written out as descriptors; conversion and validation are done by the runtime `comatype` (packages/ruby).
//!
//! Output (under `<out>`; default `comatype_gen`; the module is `ComatypeGen`):
//!   types.rb          named types (subclasses of Comatype::Model / Comatype::Enum)  ComatypeGen::Types
//!   init.rb           wrappers, ctx, wrapper statuses                                ComatypeGen::Init
//!   <module>.rb       one per endpoint (e.g. user_put_id.rb)                        ComatypeGen::UserPutId
//!   all.rb            requires everything
//!
//! The contents of init differ between client and server (ctx and wrapper statuses are server only).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "# frozen_string_literal: true\n# Code generated by comatype generate. DO NOT EDIT.\n\nrequire \"comatype\"\n";

pub fn generate(svc: &Service, role: Role) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut files = vec![
        GenFile { path: "types.rb".into(), content: types_file(svc, &names)? },
        GenFile { path: "init.rb".into(), content: init_file(svc, &names, role)? },
    ];
    let mut requires = vec!["types".to_string(), "init".to_string()];
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let file = snake_module(&ep.module);
        let cls = module_class(&ep.module);
        if file == "types" || file == "init" || file == "all" {
            return Err(format!("{} は Ruby では生成先のファイル名 `{file}` が types / init / all と衝突します（ファイルかディレクトリの名前を変えてください）", ep.file));
        }
        if let Some(prev) = seen.insert(file.clone(), &ep.file) {
            return Err(format!("{} と {prev} が同じ名前 `{cls}` になります", ep.file));
        }
        files.push(GenFile { path: format!("{file}.rb"), content: endpoint_file(svc, &names, ep)? });
        requires.push(file);
    }
    let body: String = requires.iter().map(|r| format!("require_relative \"{r}\"\n")).collect();
    files.push(GenFile {
        path: "all.rb".into(),
        content: format!("# frozen_string_literal: true\n# Code generated by comatype generate. DO NOT EDIT.\n\n{body}"),
    });
    Ok(files)
}

