fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role) -> Result<String, String> {
    let mut py = Py::new(svc, names, "_m.");
    let mut body = String::new();
    let mut wrapper_fields = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        if KEYWORDS.contains(&w.name.as_str()) {
            return Err(format!("wrapper 名 `{}` は Python のキーワードです", w.name));
        }
        let ctx = format!("{}Ctx", cap(&w.name));
        match role {
            Role::Server => {
                body.push_str(&py.model_decl(&ctx, &w.ctx, Mode::Plain)?);
                body.push_str("\n\n");
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let cls = status_class(&mut py, r, svc.cookie.is_some())?;
                    for e in py.extra.drain(..) {
                        body.push_str(&e);
                        body.push_str("\n\n");
                    }
                    body.push_str(&cls);
                    body.push_str("\n\n");
                }
                wrapper_fields.push_str(&format!("{}: _c.ComatypeWrap[{ctx}]\n", w.name));
            }
            Role::Client => wrapper_fields.push_str(&format!("{}: _c.ComatypeWrap[_t.Any]\n", w.name)),
        }
    }
    if wrapper_fields.is_empty() {
        wrapper_fields.push_str("pass\n");
    }
    body.push_str(&format!(
        "@_dc.dataclass(kw_only=True)\nclass Wrappers:\n    \"\"\"init.comat の `wrapper` ごとの実装。{}.init(wrappers=Wrappers(...)) に渡す\"\"\"\n\n{}",
        if role == Role::Server { "s" } else { "c" },
        indent(&wrapper_fields, 1)
    ));
    let imp = imports(&body, ".", &[]);
    // Imports such as dataclass are detected from body
    Ok(format!("{HEADER}# init.comat から生成\n{imp}{body}"))
}

