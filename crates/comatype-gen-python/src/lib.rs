//! Generates Python code from the IR (pydantic v2 models + dataclasses).
//!
//! Output (under `<out>`; `<out>` is a Python package; default `comatype_gen`):
//!   models.py             named types (pydantic models, enums)
//!   comatype_init.py          wrappers, ctx, wrapper statuses
//!   <module>.py           one per endpoint (e.g. user/put__id.py)
//!   __init__.py           in every directory
//!
//! Imports are relative (`from .. import models`), so they do not depend on the name or location of `<out>`.

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "# Code generated by comatype generate. DO NOT EDIT.\n";

pub fn generate(svc: &Service, role: Role) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut files = vec![
        GenFile { path: "models.py".into(), content: models_file(svc, &names)? },
        GenFile { path: "comatype_init.py".into(), content: init_file(svc, &names, role)? },
    ];
    let mut dirs: BTreeSet<String> = BTreeSet::new();
    let mut paths: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let segs: Vec<&str> = ep.module.split('/').collect();
        for s in &segs {
            check_module_segment(s, &ep.file)?;
        }
        if segs[0] == "models" || segs[0] == "comatype_init" {
            return Err(format!(
                "{} は Python では生成先の `{}` が予約済みのモジュール名と衝突します（名前を変えてください）",
                ep.file, segs[0]
            ));
        }
        for i in 1..segs.len() {
            dirs.insert(segs[..i].join("/"));
        }
        if let Some(prev) = paths.insert(ep.module.clone(), &ep.file) {
            return Err(format!("{} と {prev} が同じモジュール名になります", ep.file));
        }
        files.push(GenFile { path: format!("{}.py", ep.module), content: endpoint_file(svc, &names, ep, role)? });
    }
    for d in &dirs {
        if paths.contains_key(d) {
            return Err(format!("`{d}` がモジュール（{}）とディレクトリの両方になります", paths[d]));
        }
    }
    files.push(GenFile { path: "__init__.py".into(), content: HEADER.to_string() });
    for d in dirs {
        files.push(GenFile { path: format!("{d}/__init__.py"), content: HEADER.to_string() });
    }
    Ok(files)
}

// ---- Names ----

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif", "else", "except",
    "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try",
    "while", "with", "yield", "match", "case", "type",
];

/// Names that get a trailing `_` because they would collide with attributes of pydantic's BaseModel
const MODEL_ATTRS: &[&str] = &[
    "json",
    "dict",
    "copy",
    "schema",
    "schema_json",
    "validate",
    "construct",
    "parse_obj",
    "parse_raw",
    "parse_file",
    "from_orm",
    "update_forward_refs",
    "fields",
];

fn check_module_segment(s: &str, file: &str) -> Result<(), String> {
    let ok = !s.is_empty() && !s.chars().next().unwrap().is_ascii_digit() && s.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if !ok {
        return Err(format!("{file}: `{s}` は Python のモジュール名にできません（英数字と `_` だけにしてください）"));
    }
    if KEYWORDS.contains(&s) {
        return Err(format!("{file}: `{s}` は Python のキーワードなので、モジュール名にできません"));
    }
    Ok(())
}

/// `createdAt` / `X-Request-Id` → `created_at` / `x_request_id`
pub fn snake(s: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !out.ends_with('_') && !out.is_empty() {
                out.push('_');
            }
            continue;
        }
        if c.is_ascii_uppercase() && i > 0 {
            let prev_lower = chars[i - 1].is_ascii_lowercase() || chars[i - 1].is_ascii_digit();
            let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
            let prev_upper = chars[i - 1].is_ascii_uppercase();
            if (prev_lower || (prev_upper && next_lower)) && !out.ends_with('_') {
                out.push('_');
            }
        }
        out.push(c.to_ascii_lowercase());
    }
    let out = out.trim_end_matches('_').to_string();
    let out = if out.is_empty() || out.chars().next().unwrap().is_ascii_digit() { format!("f_{out}") } else { out };
    if KEYWORDS.contains(&out.as_str()) || MODEL_ATTRS.contains(&out.as_str()) || out.starts_with("model_") {
        format!("{out}_")
    } else {
        out
    }
}

fn pystr(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn indent(text: &str, n: usize) -> String {
    let pad = "    ".repeat(n);
    text.lines().map(|l| if l.is_empty() { String::new() } else { format!("{pad}{l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

fn uses(body: &str, alias: &str) -> bool {
    body.contains(&format!("{alias}."))
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<&str, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        if let Some(prev) = by_name.insert(&nt.name, id) {
            return Err(format!("型名 `{}` が {prev} と {id} で重複しています（Python では 1 つの models.py にまとめます）", nt.name));
        }
        if KEYWORDS.contains(&nt.name.as_str()) || nt.name.starts_with('_') {
            return Err(format!("型名 `{}` は Python のクラス名にできません", nt.name));
        }
        out.insert(id.clone(), nt.name.clone());
    }
    Ok(out)
}

// ---- Types ----

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// pydantic model (body)
    Json,
    /// path, query, headers. Scalars and their arrays only
    Wire,
    /// dataclass（ctx）
    Plain,
}

struct Py<'a> {
    names: &'a BTreeMap<String, String>,
    enums: BTreeSet<&'a str>,
    /// Prefix for referring to a models type from other modules (`_m.`). Empty inside models.py
    prefix: &'a str,
    /// Named classes created along the way, at module level
    extra: Vec<String>,
    used: BTreeSet<String>,
}

#[derive(Clone)]
struct PyTy {
    ty: String,
    /// Can be `None` (`T | null`)
    nullable: bool,
}

impl<'a> Py<'a> {
    fn new(svc: &'a Service, names: &'a BTreeMap<String, String>, prefix: &'a str) -> Self {
        let enums = svc.types.iter().filter(|(_, t)| matches!(t.def, TypeDef::Enum { .. })).map(|(id, _)| id.as_str()).collect();
        Py { names, enums, prefix, extra: vec![], used: BTreeSet::new() }
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    fn ty(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<PyTy, String> {
        let plain = |s: &str| PyTy { ty: s.to_string(), nullable: false };
        match t {
            Type::Scalar { name, constraint } => {
                let base = match name.as_str() {
                    "string" => "str",
                    "bool" => "bool",
                    "int" => "int",
                    "email" => "_s.Email",
                    "phone" => "_s.Phone",
                    "uuid" => "_s.Uuid",
                    "uuidv4" => "_s.Uuidv4",
                    "uuidv7" => "_s.Uuidv7",
                    "date" => "_s.Date",
                    "datetime" => "_s.DateTime",
                    "time" => "_s.Time",
                    "int64" => "_s.Int64",
                    "decimal" => "_s.Decimal",
                    "url" => "_s.Url",
                    "bytes" => "_s.Bytes",
                    _ => "_t.Any",
                };
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                let args = match constraint {
                    None => vec![],
                    Some(Constraint::Range { min, max }) => {
                        let (lo, hi) = if name == "string" { ("min_length", "max_length") } else { ("ge", "le") };
                        let mut v = vec![];
                        if let Some(m) = min {
                            v.push(format!("{lo}={m}"));
                        }
                        if let Some(m) = max {
                            v.push(format!("{hi}={m}"));
                        }
                        v
                    }
                    Some(Constraint::Pattern { value }) => vec![format!("pattern={}", pystr(value))],
                };
                Ok(plain(&if args.is_empty() { base.to_string() } else { format!("_t.Annotated[{base}, _p.Field({})]", args.join(", ")) }))
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.enums.contains(id.as_str()) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(plain(&format!("{}{}", self.prefix, name)))
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.model_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(plain(&name))
            }
            Type::Array { item } => {
                let inner = self.ty(item, &format!("{hint}Item"), mode)?;
                let t = if inner.nullable { format!("_t.Optional[{}]", inner.ty) } else { inner.ty };
                Ok(plain(&format!("list[{t}]")))
            }
            Type::Union { variants }
                if variants.iter().all(|v| matches!(v, Type::Literal { .. } | Type::Null))
                    && variants.iter().any(|v| matches!(v, Type::Literal { .. })) =>
            {
                // A union of string literals is merged into a single Literal
                let lits: Vec<String> =
                    variants.iter().filter_map(|v| if let Type::Literal { value } = v { Some(pystr(value)) } else { None }).collect();
                Ok(PyTy { ty: format!("_t.Literal[{}]", lits.join(", ")), nullable: variants.iter().any(|v| matches!(v, Type::Null)) })
            }
            Type::Union { variants } => {
                let mut nullable = false;
                let mut parts = Vec::new();
                for v in variants {
                    if matches!(v, Type::Null) {
                        nullable = true;
                        continue;
                    }
                    let p = self.ty(v, hint, mode)?;
                    nullable |= p.nullable;
                    parts.push(p.ty);
                }
                let ty = if parts.len() == 1 { parts.remove(0) } else { format!("_t.Union[{}]", parts.join(", ")) };
                Ok(PyTy { ty, nullable })
            }
            Type::Literal { value } => Ok(plain(&format!("_t.Literal[{}]", pystr(value)))),
            Type::Null => Ok(PyTy { ty: "None".into(), nullable: true }),
        }
    }

    /// Field declaration (`name: type = ...`)
    fn field(&mut self, owner: &str, f: &Field, mode: Mode, seen: &mut BTreeSet<String>) -> Result<String, String> {
        let name = snake(&f.name);
        if !seen.insert(name.clone()) {
            return Err(format!("{owner}: フィールド名 {name} が重複します（{}）", f.name));
        }
        let hint = format!("{owner}{}", f.name.split(|c: char| !c.is_ascii_alphanumeric()).map(cap).collect::<String>());
        let g = self.ty(&f.ty, &hint, mode).map_err(|e| format!("{owner}.{}: {e}", f.name))?;
        if mode == Mode::Plain {
            let t = if g.nullable { format!("_t.Optional[{}]", g.ty) } else { g.ty };
            return Ok(format!("{name}: {t}\n"));
        }
        let optional = f.optional || (mode == Mode::Wire && g.nullable);
        let t = if optional || g.nullable { format!("_t.Optional[{}]", g.ty) } else { g.ty.clone() };
        let mut args = Vec::new();
        if optional {
            args.push("default=None".to_string());
        }
        if name != f.name {
            args.push(format!("alias={}", pystr(&f.name)));
        }
        if optional {
            args.push("json_schema_extra={\"omit_none\": True}".to_string());
        }
        Ok(if args.is_empty() { format!("{name}: {t}\n") } else { format!("{name}: {t} = _p.Field({})\n", args.join(", ")) })
    }

    fn model_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        self.model_decl_with(name, name, fields, mode)
    }

    /// `owner` is the base of the nested class name (made not to collide at module level, like `S200Res`)
    fn model_decl_with(&mut self, name: &str, owner: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        self.used.insert(owner.to_string());
        let mut seen = BTreeSet::new();
        let mut body = String::new();
        if mode == Mode::Plain {
            for f in fields {
                body.push_str(&self.field(owner, f, mode, &mut seen)?);
            }
            if fields.is_empty() {
                body.push_str("pass\n");
            }
            return Ok(format!("@_dc.dataclass\nclass {name}:\n{}", indent(&body, 1)));
        }
        body.push_str("model_config = _p.ConfigDict(populate_by_name=True)\n");
        for f in fields {
            body.push_str(&self.field(owner, f, mode, &mut seen)?);
        }
        Ok(format!("class {name}(_p.BaseModel):\n{}", indent(&body, 1)))
    }

    /// Declaration of an alias or a class (for objects). Returns (declaration, type expression)
    fn named(&mut self, name: &str, t: &Type, mode: Mode) -> Result<String, String> {
        self.used.insert(name.to_string());
        let decl = match t {
            Type::Object { fields } => self.model_decl(name, fields, mode)?,
            _ => {
                let g = self.ty(t, name, mode)?;
                let ty = if g.nullable { format!("_t.Optional[{}]", g.ty) } else { g.ty };
                format!("{name}: _t.TypeAlias = {ty}\n")
            }
        };
        let mut out = String::new();
        for e in self.extra.drain(..) {
            out.push_str(&e);
            out.push_str("\n\n");
        }
        out.push_str(&decl);
        Ok(out)
    }
}

fn cap(w: &str) -> String {
    let mut cs = w.chars();
    cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
}

// ---- import ----

fn imports(body: &str, dots: &str, extra: &[&str]) -> String {
    let mut s = String::from("from __future__ import annotations\n\n");
    for (alias, line) in [
        ("_dc", "import dataclasses as _dc"),
        ("_en", "import enum as _en"),
        ("_t", "import typing as _t"),
        ("_p", "import pydantic as _p"),
    ] {
        if uses(body, alias) {
            s.push_str(line);
            s.push('\n');
        }
    }
    let mut comatype = Vec::new();
    if uses(body, "_c") {
        comatype.push("import comatype as _c".to_string());
    }
    if uses(body, "_s") {
        comatype.push("from comatype import scalars as _s".to_string());
    }
    if !comatype.is_empty() {
        s.push('\n');
        s.push_str(&comatype.join("\n"));
        s.push('\n');
    }
    let mut rel = Vec::new();
    if uses(body, "_m") {
        rel.push(format!("from {dots} import models as _m"));
    }
    if uses(body, "_i") {
        rel.push(format!("from {dots} import comatype_init as _i"));
    }
    rel.extend(extra.iter().map(|s| s.to_string()));
    if !rel.is_empty() {
        s.push('\n');
        s.push_str(&rel.join("\n"));
        s.push('\n');
    }
    s.push_str("\n\n");
    s
}

// ---- models.py ----

fn models_file(svc: &Service, names: &BTreeMap<String, String>) -> Result<String, String> {
    let mut py = Py::new(svc, names, "");
    for n in names.values() {
        py.used.insert(n.clone());
    }
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = py.model_decl(name, fields, Mode::Json)?;
                for e in py.extra.drain(..) {
                    body.push_str(&e);
                    body.push_str("\n\n");
                }
                body.push_str(&decl);
                body.push_str("\n\n");
            }
            TypeDef::Enum { values } => {
                let mut members = String::new();
                let mut seen = BTreeSet::new();
                for v in values {
                    let mut m = snake(v);
                    if !seen.insert(m.clone()) {
                        m = format!("{m}_{}", seen.len());
                        seen.insert(m.clone());
                    }
                    members.push_str(&format!("{m} = {}\n", pystr(v)));
                }
                body.push_str(&format!("class {name}(str, _en.Enum):\n{}\n\n", indent(&members, 1)));
            }
        }
    }
    let imp = imports(&body, ".", &[]);
    Ok(format!("{HEADER}{imp}{}", body.trim_end().to_string() + "\n"))
}

// ---- Statuses ----

/// The `S200` class (and its body / header types `S200Res` / `S200Headers`). `cookie`: accepts `cookie=`
/// (on the server, when cookie is on and init.comat has a declaration)
///
/// The body and header types live at module level (use `S200Res` in type annotations). `S200.Res` / `S200.Headers` inside the class are
/// aliases that let you build `S200.Res(...)` at runtime (mypy does not treat aliases inside a class as types)
fn status_class(py: &mut Py, r: &Response, cookie: bool) -> Result<String, String> {
    let c = r.status;
    let kind = if (200..300).contains(&c) { "data" } else { "error" };
    let name = format!("S{c}");
    let (res, hdr) = (format!("S{c}Res"), format!("S{c}Headers"));
    let mut top = String::new();
    let mut aliases = String::new();
    let mut fields = String::new();
    let mut body_expr = "None".to_string();

    if let Some(b) = &r.body {
        top.push_str(&py.named(&res, b, Mode::Json).map_err(|e| format!("{name}: {e}"))?);
        top.push_str("\n\n");
        aliases.push_str(&format!("Res = {res}\n"));
        body_expr = res.clone();
        fields.push_str(&format!("{kind}: {res} | None = None\n"));
    }
    let mut headers_expr = "None".to_string();
    if !r.headers.is_empty() {
        top.push_str(&py.model_decl(&hdr, &r.headers, Mode::Wire).map_err(|e| format!("{name} のヘッダ: {e}"))?);
        top.push_str("\n\n");
        aliases.push_str(&format!("Headers = {hdr}\n"));
        headers_expr = hdr.clone();
        if r.headers.iter().any(|h| !h.optional) {
            fields.push_str(&format!("headers: {hdr}\n"));
        } else {
            fields.push_str(&format!("headers: {hdr} | None = None\n"));
        }
    }
    if cookie {
        fields.push_str("cookie: _c.Cookie | str | None = None\n");
    }
    let mut body = String::new();
    body.push_str(&format!("\"\"\"ステータス {c}\"\"\"\n\n"));
    body.push_str(&format!("status: _t.Literal[{c}] = _dc.field(default={c}, init=False)\n"));
    body.push_str(&aliases);
    body.push_str(&format!("_kind: _t.ClassVar[_t.Literal[\"data\", \"error\"]] = \"{kind}\"\n_body: _t.ClassVar[_t.Any] = {body_expr}\n_headers: _t.ClassVar[_t.Any] = {headers_expr}\n"));
    body.push_str(&fields);
    Ok(format!("{top}@_dc.dataclass(kw_only=True)\nclass {name}(_c.Status):\n{}", indent(&body, 1)))
}

// ---- Endpoints ----

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role) -> Result<String, String> {
    let ctx_err = |e: String| format!("{}: {e}", ep.file);
    let mut py = Py::new(svc, names, "_m.");
    let mut body = String::new();
    let push = |s: String, body: &mut String| {
        body.push_str(&s);
        body.push_str("\n\n");
    };

    // Request
    let mut req_fields: Vec<(String, String, bool)> = Vec::new(); // (name, type, has a default)
    let all_optional = |fs: &[Field]| fs.iter().all(|f| f.optional);
    if !ep.params.is_empty() {
        push(py.model_decl("Params", &ep.params, Mode::Wire).map_err(ctx_err)?, &mut body);
        req_fields.push(("params".into(), "Params".into(), false));
    }
    if !ep.search.is_empty() {
        push(py.model_decl("Search", &ep.search, Mode::Wire).map_err(ctx_err)?, &mut body);
        req_fields.push(("search".into(), "Search".into(), all_optional(&ep.search)));
    }
    if let Some(b) = &ep.body {
        push(py.named("Body", b, Mode::Json).map_err(ctx_err)?, &mut body);
        req_fields.push(("body".into(), "Body".into(), false));
    }
    if !ep.request_headers.is_empty() {
        push(py.model_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx_err)?, &mut body);
        req_fields.push(("headers".into(), "RequestHeaders".into(), all_optional(&ep.request_headers)));
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let bases: Vec<String> = ctx_wrappers.iter().map(|w| format!("_i.{}Ctx", cap(&w.name))).collect();
        push(
            format!(
                "class Ctx{}:\n    \"\"\"有効なラッパーが足した値（req.ctx.user のように読む）\"\"\"\n",
                if bases.is_empty() { String::new() } else { format!("({})", bases.join(", ")) }
            ),
            &mut body,
        );
    }
    let mut rq = String::from("@_dc.dataclass(kw_only=True)\nclass Request:\n    \"\"\"リクエスト全体\"\"\"\n\n");
    for (n, t, has_default) in &req_fields {
        // Fields with a default use dataclass field(default_factory=...)
        rq.push_str(&if *has_default { format!("    {n}: {t} = _dc.field(default_factory={t})\n") } else { format!("    {n}: {t}\n") });
    }
    if role == Role::Server {
        rq.push_str("    ctx: Ctx\n");
    }
    if req_fields.is_empty() && role == Role::Client {
        rq.push_str("    pass\n");
    }
    push(rq.trim_end().to_string(), &mut body);

    // Response
    let cookie = role == Role::Server && ep.cookie && svc.cookie.is_some();
    for r in &ep.responses {
        let cls = status_class(&mut py, r, cookie).map_err(|e| format!("{}: {e}", ep.file))?;
        for e in py.extra.drain(..) {
            push(e, &mut body);
        }
        push(cls, &mut body);
    }
    let resp = if ep.responses.is_empty() {
        "_t.NoReturn".to_string()
    } else {
        ep.responses.iter().map(|r| format!("S{}", r.status)).collect::<Vec<_>>().join(" | ")
    };
    push(format!("Response: _t.TypeAlias = {resp}"), &mut body);

    // Descriptor
    let arg_form = if !ep.params.is_empty() || !ep.search.is_empty() {
        "request"
    } else if ep.body.is_some() {
        "body"
    } else {
        "none"
    };
    let arg_ty = match arg_form {
        "request" => "Request",
        "body" => "Body",
        _ => "_c.NoArg",
    };
    let opt = |present: bool, n: &str| if present { n.to_string() } else { "None".to_string() };
    let mut d = format!(
        "path: _c.Endpoint[{arg_ty}, Request, Response] = _c.Endpoint(\n    method={},\n    path={},\n    module={},\n",
        pystr(&ep.method),
        pystr(&ep.path),
        pystr(&ep.module)
    );
    if let Some(u) = &svc.base_url {
        d.push_str(&format!("    base_url={},\n", pystr(u)));
    }
    d.push_str(&format!("    wraps=({}),\n", ep.wraps.iter().map(|w| format!("{},", pystr(w))).collect::<Vec<_>>().join(" ")));
    d.push_str(&format!("    cookie={},\n", if ep.cookie { "True" } else { "False" }));
    if let Some(c) = &ep.cache {
        use comatype_core::ast::CacheMode;
        let (mode, ttl) = match c {
            CacheMode::Off => ("off", 0),
            CacheMode::Memory { ttl_ms } => ("memory", *ttl_ms),
            CacheMode::Cookie { ttl_ms } => ("cookie", *ttl_ms),
        };
        d.push_str(&format!("    cache=_c.CacheSpec(\"{mode}\", {ttl}),\n"));
        let names: Vec<String> = ep.request_headers.iter().map(|h| format!("{:?}", h.name)).collect();
        d.push_str(&format!("    cache_headers=({}),\n", if names.len() == 1 { format!("{},", names[0]) } else { names.join(", ") }));
    }
    if let (Some(c), true) = (&svc.cookie, ep.cookie) {
        d.push_str(&format!("    cookie_def={},\n", cookie_def_py(c)));
    }
    d.push_str(&format!(
        "    params={},\n    search={},\n    body={},\n    request_headers={},\n    responses=({}),\n    arg_form={},\n    request_cls=Request,\n",
        opt(!ep.params.is_empty(), "Params"),
        opt(!ep.search.is_empty(), "Search"),
        opt(ep.body.is_some(), "Body"),
        opt(!ep.request_headers.is_empty(), "RequestHeaders"),
        ep.responses.iter().map(|r| format!("S{},", r.status)).collect::<Vec<_>>().join(" "),
        pystr(arg_form)
    ));
    if role == Role::Server {
        d.push_str("    ctx_cls=Ctx,\n");
    }
    d.push_str(")\n");
    body.push_str(&d);

    let dots = ".".repeat(ep.module.matches('/').count() + 1);
    let imp = imports(&body, &dots, &[]);
    Ok(format!("{HEADER}# {} — {} {}\n{imp}{body}", ep.file, ep.method.to_uppercase(), ep.path))
}

fn cookie_def_py(c: &CookieDef) -> String {
    let mut parts = vec![format!("name={}", pystr(&c.name))];
    for (k, f) in [("httpOnly", "http_only"), ("secure", "secure")] {
        if c.settings.get(k).map(String::as_str) == Some("true") {
            parts.push(format!("{f}=True"));
        }
    }
    for (k, f) in [("sameSite", "same_site"), ("path", "path"), ("domain", "domain")] {
        if let Some(v) = c.settings.get(k) {
            parts.push(format!("{f}={}", pystr(v)));
        }
    }
    if let Some(v) = c.settings.get("maxAge") {
        parts.push(format!("max_age={v}"));
    }
    format!("_c.CookieDef({})", parts.join(", "))
}

