fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role, package: &str) -> Result<String, String> {
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut comps = Vec::new();
    let mut entries = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let (p, f) = (pascal(&w.name), camel(&w.name));
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("/** ラッパー {} が足す値（ハンドラの req.ctx().{f}()） */\n", w.name));
                body.push_str(&g.record_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            let label = format!("S{c}Res");
                            let (inner, _) = strip_null(b);
                            let ty = if let Some(decl) = g.named_object(&label, b)? {
                                body.push_str(&decl);
                                body.push('\n');
                                label.clone()
                            } else {
                                g.jty(inner, &label, Mode::Json, true)?
                            };
                            let v = g.vstmts(b, "body", "\"\"", 0);
                            let enc = g.enc(b, "body", 0);
                            body.push_str(&format!(
                                "/** ラッパー {} が返せるステータス {c} のレスポンス */\npublic static comatype.RawResponse s{c}({ty} body) {{\n{v}comatype.RawResponse r = new comatype.RawResponse({c});\nr.body = comatype.Codec.encodeValue({enc});\nr.headers.set(\"Content-Type\", \"application/json\");\nreturn r;\n}}\n\n",
                                w.name
                            ));
                        }
                        None => body.push_str(&format!("/** ラッパー {} が返せるステータス {c} のレスポンス */\npublic static comatype.RawResponse s{c}() {{\nreturn new comatype.RawResponse({c});\n}}\n\n", w.name)),
                    }
                }
                comps.push(format!("comatype.S.ComatypeWrap<{ctx_name}> {f}"));
                entries.push_str(&format!("m.put({}, comatype.S.adapt({}, {f}));\n", jstr(&w.name), jstr(&w.name)));
            }
            Role::Client => {
                comps.push(format!("comatype.C.ComatypeWrap {f}"));
                entries.push_str(&format!("m.put({}, {f});\n", jstr(&w.name)));
            }
        }
    }
    let (set, wrap_ty) = match role {
        Role::Server => ("S", "comatype.S.ServerWrap"),
        Role::Client => ("C", "comatype.C.ComatypeWrap"),
    };
    body.push_str(&format!(
        "/** init.comat の `wrapper` ごとの実装。{set}.init に渡す */\npublic record Wrappers({}) implements comatype.{set}.WrapperSet {{\n    @Override\n    public java.util.Map<String, {wrap_ty}> comatypeWrappers() {{\n        java.util.Map<String, {wrap_ty}> m = new java.util.LinkedHashMap<>();\n{}        return m;\n    }}\n}}\n",
        comps.join(", "),
        indent(&indent(&entries))
    ));
    Ok(format!("{HEADER}package {package};\n\n/** init.comat から生成 */\npublic final class Init {{\n    private Init() {{}}\n\n{}}}\n", indent(body.trim_end())))
}

