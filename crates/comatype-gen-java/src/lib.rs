fn cookie_def_java(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("null".to_string(), jstr);
    format!(
        "new comatype.CookieDef({}, {}, {}, {}, {}, {}, {})",
        jstr(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("null".to_string(), |v| format!("{v}L")),
    )
}

/// Static methods that read and write the body (JSON). `T` is a Java type
fn body_codec(g: &mut Gen, label: &str, t: &Type, ty: &str) -> String {
    let v = g.vstmts(t, "v", "\"\"", 0);
    let enc = g.enc(t, "v", 0);
    let dec = match t {
        Type::Object { .. } => format!("{ty}::decode"),
        _ => g.dec(t),
    };
    format!(
        "private static byte[] encode{label}({ty} v) {{\n{v}return comatype.Codec.encodeValue({enc});\n}}\n\n\
         private static {ty} decode{label}(byte[] b, String path) {{\nreturn comatype.Codec.decode(b, path, {dec});\n}}\n\n"
    )
}

fn wire_pairs(fields: &[Field], var: &str) -> String {
    fields.iter().map(|f| format!("{}, {var}.{}()", jstr(&f.name), camel(&f.name))).collect::<Vec<_>>().join(", ")
}

/// Expression that reads the header / params / search records
fn wire_build(name: &str, fields: &[Field], g: &Gen, values: &str, split: bool) -> String {
    let args: Vec<String> = fields
        .iter()
        .map(|f| {
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let vals = values.replace("{}", &jstr(&f.name));
            match inner {
                Type::Array { item } => format!("comatype.Wire.readList({vals}, {}, {split}, {opt}, {})", jstr(&f.name), g.wdec(item)),
                _ if opt => format!("comatype.Wire.readOpt({vals}, {}, {split}, {})", jstr(&f.name), g.wdec(inner)),
                _ => format!("comatype.Wire.read({vals}, {}, {split}, {})", jstr(&f.name), g.wdec(inner)),
            }
        })
        .collect();
    format!("new {name}({})", args.join(", "))
}

/// The `cache` setting (GET / QUERY only)
fn cache_java(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let (mode, ttl) = match &ep.cache {
        None => return String::new(),
        Some(CacheMode::Off) => ("off", 0),
        Some(CacheMode::Memory { ttl_ms }) => ("memory", *ttl_ms),
        Some(CacheMode::Cookie { ttl_ms }) => ("cookie", *ttl_ms),
    };
    let names: Vec<String> = ep.request_headers.iter().map(|h| jstr(&h.name)).collect();
    format!(".cache(new comatype.CacheSpec(\"{mode}\", {ttl}L), java.util.List.of({}))", names.join(", "))
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role, package: &str) -> Result<String, String> {
    let class = module_class(&ep.module);
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();
    let mut codecs = String::new();
    let has_req_headers = !ep.request_headers.is_empty();

    if !ep.params.is_empty() {
        body.push_str(&g.record_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    if !ep.search.is_empty() {
        body.push_str(&g.record_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let mut body_ty = String::new();
    if let Some(b) = &ep.body {
        g.used_names.insert("Body".into());
        if let Some(decl) = g.named_object("Body", b).map_err(ctx)? {
            body.push_str(&decl);
            body.push('\n');
            body_ty = "Body".into();
        } else {
            let (inner, nullable) = strip_null(b);
            body_ty = g.jty(inner, "Body", Mode::Json, true).map_err(ctx)?;
            let _ = nullable;
        }
        codecs.push_str(&body_codec(&mut g, "Body", b, &body_ty));
    }
    if has_req_headers {
        body.push_str(&g.record_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let comps: Vec<String> = ctx_wrappers.iter().map(|w| format!("Init.{}Ctx {}", pascal(&w.name), camel(&w.name))).collect();
        body.push_str(&format!("/** 有効なラッパーが足した値 */\npublic record Ctx({}) {{}}\n\n", comps.join(", ")));
    }
    // Whole request
    let mut req_comps: Vec<(&str, String)> = Vec::new();
    if !ep.params.is_empty() {
        req_comps.push(("params", "Params".into()));
    }
    if !ep.search.is_empty() {
        req_comps.push(("search", "Search".into()));
    }
    if has_req_headers {
        req_comps.push(("headers", "RequestHeaders".into()));
    }
    if ep.body.is_some() {
        req_comps.push(("body", body_ty.clone()));
    }
    if role == Role::Server {
        req_comps.push(("ctx", "Ctx".into()));
    }
    let has = |n: &str| req_comps.iter().any(|(f, _)| *f == n);
    body.push_str(&format!(
        "/** リクエスト全体 */\npublic record Request({}) {{}}\n\n",
        req_comps.iter().map(|(n, t)| format!("{t} {n}")).collect::<Vec<_>>().join(", ")
    ));

    // Response
    let cookie = ep.cookie && svc.cookie.is_some();
    let mut variants = String::new();
    let mut permits = Vec::new();
    for r in &ep.responses {
        let c = r.status;
        let mut comps = Vec::new();
        if let Some(b) = &r.body {
            let label = format!("S{c}Res");
            let (inner, _) = strip_null(b);
            let ty = if let Some(decl) = g.named_object(&label, b).map_err(ctx)? {
                body.push_str(&decl);
                body.push('\n');
                label.clone()
            } else {
                g.jty(inner, &label, Mode::Json, true).map_err(ctx)?
            };
            codecs.push_str(&body_codec(&mut g, &format!("S{c}"), b, &ty));
            comps.push(format!("{ty} body"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.record_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            body.push('\n');
            comps.push(format!("S{c}Headers headers"));
        }
        variants.push_str(&format!("public record S{c}({}) implements Response {{}}\n", comps.join(", ")));
        permits.push(format!("S{c}"));
    }
    body.push_str(&format!("/** 全ステータスのレスポンス */\npublic sealed interface Response permits {} {{}}\n\n{variants}\n", permits.join(", ")));

    // Descriptor
    let arg = if has("params") || has("search") || has("headers") {
        "Request".to_string()
    } else if ep.body.is_some() {
        body_ty.clone()
    } else {
        "comatype.NoArg".to_string()
    };
    let res_ty = if role == Role::Server && cookie { "comatype.S.Reply<Response>".to_string() } else { "Response".to_string() };
    let wraps = if ep.wraps.is_empty() { "java.util.List.of()".to_string() } else { format!("java.util.List.of({})", ep.wraps.iter().map(|w| jstr(w)).collect::<Vec<_>>().join(", ")) };
    let base = svc.base_url.as_ref().map_or("null".to_string(), |u| jstr(u));
    let cd = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_java(c),
        _ => "null".to_string(),
    };
    match role {
        Role::Client => body.push_str(&format!(
            "/** path とメソッド */\npublic static final comatype.Endpoint<{arg}, Void, Response> ENDPOINT = comatype.Endpoint.client(\n{}, {}, {}, {base}, {wraps}, {}, {cd},\n{class}::buildRequest, {class}::parseResponse){};\n\n",
            jstr(&ep.method),
            jstr(&ep.path),
            jstr(&ep.module),
            ep.cookie,
            cache_java(ep)
        )),
        Role::Server => body.push_str(&format!(
            "/** path とメソッド */\npublic static final comatype.Endpoint<Void, Request, {res_ty}> ENDPOINT = comatype.Endpoint.server(\n{}, {}, {}, {base}, {wraps}, {}, {cd},\n{class}::parseRequest, {class}::buildResponse){};\n\n",
            jstr(&ep.method),
            jstr(&ep.path),
            jstr(&ep.module),
            ep.cookie,
            cache_java(ep)
        )),
    }
    body.push_str(&codecs);

    match role {
        Role::Client => {
            let mut f = format!("private static comatype.RawRequest buildRequest({arg} arg) {{\ncomatype.RawRequest raw = new comatype.RawRequest({}, {});\n", jstr(&ep.method), jstr(&ep.path));
            if arg == "Request" {
                if has("params") {
                    f.push_str(&format!("arg.params().validate(\"\");\ncomatype.Wire.fillPath(raw, {});\n", wire_pairs(&ep.params, "arg.params()")));
                }
                if has("search") {
                    f.push_str(&format!("arg.search().validate(\"\");\ncomatype.Wire.addQuery(raw, {});\n", wire_pairs(&ep.search, "arg.search()")));
                }
                if has("headers") {
                    f.push_str(&format!("arg.headers().validate(\"\");\ncomatype.Wire.setHeaders(raw.headers, {});\n", wire_pairs(&ep.request_headers, "arg.headers()")));
                }
                if has("body") {
                    f.push_str("raw.body = encodeBody(arg.body());\nraw.headers.set(\"Content-Type\", \"application/json\");\n");
                }
            } else if arg != "comatype.NoArg" {
                f.push_str("raw.body = encodeBody(arg);\nraw.headers.set(\"Content-Type\", \"application/json\");\n");
            }
            f.push_str("return raw;\n}\n\n");
            body.push_str(&f);

            let mut p = String::from("private static Response parseResponse(comatype.RawResponse raw) {\nswitch (raw.status) {\n");
            for r in &ep.responses {
                let c = r.status;
                p.push_str(&format!("case {c}: {{\n"));
                let mut args = Vec::new();
                if r.body.is_some() {
                    p.push_str(&format!("if (raw.body.length == 0) throw new comatype.ValidationException(\"body\", \"必須です\");\nvar body = decodeS{c}(raw.body, \"body\");\n"));
                    args.push("body");
                }
                if !r.headers.is_empty() {
                    p.push_str(&format!(
                        "var headers = {};\nheaders.validate(\"\");\n",
                        wire_build(&format!("S{c}Headers"), &r.headers, &g, "comatype.Wire.headerValues(raw.headers, {})", true)
                    ));
                    args.push("headers");
                }
                p.push_str(&format!("return new S{c}({});\n}}\n", args.join(", ")));
            }
            p.push_str("default:\nthrow new comatype.ComatypeException.UnexpectedStatus(raw.status, raw.body);\n}\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            let mut f = String::from("private static Request parseRequest(comatype.RawRequest raw) {\n");
            let mut inits = Vec::new();
            if has("params") {
                f.push_str(&format!("var params = {};\nparams.validate(\"\");\n", wire_build("Params", &ep.params, &g, "comatype.Wire.paramValues(raw, {})", false)));
                inits.push("params");
            }
            if has("search") {
                f.push_str(&format!("var search = {};\nsearch.validate(\"\");\n", wire_build("Search", &ep.search, &g, "comatype.Wire.queryValues(raw, {})", false)));
                inits.push("search");
            }
            if has("headers") {
                f.push_str(&format!(
                    "var headers = {};\nheaders.validate(\"\");\n",
                    wire_build("RequestHeaders", &ep.request_headers, &g, "comatype.Wire.headerValues(raw.headers, {})", true)
                ));
                inits.push("headers");
            }
            if has("body") {
                f.push_str("if (raw.body.length == 0) throw new comatype.ValidationException(\"body\", \"必須です\");\nvar body = decodeBody(raw.body, \"body\");\n");
                inits.push("body");
            }
            if has("ctx") {
                let cs: Vec<String> = ctx_wrappers
                    .iter()
                    .map(|w| format!("comatype.S.ctx(raw, {}, Init.{}Ctx.class)", jstr(&w.name), pascal(&w.name)))
                    .collect();
                f.push_str(&format!("var ctx = new Ctx({});\n", cs.join(", ")));
                inits.push("ctx");
            }
            f.push_str(&format!("return new Request({});\n}}\n\n", inits.join(", ")));
            body.push_str(&f);

            let mut b = format!("private static comatype.RawResponse buildResponse({res_ty} reply) {{\n");
            if cookie {
                b.push_str("Response res = reply.response();\n");
            } else {
                b.push_str("Response res = reply;\n");
            }
            b.push_str("comatype.RawResponse out;\n");
            for (i, r) in ep.responses.iter().enumerate() {
                let c = r.status;
                let kw = if i == 0 { "if" } else { "} else if" };
                b.push_str(&format!("{kw} (res instanceof S{c} r) {{\nout = new comatype.RawResponse({c});\n"));
                if r.body.is_some() {
                    b.push_str(&format!("out.body = encodeS{c}(r.body());\nout.headers.set(\"Content-Type\", \"application/json\");\n"));
                }
                if !r.headers.is_empty() {
                    b.push_str(&format!("r.headers().validate(\"\");\ncomatype.Wire.setHeaders(out.headers, {});\n", wire_pairs(&r.headers, "r.headers()")));
                }
            }
            b.push_str("} else {\nthrow new comatype.ComatypeException(\"宣言されていないレスポンスです: \" + res);\n}\n");
            if cookie {
                b.push_str("comatype.S.applyCookie(out, ENDPOINT.cookieDef, reply.cookie());\n");
            }
            b.push_str("return out;\n}\n");
            body.push_str(&b);
        }
    }

    Ok(format!(
        "{HEADER}package {package};\n\n/** {} — {} {} */\npublic final class {class} {{\n    private {class}() {{}}\n\n{}}}\n",
        ep.file,
        ep.method.to_uppercase(),
        ep.path,
        indent(body.trim_end())
    ))
}

