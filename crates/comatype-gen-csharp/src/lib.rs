//! Generates C# code from the IR (sealed records; the runtime is the `Comatype` package).
//!
//! Output (under `<out>`; default `ComatypeGen`):
//!   Types.cs          named types (records, enums)
//!   Init.cs           wrappers, ctx, wrapper statuses
//!   <Module>.cs       one per endpoint (e.g. UserPutId.cs; module names are PascalCase)
//!
//! The contents of Init and the endpoints differ between client and server (matching the runtime's C / S).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "// <auto-generated>\n// Code generated by comatype generate. DO NOT EDIT.\n// </auto-generated>\n#nullable enable\n";

pub fn generate(svc: &Service, role: Role, namespace: &str) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut files = vec![
        GenFile { path: "Types.cs".into(), content: types_file(svc, &names, namespace)? },
        GenFile { path: "Init.cs".into(), content: init_file(svc, &names, role, namespace)? },
    ];
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let m = module_class(&ep.module);
        if m == "Types" || m == "Init" {
            return Err(format!("{}: the class name `{m}` clashes with Types / Init (rename the file or the directory)", ep.file));
        }
        if let Some(prev) = seen.insert(m.clone(), &ep.file) {
            return Err(format!("{} and {prev} produce the same class name `{m}`", ep.file));
        }
        files.push(GenFile { path: format!("{m}.cs"), content: endpoint_file(svc, &names, ep, role, namespace)? });
    }
    for f in &mut files {
        f.content = reindent(&f.content);
    }
    Ok(files)
}

/// Fixes indentation by brace depth (the generated fragments carry no indentation for nesting)
fn reindent(code: &str) -> String {
    let mut depth: i32 = 0;
    let mut out = String::new();
    for line in code.lines() {
        let t = line.trim();
        if t.is_empty() {
            out.push('\n');
            continue;
        }
        let opens = t.matches('{').count() as i32;
        let closes = t.matches('}').count() as i32;
        let leading = t.chars().take_while(|c| *c == '}' || *c == ')').filter(|c| *c == '}').count() as i32;
        let d = (depth - leading).max(0);
        out.push_str(&"    ".repeat(d as usize));
        out.push_str(t);
        out.push('\n');
        depth = (depth + opens - closes).max(0);
    }
    out
}

// ---- Names ----

/// Members every record (or object) has: a property with one of these names gets a trailing `_`
const RESERVED_MEMBERS: &[&str] = &[
    "Equals",
    "GetHashCode",
    "ToString",
    "GetType",
    "EqualityContract",
    "PrintMembers",
    "Deconstruct",
    "MemberwiseClone",
    "Finalize",
    "Validate",
    "Encode",
    "Decode",
    "Empty",
];

pub fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            continue;
        }
        let prev_lower = i > 0 && chars[i - 1].is_ascii_lowercase();
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
        let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
        if c.is_ascii_uppercase() && !cur.is_empty() && (prev_lower || (prev_upper && next_lower)) {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

fn cap(w: &str) -> String {
    let mut cs = w.chars();
    cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
}

/// PascalCase (type names, enum members)
pub fn pascal(s: &str) -> String {
    let out: String = words(s).iter().map(|w| cap(&w.to_ascii_lowercase())).collect::<Vec<_>>().concat();
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("V{out}")
    } else {
        out
    }
}

/// `user/put__id` → `UserPutId`
pub fn module_class(module: &str) -> String {
    let out: String = module.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()).map(cap).collect();
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("M{out}")
    } else {
        out
    }
}

/// Property name of a field of the record `owner` (a member cannot have the name of its enclosing type)
pub fn prop(field: &str, owner: &str) -> String {
    let p = pascal(field);
    if p == owner || RESERVED_MEMBERS.contains(&p.as_str()) {
        format!("{p}_")
    } else {
        p
    }
}

fn cstr(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '\n' => o.push_str("\\n"),
            '\r' => o.push_str("\\r"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

// ---- Types ----

struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    /// Prefix when referring to a type in another class (`Types.`). Empty inside Types
    prefix: &'a str,
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// Body (JSON)
    Json,
    /// path, query, headers. Scalars and their arrays only
    Wire,
    /// ctx
    Plain,
}

fn strip_null(t: &Type) -> (&Type, bool) {
    if let Type::Union { variants } = t {
        let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
        if non_null.len() == 1 && non_null.len() != variants.len() {
            return (non_null[0], true);
        }
    }
    (t, false)
}

fn literal_union(t: &Type) -> Option<Vec<String>> {
    match t {
        Type::Literal { value } => Some(vec![value.clone()]),
        Type::Union { variants } if variants.iter().all(|v| matches!(v, Type::Literal { .. })) => {
            Some(variants.iter().map(|v| if let Type::Literal { value } = v { value.clone() } else { String::new() }).collect())
        }
        _ => None,
    }
}

fn scalar_ty(name: &str) -> &'static str {
    match name {
        "string" => "string",
        "bool" => "bool",
        "int" | "int64" => "long",
        "email" => "Comatype.Email",
        "phone" => "Comatype.Phone",
        "uuid" | "uuidv4" | "uuidv7" => "System.Guid",
        "date" => "System.DateOnly",
        "datetime" => "System.DateTimeOffset",
        "time" => "System.TimeOnly",
        "decimal" => "decimal",
        "url" => "System.Uri",
        "bytes" => "byte[]",
        _ => "object",
    }
}

/// The suffix of the `Opt` / `Nullable` helpers: `V` for value types (`T?` is `Nullable<T>`), `R` for reference types
fn kind(is_value: bool) -> &'static str {
    if is_value {
        "V"
    } else {
        "R"
    }
}

impl<'a> Gen<'a> {
    fn is_enum(&self, id: &str) -> bool {
        self.names.contains_key(&format!("enum:{id}"))
    }

    fn is_value(&self, t: &Type) -> bool {
        match t {
            Type::Scalar { name, .. } => {
                matches!(name.as_str(), "bool" | "int" | "int64" | "uuid" | "uuidv4" | "uuidv7" | "date" | "datetime" | "time" | "decimal")
            }
            Type::Ref { id, .. } => self.is_enum(id),
            _ => false,
        }
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    /// C# type. If `nullable`, a `?` is added (optional fields, `T | null`)
    fn cty(&mut self, t: &Type, hint: &str, mode: Mode, nullable: bool) -> Result<String, String> {
        let q = if nullable { "?" } else { "" };
        match t {
            Type::Scalar { name, .. } => {
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} cannot be used in a path, query or header"));
                }
                Ok(format!("{}{q}", scalar_ty(name)))
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("unknown type {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} is an object, so it cannot be used in a path, query or header"));
                }
                Ok(format!("{}{}{q}", self.prefix, name))
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("an object cannot be used in a path, query or header".into());
                }
                let name = self.unique(hint);
                let decl = self.record_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(format!("{name}{q}"))
            }
            Type::Array { item } => {
                if strip_null(item).1 {
                    return Err("array items that may be null are not supported in C#".into());
                }
                Ok(format!("System.Collections.Generic.List<{}>{q}", self.cty(item, &format!("{hint}Item"), mode, false)?))
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if literal_union(t).is_some() {
                    return Ok(format!("string{q}"));
                }
                Err("C# cannot express a union type (`T | null` and unions of string literals are supported)".into())
            }
            Type::Null => Err("a type that is only null is not supported in C#".into()),
        }
    }

    /// Decoder (JSON tree to value): an expression of `Comatype.Codec.Decoder<T>`
    fn dec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "Comatype.Codec.ReadString",
                "bool" => "Comatype.Codec.ReadBool",
                "int" => "Comatype.Codec.ReadInteger",
                "int64" => "Comatype.Codec.ReadInt64",
                "email" => "Comatype.Codec.ReadEmail",
                "phone" => "Comatype.Codec.ReadPhone",
                "uuid" => "Comatype.Codec.ReadUuid",
                "uuidv4" => "Comatype.Codec.ReadUuidV4",
                "uuidv7" => "Comatype.Codec.ReadUuidV7",
                "date" => "Comatype.Codec.ReadDate",
                "datetime" => "Comatype.Codec.ReadDatetime",
                "time" => "Comatype.Codec.ReadTime",
                "decimal" => "Comatype.Codec.ReadDecimal",
                "url" => "Comatype.Codec.ReadUrl",
                "bytes" => "Comatype.Codec.ReadBytes",
                _ => "Comatype.Codec.ReadJson",
            }
            .to_string(),
            Type::Ref { id, .. } => {
                let n = format!("{}{}", self.prefix, self.names.get(id).cloned().unwrap_or_default());
                if self.is_enum(id) {
                    format!("Comatype.Codec.ReadEnum<{n}>")
                } else {
                    format!("{n}.Decode")
                }
            }
            Type::Object { .. } => "/* inline */".into(),
            Type::Array { item } => format!("(j, p) => Comatype.Codec.ReadList(j, p, {})", self.dec(item)),
            _ => "Comatype.Codec.ReadString".into(),
        }
    }

    /// Parser (string from a path, query or header to value)
    fn wdec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "Comatype.Wire.ParseString",
                "bool" => "Comatype.Wire.ParseBool",
                "int" | "int64" => "Comatype.Wire.ParseInteger",
                "email" => "Comatype.Wire.ParseEmail",
                "phone" => "Comatype.Wire.ParsePhone",
                "uuid" => "Comatype.Wire.ParseUuid",
                "uuidv4" => "Comatype.Wire.ParseUuidV4",
                "uuidv7" => "Comatype.Wire.ParseUuidV7",
                "date" => "Comatype.Wire.ParseDate",
                "datetime" => "Comatype.Wire.ParseDatetime",
                "time" => "Comatype.Wire.ParseTime",
                "decimal" => "Comatype.Wire.ParseDecimal",
                "url" => "Comatype.Wire.ParseUrl",
                _ => "Comatype.Wire.ParseString",
            }
            .to_string(),
            Type::Ref { id, .. } => {
                let n = format!("{}{}", self.prefix, self.names.get(id).cloned().unwrap_or_default());
                format!("Comatype.Wire.ParseEnum<{n}>")
            }
            _ => "Comatype.Wire.ParseString".into(),
        }
    }

    /// Expression that turns a value into a JSON tree
    fn enc(&self, t: &Type, e: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "int64" => format!("Comatype.Codec.FromInt64({e})"),
                "decimal" => format!("Comatype.Codec.FromDecimal({e})"),
                "time" => format!("Comatype.Codec.FromTime({e})"),
                "date" => format!("Comatype.Codec.FromDate({e})"),
                "datetime" => format!("Comatype.Codec.FromDatetime({e})"),
                "url" => format!("Comatype.Codec.FromUrl({e})"),
                "bytes" => format!("Comatype.Codec.FromBytes({e})"),
                "email" | "phone" => format!("{e}.Value"),
                "uuid" | "uuidv4" | "uuidv7" => format!("{e}.ToString()"),
                _ => e.to_string(),
            },
            Type::Ref { id, .. } => {
                if self.is_enum(id) {
                    format!("Comatype.Wire.Str({e})")
                } else {
                    format!("{e}.Encode()")
                }
            }
            Type::Object { .. } => format!("{e}.Encode()"),
            Type::Array { item } => {
                let x = format!("x{depth}");
                format!("Comatype.Codec.FromList({e}, {x} => {})", self.enc(item, &x, depth + 1))
            }
            _ => e.to_string(),
        }
    }

    /// Validation statements. `var` is the (non-null) value expression, `path` is a string expression
    fn vstmts(&self, t: &Type, var: &str, path: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, constraint } => {
                let mut s = String::new();
                match name.as_str() {
                    "email" | "phone" => s.push_str(&format!("{var}.Validate({path});\n")),
                    "uuidv4" => s.push_str(&format!("Comatype.Check.UuidVersion({path}, {var}, 4);\n")),
                    "uuidv7" => s.push_str(&format!("Comatype.Check.UuidVersion({path}, {var}, 7);\n")),
                    _ => {}
                }
                match constraint {
                    Some(Constraint::Range { min, max }) => {
                        let opt = |v: &Option<i64>| v.map_or("null".to_string(), |n| format!("{n}L"));
                        match name.as_str() {
                            "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" => {
                                s.push_str(&format!("Comatype.Check.Len({path}, Comatype.Wire.Str({var}), {}, {});\n", opt(min), opt(max)))
                            }
                            "int" | "int64" | "decimal" => {
                                s.push_str(&format!("Comatype.Check.Range({path}, (double){var}, {}, {});\n", opt(min), opt(max)))
                            }
                            _ => {}
                        }
                    }
                    Some(Constraint::Pattern { value }) => {
                        if matches!(
                            name.as_str(),
                            "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" | "decimal"
                        ) {
                            s.push_str(&format!("Comatype.Check.Pattern({path}, Comatype.Wire.Str({var}), {});\n", cstr(value)));
                        }
                    }
                    None => {}
                }
                s
            }
            Type::Ref { id, .. } => {
                if self.is_enum(id) {
                    String::new()
                } else {
                    format!("{var}.Validate({path});\n")
                }
            }
            Type::Object { .. } => format!("{var}.Validate({path});\n"),
            Type::Array { item } => {
                let (i, it) = (format!("i{depth}"), format!("item{depth}"));
                let inner = self.vstmts(item, &it, &format!("{path} + \"[\" + {i} + \"]\""), depth + 1);
                if inner.is_empty() {
                    String::new()
                } else {
                    format!("for (int {i} = 0; {i} < {var}.Count; {i}++) {{\nvar {it} = {var}[{i}];\n{inner}}}\n")
                }
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if let Some(vals) = literal_union(t) {
                    let list = vals.iter().map(|v| cstr(v)).collect::<Vec<_>>().join(", ");
                    return format!("Comatype.Check.OneOf({path}, {var}, {list});\n");
                }
                String::new()
            }
            Type::Null => String::new(),
        }
    }

    fn record_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut comps = Vec::new();
        let mut checks = String::new();
        let mut puts = String::new();
        let mut args = Vec::new();
        let mut seen = BTreeSet::new();
        let mut all_optional = true;
        let mut names = Vec::new();
        for (idx, f) in fields.iter().enumerate() {
            let p = prop(&f.name, name);
            names.push(p.clone());
            if !seen.insert(p.clone()) {
                return Err(format!("{name}: the field name {p} is duplicated ({})", f.name));
            }
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let ty = self.cty(inner, &format!("{name}{}", pascal(&f.name)), mode, opt).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            comps.push(format!("{ty} {p}"));
            if !opt {
                all_optional = false;
            }
            let v = format!("v{idx}");
            let path = format!("Comatype.ValidationException.Join(path, {})", cstr(&f.name));
            if opt {
                let body = self.vstmts(inner, &v, &path, 0);
                if !body.is_empty() {
                    checks.push_str(&format!("if ({p} is {{ }} {v}) {{\n{body}}}\n"));
                }
            } else {
                checks.push_str(&self.vstmts(inner, &p, &path, 0));
            }
            if mode == Mode::Json {
                if f.optional {
                    puts.push_str(&format!("if ({p} is {{ }} {v}) m[{}] = {};\n", cstr(&f.name), self.enc(inner, &v, 0)));
                } else if nullable {
                    puts.push_str(&format!("m[{}] = {p} is {{ }} {v} ? (object?)({}) : null;\n", cstr(&f.name), self.enc(inner, &v, 0)));
                } else {
                    puts.push_str(&format!("m[{}] = {};\n", cstr(&f.name), self.enc(inner, &p, 0)));
                }
                if matches!(inner, Type::Object { .. }) {
                    return Err("internal error: inline object".into());
                }
                let d = self.dec(inner);
                let k = kind(self.is_value(inner));
                let call = if f.optional {
                    format!("Comatype.Codec.Opt{k}(m, {}, path, {d})", cstr(&f.name))
                } else if nullable {
                    format!("Comatype.Codec.Req(m, {}, path, Comatype.Codec.Nullable{k}({d}))", cstr(&f.name))
                } else {
                    format!("Comatype.Codec.Req(m, {}, path, {d})", cstr(&f.name))
                };
                args.push(call);
            }
        }
        let implements = if mode == Mode::Json { " : Comatype.IJsonType" } else { "" };
        let mut body = String::new();
        if mode != Mode::Plain {
            body.push_str(&format!("public void Validate(string path)\n{{\n{checks}}}\n"));
        }
        if mode == Mode::Json {
            body.push_str(&format!(
                "public object? Encode()\n{{\nvar m = new System.Collections.Generic.Dictionary<string, object?>();\n{puts}return m;\n}}\n"
            ));
            body.push_str(&format!(
                "public static {name} Decode(object? j, string path)\n{{\nvar m = Comatype.Codec.ReadObject(j, path);\nvar v = new {name}({});\nv.Validate(path);\nreturn v;\n}}\n",
                args.join(", ")
            ));
        }
        if all_optional && !fields.is_empty() {
            body.push_str(&format!(
                "public static {name} Empty() => new {name}({});\n",
                // Named arguments, so that a one-field record is not mistaken for its copy constructor
                names.iter().map(|n| format!("{n}: null")).collect::<Vec<_>>().join(", ")
            ));
        }
        Ok(format!("public sealed record {name}({comps}){implements}\n{{\n{}}}\n", indent(body.trim_end()), comps = comps.join(", ")))
    }

    /// Named declaration: an object becomes a record, anything else produces nothing (the type is written directly where it is used)
    fn named_object(&mut self, name: &str, t: &Type) -> Result<Option<String>, String> {
        self.used_names.insert(name.to_string());
        match t {
            Type::Object { fields } => {
                let decl = self.record_decl(name, fields, Mode::Json)?;
                let mut out = String::new();
                for e in self.extra.drain(..) {
                    out.push_str(&e);
                    out.push('\n');
                }
                out.push_str(&decl);
                Ok(Some(out))
            }
            _ => Ok(None),
        }
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        let name = cap(&nt.name);
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("the C# type name `{name}` is used by both {prev} and {id}"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

fn indent(s: &str) -> String {
    s.lines().map(|l| if l.is_empty() { String::new() } else { format!("    {l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

// ---- Types.cs ----

fn types_file(svc: &Service, names: &BTreeMap<String, String>, namespace: &str) -> Result<String, String> {
    let mut g = Gen { names, prefix: "", extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = g.record_decl(name, fields, Mode::Json)?;
                for e in g.extra.drain(..) {
                    body.push_str(&e);
                    body.push('\n');
                }
                body.push_str(&decl);
                body.push('\n');
            }
            TypeDef::Enum { values } => {
                let mut consts = Vec::new();
                let mut seen = BTreeSet::new();
                for v in values {
                    let c = pascal(v);
                    if !seen.insert(c.clone()) {
                        return Err(format!("{name}: the enum value {c} is duplicated ({v})"));
                    }
                    consts.push(format!("[Comatype.WireName({})]\n{c}", cstr(v)));
                }
                body.push_str(&format!("public enum {name}\n{{\n{}\n}}\n\n", indent(&consts.join(",\n")).trim_end()));
            }
        }
    }
    Ok(format!("{HEADER}\nnamespace {namespace};\n\npublic static class Types\n{{\n{}}}\n", indent(body.trim_end())))
}

// ---- Endpoints ----

fn cookie_def_cs(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("null".to_string(), cstr);
    format!(
        "new Comatype.CookieDef({}, {}, {}, {}, {}, {}, {})",
        cstr(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("null".to_string(), |v| format!("{v}L")),
    )
}

/// Static methods that read and write the body (JSON). `ty` is the C# type
fn body_codec(g: &mut Gen, label: &str, t: &Type, ty: &str) -> String {
    let v = g.vstmts(t, "v", "\"\"", 0);
    let enc = g.enc(t, "v", 0);
    let dec = match t {
        Type::Object { .. } => format!("{ty}.Decode"),
        _ => g.dec(t),
    };
    format!(
        "private static byte[] Encode{label}({ty} v)\n{{\n{v}return Comatype.Codec.EncodeValue({enc});\n}}\n\n\
         private static {ty} Decode{label}(byte[] b, string path)\n{{\nreturn Comatype.Codec.Decode(b, path, {dec});\n}}\n\n"
    )
}

/// `"name", var.Prop, "name", var.Prop` for the Wire helpers
fn wire_pairs(fields: &[Field], var: &str, owner: &str) -> String {
    fields.iter().map(|f| format!("{}, {var}.{}", cstr(&f.name), prop(&f.name, owner))).collect::<Vec<_>>().join(", ")
}

/// Expression that reads the header / params / search records
fn wire_build(name: &str, fields: &[Field], g: &Gen, values: &str, split: bool) -> String {
    let args: Vec<String> = fields
        .iter()
        .map(|f| {
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let vals = values.replace("{}", &cstr(&f.name));
            match inner {
                Type::Array { item } => {
                    let fun = if opt { "ReadListOpt" } else { "ReadList" };
                    format!("Comatype.Wire.{fun}({vals}, {}, {split}, {})", cstr(&f.name), g.wdec(item))
                }
                _ if opt => {
                    format!("Comatype.Wire.ReadOpt{}({vals}, {}, {split}, {})", kind(g.is_value(inner)), cstr(&f.name), g.wdec(inner))
                }
                _ => format!("Comatype.Wire.Read({vals}, {}, {split}, {})", cstr(&f.name), g.wdec(inner)),
            }
        })
        .collect();
    format!("new {name}({})", args.join(", "))
}

/// The `cache` setting (GET / QUERY only)
fn cache_cs(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let (mode, ttl) = match &ep.cache {
        None => return String::new(),
        Some(CacheMode::Off) => ("off", 0),
        Some(CacheMode::Memory { ttl_ms }) => ("memory", *ttl_ms),
        Some(CacheMode::Cookie { ttl_ms }) => ("cookie", *ttl_ms),
    };
    let names: Vec<String> = ep.request_headers.iter().map(|h| cstr(&h.name)).collect();
    format!(".Cache(new Comatype.CacheSpec(\"{mode}\", {ttl}L), new string[] {{ {} }})", names.join(", "))
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role, namespace: &str) -> Result<String, String> {
    let class = module_class(&ep.module);
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();
    let mut codecs = String::new();
    let has_req_headers = !ep.request_headers.is_empty();

    if !ep.params.is_empty() {
        body.push_str(&g.record_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    if !ep.search.is_empty() {
        body.push_str(&g.record_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let mut body_ty = String::new();
    if let Some(b) = &ep.body {
        g.used_names.insert("Body".into());
        if let Some(decl) = g.named_object("Body", b).map_err(ctx)? {
            body.push_str(&decl);
            body.push('\n');
            body_ty = "Body".into();
        } else {
            let (inner, _) = strip_null(b);
            body_ty = g.cty(inner, "Body", Mode::Json, false).map_err(ctx)?;
        }
        codecs.push_str(&body_codec(&mut g, "Body", b, &body_ty));
    }
    if has_req_headers {
        body.push_str(&g.record_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let comps: Vec<String> = ctx_wrappers.iter().map(|w| format!("Init.{}Ctx {}", pascal(&w.name), prop(&w.name, "Ctx"))).collect();
        body.push_str(&format!("// The values added by the wrappers in effect\npublic sealed record Ctx({});\n\n", comps.join(", ")));
    }
    // Whole request
    let mut req_comps: Vec<(&str, &str, String)> = Vec::new();
    if !ep.params.is_empty() {
        req_comps.push(("params", "Params", "Params".into()));
    }
    if !ep.search.is_empty() {
        req_comps.push(("search", "Search", "Search".into()));
    }
    if has_req_headers {
        req_comps.push(("headers", "Headers", "RequestHeaders".into()));
    }
    if ep.body.is_some() {
        req_comps.push(("body", "Body", body_ty.clone()));
    }
    if role == Role::Server {
        req_comps.push(("ctx", "Ctx", "Ctx".into()));
    }
    let has = |n: &str| req_comps.iter().any(|(f, _, _)| *f == n);
    body.push_str(&format!(
        "// The whole request\npublic sealed record Request({});\n\n",
        req_comps.iter().map(|(_, p, t)| format!("{t} {p}")).collect::<Vec<_>>().join(", ")
    ));

    // Response
    let cookie = ep.cookie && svc.cookie.is_some();
    let mut variants = String::new();
    for r in &ep.responses {
        let c = r.status;
        let mut comps = Vec::new();
        if let Some(b) = &r.body {
            let label = format!("S{c}Res");
            let (inner, _) = strip_null(b);
            let ty = if let Some(decl) = g.named_object(&label, b).map_err(ctx)? {
                body.push_str(&decl);
                body.push('\n');
                label.clone()
            } else {
                g.cty(inner, &label, Mode::Json, false).map_err(ctx)?
            };
            codecs.push_str(&body_codec(&mut g, &format!("S{c}"), b, &ty));
            comps.push(format!("{ty} Body"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.record_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            body.push('\n');
            comps.push(format!("S{c}Headers Headers"));
        }
        variants.push_str(&format!("public sealed record S{c}({}) : Response;\n", comps.join(", ")));
    }
    body.push_str(&format!("// The response of every declared status\npublic abstract record Response\n{{\nprivate protected Response() {{ }}\n}}\n\n{variants}\n"));

    // Descriptor
    let arg = if has("params") || has("search") || has("headers") {
        "Request".to_string()
    } else if ep.body.is_some() {
        body_ty.clone()
    } else {
        "Comatype.NoArg".to_string()
    };
    let res_ty = if role == Role::Server && cookie { "Comatype.S.Reply<Response>".to_string() } else { "Response".to_string() };
    let wraps = if ep.wraps.is_empty() {
        "System.Array.Empty<string>()".to_string()
    } else {
        format!("new string[] {{ {} }}", ep.wraps.iter().map(|w| cstr(w)).collect::<Vec<_>>().join(", "))
    };
    let base = svc.base_url.as_ref().map_or("null".to_string(), |u| cstr(u));
    let cd = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_cs(c),
        _ => "null".to_string(),
    };
    match role {
        Role::Client => body.push_str(&format!(
            "// The method and the path\npublic static readonly Comatype.Endpoint<{arg}, Comatype.NoArg, Response> Endpoint = Comatype.Endpoint.Client<{arg}, Response>(\n{}, {}, {}, {base}, {wraps}, {}, {cd},\nBuildRequest, ParseResponse){};\n\n",
            cstr(&ep.method),
            cstr(&ep.path),
            cstr(&ep.module),
            ep.cookie,
            cache_cs(ep)
        )),
        Role::Server => body.push_str(&format!(
            "// The method and the path\npublic static readonly Comatype.Endpoint<Comatype.NoArg, Request, {res_ty}> Endpoint = Comatype.Endpoint.Server<Request, {res_ty}>(\n{}, {}, {}, {base}, {wraps}, {}, {cd},\nParseRequest, BuildResponse){};\n\n",
            cstr(&ep.method),
            cstr(&ep.path),
            cstr(&ep.module),
            ep.cookie,
            cache_cs(ep)
        )),
    }
    body.push_str(&codecs);

    match role {
        Role::Client => {
            let mut f = format!(
                "private static Comatype.RawRequest BuildRequest({arg} arg)\n{{\nvar raw = new Comatype.RawRequest({}, {});\n",
                cstr(&ep.method),
                cstr(&ep.path)
            );
            if arg == "Request" {
                if has("params") {
                    f.push_str(&format!(
                        "arg.Params.Validate(\"\");\nComatype.Wire.FillPath(raw, {});\n",
                        wire_pairs(&ep.params, "arg.Params", "Params")
                    ));
                }
                if has("search") {
                    f.push_str(&format!(
                        "arg.Search.Validate(\"\");\nComatype.Wire.AddQuery(raw, {});\n",
                        wire_pairs(&ep.search, "arg.Search", "Search")
                    ));
                }
                if has("headers") {
                    f.push_str(&format!(
                        "arg.Headers.Validate(\"\");\nComatype.Wire.SetHeaders(raw.Headers, {});\n",
                        wire_pairs(&ep.request_headers, "arg.Headers", "RequestHeaders")
                    ));
                }
                if has("body") {
                    f.push_str("raw.Body = EncodeBody(arg.Body);\nraw.Headers.Set(\"Content-Type\", \"application/json\");\n");
                }
            } else if arg != "Comatype.NoArg" {
                f.push_str("raw.Body = EncodeBody(arg);\nraw.Headers.Set(\"Content-Type\", \"application/json\");\n");
            }
            f.push_str("return raw;\n}\n\n");
            body.push_str(&f);

            let mut p = String::from("private static Response ParseResponse(Comatype.RawResponse raw)\n{\nswitch (raw.Status)\n{\n");
            for r in &ep.responses {
                let c = r.status;
                p.push_str(&format!("case {c}:\n{{\n"));
                let mut args = Vec::new();
                if r.body.is_some() {
                    p.push_str(&format!(
                        "if (raw.Body.Length == 0) throw new Comatype.ValidationException(\"body\", \"必須です\");\nvar body = DecodeS{c}(raw.Body, \"body\");\n"
                    ));
                    args.push("body");
                }
                if !r.headers.is_empty() {
                    p.push_str(&format!(
                        "var headers = {};\nheaders.Validate(\"\");\n",
                        wire_build(&format!("S{c}Headers"), &r.headers, &g, "Comatype.Wire.HeaderValues(raw.Headers, {})", true)
                    ));
                    args.push("headers");
                }
                p.push_str(&format!("return new S{c}({});\n}}\n", args.join(", ")));
            }
            p.push_str("default:\nthrow new Comatype.ComatypeException.UnexpectedStatus(raw.Status, raw.Body);\n}\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            let mut f = String::from("private static Request ParseRequest(Comatype.RawRequest raw)\n{\n");
            let mut inits = Vec::new();
            if has("params") {
                f.push_str(&format!(
                    "var prms = {};\nprms.Validate(\"\");\n",
                    wire_build("Params", &ep.params, &g, "Comatype.Wire.ParamValues(raw, {})", false)
                ));
                inits.push("prms");
            }
            if has("search") {
                f.push_str(&format!(
                    "var search = {};\nsearch.Validate(\"\");\n",
                    wire_build("Search", &ep.search, &g, "Comatype.Wire.QueryValues(raw, {})", false)
                ));
                inits.push("search");
            }
            if has("headers") {
                f.push_str(&format!(
                    "var headers = {};\nheaders.Validate(\"\");\n",
                    wire_build("RequestHeaders", &ep.request_headers, &g, "Comatype.Wire.HeaderValues(raw.Headers, {})", true)
                ));
                inits.push("headers");
            }
            if has("body") {
                f.push_str("if (raw.Body.Length == 0) throw new Comatype.ValidationException(\"body\", \"必須です\");\nvar body = DecodeBody(raw.Body, \"body\");\n");
                inits.push("body");
            }
            if has("ctx") {
                let cs: Vec<String> =
                    ctx_wrappers.iter().map(|w| format!("Comatype.S.Ctx<Init.{}Ctx>(raw, {})", pascal(&w.name), cstr(&w.name))).collect();
                f.push_str(&format!("var ctx = new Ctx({});\n", cs.join(", ")));
                inits.push("ctx");
            }
            f.push_str(&format!("return new Request({});\n}}\n\n", inits.join(", ")));
            body.push_str(&f);

            let mut b = format!("private static Comatype.RawResponse BuildResponse({res_ty} reply)\n{{\n");
            if cookie {
                b.push_str("Response res = reply.Response;\n");
            } else {
                b.push_str("Response res = reply;\n");
            }
            b.push_str("Comatype.RawResponse result;\nswitch (res)\n{\n");
            for r in &ep.responses {
                let c = r.status;
                b.push_str(&format!("case S{c} r:\n{{\nresult = new Comatype.RawResponse({c});\n"));
                if r.body.is_some() {
                    b.push_str(&format!(
                        "result.Body = EncodeS{c}(r.Body);\nresult.Headers.Set(\"Content-Type\", \"application/json\");\n"
                    ));
                }
                if !r.headers.is_empty() {
                    b.push_str(&format!(
                        "r.Headers.Validate(\"\");\nComatype.Wire.SetHeaders(result.Headers, {});\n",
                        wire_pairs(&r.headers, "r.Headers", &format!("S{c}Headers"))
                    ));
                }
                b.push_str("break;\n}\n");
            }
            b.push_str("default:\nthrow new Comatype.ComatypeException(\"the response is not declared: \" + res);\n}\n");
            if cookie {
                b.push_str("Comatype.S.ApplyCookie(result, Endpoint.CookieDef, reply.Cookie);\n");
            }
            b.push_str("return result;\n}\n");
            body.push_str(&b);
        }
    }

    Ok(format!(
        "{HEADER}\nnamespace {namespace};\n\n// {} — {} {}\npublic static class {class}\n{{\n{}}}\n",
        ep.file,
        ep.method.to_uppercase(),
        ep.path,
        indent(body.trim_end())
    ))
}

// ---- Init.cs ----

fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role, namespace: &str) -> Result<String, String> {
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut comps = Vec::new();
    let mut entries = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let (p, f) = (pascal(&w.name), prop(&w.name, "Wrappers"));
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("// The values wrapper {} adds (req.Ctx.{f} in a handler)\n", w.name));
                body.push_str(&g.record_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` and `{prev}` both declare s{}", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            let label = format!("S{c}Res");
                            let (inner, _) = strip_null(b);
                            let ty = if let Some(decl) = g.named_object(&label, b)? {
                                body.push_str(&decl);
                                body.push('\n');
                                label.clone()
                            } else {
                                g.cty(inner, &label, Mode::Json, false)?
                            };
                            let v = g.vstmts(b, "body", "\"\"", 0);
                            let enc = g.enc(b, "body", 0);
                            body.push_str(&format!(
                                "// The status {c} response wrapper {} may return\npublic static Comatype.RawResponse S{c}({ty} body)\n{{\n{v}var r = new Comatype.RawResponse({c});\nr.Body = Comatype.Codec.EncodeValue({enc});\nr.Headers.Set(\"Content-Type\", \"application/json\");\nreturn r;\n}}\n\n",
                                w.name
                            ));
                        }
                        None => body.push_str(&format!(
                            "// The status {c} response wrapper {} may return\npublic static Comatype.RawResponse S{c}()\n{{\nreturn new Comatype.RawResponse({c});\n}}\n\n",
                            w.name
                        )),
                    }
                }
                comps.push(format!("Comatype.S.ComatypeWrap<{ctx_name}> {f}"));
                entries.push_str(&format!("m[{}] = Comatype.S.Adapt({}, {f});\n", cstr(&w.name), cstr(&w.name)));
            }
            Role::Client => {
                comps.push(format!("Comatype.C.ComatypeWrap {f}"));
                entries.push_str(&format!("m[{}] = {f};\n", cstr(&w.name)));
            }
        }
    }
    let (set, wrap_ty) = match role {
        Role::Server => ("S", "Comatype.S.ServerWrap"),
        Role::Client => ("C", "Comatype.C.ComatypeWrap"),
    };
    body.push_str(&format!(
        "// One implementation per `wrapper` in init.comat. Pass it to {set}.Init\npublic sealed record Wrappers({}) : Comatype.{set}.IWrapperSet\n{{\npublic System.Collections.Generic.IReadOnlyDictionary<string, {wrap_ty}> ComatypeWrappers()\n{{\nvar m = new System.Collections.Generic.Dictionary<string, {wrap_ty}>();\n{entries}return m;\n}}\n}}\n",
        comps.join(", ")
    ));
    Ok(format!(
        "{HEADER}\nnamespace {namespace};\n\n// Generated from init.comat\npublic static class Init\n{{\n{}}}\n",
        indent(body.trim_end())
    ))
}

