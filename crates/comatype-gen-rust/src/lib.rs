//! Generates Rust code from the IR (serde structs + the runtime `comatype` crate).
//!
//! Output (under `<out>`; `<out>` is a Rust module; default `src/comatype_gen`):
//!   mod.rs                 declarations of each module
//!   types.rs               named types (structs, enums)
//!   init.rs                wrappers, ctx, wrapper statuses
//!   <module>.rs            one per endpoint (e.g. user_put_id.rs; module names are the same as Go package names)
//!
//! The contents of init and endpoint differ between client and server (matching the runtime's c / s).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "// Code generated by comatype generate. DO NOT EDIT.\n#![allow(unused_imports, unused_mut, unused_variables, dead_code, clippy::all)]\n";
const SERDE: &str = "#[serde(crate = \"::comatype::serde\")]";

pub fn generate(svc: &Service, role: Role) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut mods = vec!["types".to_string(), "init".to_string()];
    let mut files = vec![
        GenFile { path: "types.rs".into(), content: types_file(svc, &names)? },
        GenFile { path: "init.rs".into(), content: init_file(svc, &names, role)? },
    ];
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let m = module_name(&ep.module);
        if m == "types" || m == "init" {
            return Err(format!(
                "{} は Rust では生成先のモジュール名 `{m}` が types / init と衝突します（ファイルかディレクトリの名前を変えてください）",
                ep.file
            ));
        }
        if let Some(prev) = seen.insert(m.clone(), &ep.file) {
            return Err(format!("{} と {prev} が同じモジュール名 `{m}` になります", ep.file));
        }
        files.push(GenFile { path: format!("{m}.rs"), content: endpoint_file(svc, &names, ep, role)? });
        mods.push(m);
    }
    let decls: String = mods.iter().map(|m| format!("pub mod {m};\n")).collect();
    files.push(GenFile { path: "mod.rs".into(), content: format!("// Code generated by comatype generate. DO NOT EDIT.\n{decls}") });
    Ok(files)
}

// ---- Names ----

const RESERVED: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield",
    "try", "gen",
];

fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            continue;
        }
        let prev_lower = i > 0 && chars[i - 1].is_ascii_lowercase();
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
        let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
        if c.is_ascii_uppercase() && !cur.is_empty() && (prev_lower || (prev_upper && next_lower)) {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// `user/put__id` → `user_put_id` (Rust module name)
pub fn module_name(module: &str) -> String {
    let n = module
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| w.to_ascii_lowercase())
        .collect::<Vec<_>>()
        .join("_");
    let n = if n.chars().next().is_none_or(|c| c.is_ascii_digit()) { format!("m_{n}") } else { n };
    if RESERVED.contains(&n.as_str()) || ["self", "super", "crate"].contains(&n.as_str()) {
        format!("{n}_")
    } else {
        n
    }
}

/// Field name (snake_case)
pub fn snake(s: &str) -> String {
    let n = words(s).iter().map(|w| w.to_ascii_lowercase()).collect::<Vec<_>>().join("_");
    let n = if n.chars().next().is_none_or(|c| c.is_ascii_digit()) { format!("f_{n}") } else { n };
    if ["self", "super", "crate"].contains(&n.as_str()) {
        format!("{n}_")
    } else if RESERVED.contains(&n.as_str()) {
        format!("r#{n}")
    } else {
        n
    }
}

/// Type name / enum value (PascalCase)
pub fn pascal(s: &str) -> String {
    let out: String = words(s)
        .iter()
        .map(|w| {
            let mut cs = w.chars();
            let f = cs.next().unwrap();
            f.to_ascii_uppercase().to_string() + cs.as_str()
        })
        .collect();
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("V{out}")
    } else {
        out
    }
}

fn rs_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}

// ---- Types ----

struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    /// Prefix when referring to a type in another module (`types::`). Empty inside the types module
    prefix: &'a str,
    /// Declarations of named types created along the way
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// serde (body)
    Json,
    /// path, query, headers. Scalars and their arrays only
    Wire,
    /// ctx
    Plain,
}

/// (T, true) for `T | null`
fn strip_null(t: &Type) -> (&Type, bool) {
    if let Type::Union { variants } = t {
        let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
        if non_null.len() == 1 && non_null.len() != variants.len() {
            return (non_null[0], true);
        }
    }
    (t, false)
}

fn literal_union(t: &Type) -> Option<Vec<String>> {
    match t {
        Type::Literal { value } => Some(vec![value.clone()]),
        Type::Union { variants } if variants.iter().all(|v| matches!(v, Type::Literal { .. })) => {
            Some(variants.iter().map(|v| if let Type::Literal { value } = v { value.clone() } else { String::new() }).collect())
        }
        _ => None,
    }
}

fn scalar_ty(name: &str) -> &'static str {
    match name {
        "string" => "String",
        "bool" => "bool",
        "int" => "i64",
        "email" => "::comatype::Email",
        "phone" => "::comatype::Phone",
        "uuid" => "::comatype::Uuid",
        "uuidv4" => "::comatype::Uuidv4",
        "uuidv7" => "::comatype::Uuidv7",
        "date" => "::comatype::Date",
        "datetime" => "::comatype::DateTime",
        "time" => "::comatype::Time",
        "int64" => "::comatype::Int64",
        "decimal" => "::comatype::Decimal",
        "url" => "::comatype::Url",
        "bytes" => "::comatype::Bytes",
        _ => "::comatype::serde_json::Value",
    }
}

impl<'a> Gen<'a> {
    fn is_enum(&self, id: &str) -> bool {
        self.names.contains_key(&format!("enum:{id}"))
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    /// Rust type (does not include `Option`; optional / null is up to the caller)
    fn rty(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<String, String> {
        match t {
            Type::Scalar { name, .. } => {
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                Ok(scalar_ty(name).to_string())
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(format!("{}{}", self.prefix, name))
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.struct_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(name)
            }
            Type::Array { item } => {
                if strip_null(item).1 {
                    return Err("null を含む配列の要素は Rust では未対応です".into());
                }
                Ok(format!("Vec<{}>", self.rty(item, &format!("{hint}Item"), mode)?))
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if let Some(vals) = literal_union(t) {
                    if vals.iter().any(|v| v.contains('"')) {
                        return Err("リテラルの値に `\"` は使えません".into());
                    }
                    return Ok("String".into());
                }
                Err("Rust ではユニオン型を表せません（`T | null` と、文字列リテラルだけのユニオンに対応しています）".into())
            }
            Type::Null => Err("null だけの型は Rust では未対応です".into()),
        }
    }

    /// Validation statements. `var` is a `&T` expression, `path` is a String expression
    fn validate_stmts(&self, t: &Type, var: &str, path: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, constraint } => {
                let mut s = String::new();
                if matches!(
                    name.as_str(),
                    "email" | "phone" | "uuid" | "uuidv4" | "uuidv7" | "date" | "datetime" | "time" | "decimal" | "url"
                ) {
                    s.push_str(&format!("::comatype::Validate::validate({var}, &{path})?;\n"));
                }
                match constraint {
                    Some(Constraint::Range { min, max }) => {
                        let opt = |v: &Option<i64>| v.map_or("None".to_string(), |n| format!("Some({n})"));
                        let optf = |v: &Option<i64>| v.map_or("None".to_string(), |n| format!("Some({n}.0)"));
                        match name.as_str() {
                            "string" | "email" | "phone" | "uuid" | "uuidv4" | "uuidv7" | "date" | "datetime" | "time" | "url" => s
                                .push_str(&format!(
                                    "::comatype::validate::check_len(&{path}, {var}.as_str(), {}, {})?;\n",
                                    opt(min),
                                    opt(max)
                                )),
                            "int" => s.push_str(&format!(
                                "::comatype::validate::check_range(&{path}, *{var} as f64, {}, {})?;\n",
                                optf(min),
                                optf(max)
                            )),
                            "int64" => s.push_str(&format!(
                                "::comatype::validate::check_range(&{path}, {var}.0 as f64, {}, {})?;\n",
                                optf(min),
                                optf(max)
                            )),
                            "decimal" => s.push_str(&format!(
                                "::comatype::validate::check_range(&{path}, {var}.to_f64(), {}, {})?;\n",
                                optf(min),
                                optf(max)
                            )),
                            _ => {}
                        }
                    }
                    Some(Constraint::Pattern { value }) => {
                        if matches!(
                            name.as_str(),
                            "string" | "email" | "phone" | "uuid" | "uuidv4" | "uuidv7" | "date" | "datetime" | "time" | "url" | "decimal"
                        ) {
                            s.push_str(&format!("::comatype::validate::check_pattern(&{path}, {var}.as_str(), {})?;\n", rs_string(value)));
                        }
                    }
                    None => {}
                }
                s
            }
            Type::Ref { .. } | Type::Object { .. } => format!("::comatype::Validate::validate({var}, &{path})?;\n"),
            Type::Array { item } => {
                let (i, it) = (format!("i{depth}"), format!("item{depth}"));
                let inner = self.validate_stmts(item, &it, &format!("format!(\"{{}}[{{}}]\", {path}, {i})"), depth + 1);
                if inner.is_empty() {
                    String::new()
                } else {
                    format!("for ({i}, {it}) in {var}.iter().enumerate() {{\n{inner}}}\n")
                }
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if let Some(vals) = literal_union(t) {
                    let list = vals.iter().map(|v| rs_string(v)).collect::<Vec<_>>().join(", ");
                    return format!("::comatype::validate::check_oneof(&{path}, {var}.as_str(), &[{list}])?;\n");
                }
                String::new()
            }
            Type::Null => String::new(),
        }
    }

    fn struct_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut lines = String::new();
        let mut checks = String::new();
        let mut seen = BTreeSet::new();
        for f in fields {
            let fname = snake(&f.name);
            if !seen.insert(fname.clone()) {
                return Err(format!("{name}: フィールド名 {fname} が重複します（{}）", f.name));
            }
            let (inner, nullable) = strip_null(&f.ty);
            let base = self.rty(inner, &format!("{name}{}", pascal(&f.name)), mode).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            let opt = f.optional || nullable;
            let ty = if opt { format!("Option<{base}>") } else { base };
            if mode == Mode::Json {
                let mut attrs = Vec::new();
                if fname.trim_start_matches("r#") != f.name {
                    attrs.push(format!("rename = {}", rs_string(&f.name)));
                }
                if f.optional {
                    attrs.push("default".into());
                    attrs.push("skip_serializing_if = \"Option::is_none\"".into());
                }
                if !attrs.is_empty() {
                    lines.push_str(&format!("#[serde({})]\n", attrs.join(", ")));
                }
            }
            lines.push_str(&format!("pub {fname}: {ty},\n"));
            let path = format!("::comatype::error::join(path, {})", rs_string(&f.name));
            if opt {
                let body = self.validate_stmts(inner, "v", &path, 0);
                if !body.is_empty() {
                    checks.push_str(&format!("if let Some(v) = &self.{fname} {{\n{body}}}\n"));
                }
            } else {
                checks.push_str(&self.validate_stmts(inner, &format!("&self.{fname}"), &path, 0));
            }
        }
        let derive = if mode == Mode::Json {
            format!("#[derive(Debug, Clone, Default, PartialEq, ::comatype::serde::Serialize, ::comatype::serde::Deserialize)]\n{SERDE}\n")
        } else if mode == Mode::Plain {
            "#[derive(Debug, Clone)]\n".to_string()
        } else {
            "#[derive(Debug, Clone, Default, PartialEq)]\n".to_string()
        };
        let validate = if mode == Mode::Plain {
            String::new()
        } else {
            format!("impl ::comatype::Validate for {name} {{\nfn validate(&self, path: &str) -> ::comatype::validate::VResult {{\n{checks}Ok(())\n}}\n}}\n")
        };
        Ok(format!("{derive}pub struct {name} {{\n{lines}}}\n\n{validate}"))
    }

    /// Named declaration: an object becomes a struct, anything else an alias
    fn named(&mut self, name: &str, t: &Type, mode: Mode) -> Result<String, String> {
        self.used_names.insert(name.to_string());
        let decl = match t {
            Type::Object { fields } => self.struct_decl(name, fields, mode)?,
            _ => {
                let (inner, nullable) = strip_null(t);
                let b = self.rty(inner, name, mode)?;
                format!("pub type {name} = {};\n", if nullable { format!("Option<{b}>") } else { b })
            }
        };
        let mut out = String::new();
        for e in self.extra.drain(..) {
            out.push_str(&e);
            out.push('\n');
        }
        out.push_str(&decl);
        Ok(out)
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        let name = {
            let mut cs = nt.name.chars();
            cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        };
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("Rust の型名 `{name}` が {prev} と {id} で重複しています"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

// ---- types.rs ----

fn types_file(svc: &Service, names: &BTreeMap<String, String>) -> Result<String, String> {
    let mut g = Gen { names, prefix: "", extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = g.struct_decl(name, fields, Mode::Json)?;
                for e in g.extra.drain(..) {
                    body.push_str(&e);
                    body.push('\n');
                }
                body.push_str(&decl);
                body.push('\n');
            }
            TypeDef::Enum { values } => {
                let mut variants = String::new();
                let mut as_str = String::new();
                let mut from = String::new();
                let mut seen = BTreeSet::new();
                for (i, v) in values.iter().enumerate() {
                    let var = pascal(v);
                    if !seen.insert(var.clone()) {
                        return Err(format!("{name}: enum の値 {var} が重複します（{v}）"));
                    }
                    let default = if i == 0 { "#[default]\n" } else { "" };
                    variants.push_str(&format!("{default}#[serde(rename = {})]\n{var},\n", rs_string(v)));
                    as_str.push_str(&format!("{name}::{var} => {},\n", rs_string(v)));
                    from.push_str(&format!("{} => Ok({name}::{var}),\n", rs_string(v)));
                }
                let all = values.join(" | ");
                body.push_str(&format!(
                    "#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, ::comatype::serde::Serialize, ::comatype::serde::Deserialize)]\n{SERDE}\npub enum {name} {{\n{variants}}}\n\n\
                     impl {name} {{\npub fn as_str(&self) -> &'static str {{\nmatch self {{\n{as_str}}}\n}}\n}}\n\n\
                     impl ::comatype::Validate for {name} {{\nfn validate(&self, _: &str) -> ::comatype::validate::VResult {{\nOk(())\n}}\n}}\n\n\
                     impl ::comatype::Wire for {name} {{\nfn to_wire(&self) -> Vec<String> {{\nvec![self.as_str().to_string()]\n}}\n\
                     fn from_wire(vals: &[String], _: bool) -> Result<Self, String> {{\nmatch vals.first().map(String::as_str) {{\n{from}Some(_) => Err({}.to_string()),\nNone => Err(\"必須です\".to_string()),\n}}\n}}\n}}\n\n",
                    rs_string(&format!("{all} のどれかにしてください"))
                ));
            }
        }
    }
    Ok(format!("{HEADER}\n{}", body.trim_end().to_string() + "\n"))
}

// ---- Endpoints ----

fn cookie_def_rs(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("None".to_string(), |s| format!("Some({})", rs_string(s)));
    format!(
        "::comatype::CookieDef {{ name: {}, http_only: {}, secure: {}, same_site: {}, path: {}, domain: {}, max_age: {} }}",
        rs_string(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("None".to_string(), |v| format!("Some({v})")),
    )
}

/// List of (header name, field access) for the header struct
fn wire_items(fields: &[Field], var: &str) -> String {
    fields
        .iter()
        .map(|f| format!("({}, ::comatype::Wire::to_wire(&{var}.{}))", rs_string(&f.name), snake(&f.name)))
        .collect::<Vec<_>>()
        .join(", ")
}

/// Expression that builds a struct. `values` is (field name, expression to extract)
fn wire_build(name: &str, fields: &[Field], values_fn: &str, split: bool) -> String {
    let inits: String = fields
        .iter()
        .map(|f| {
            format!("{}: ::comatype::wire::read(&{values_fn}({}), {}, {split})?,\n", snake(&f.name), rs_string(&f.name), rs_string(&f.name))
        })
        .collect();
    format!("{name} {{\n{inits}}}")
}

/// The `cache` setting (GET / QUERY only)
fn cache_rs(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let (mode, ttl) = match &ep.cache {
        None => return "None".to_string(),
        Some(CacheMode::Off) => ("Off", 0),
        Some(CacheMode::Memory { ttl_ms }) => ("Memory", *ttl_ms),
        Some(CacheMode::Cookie { ttl_ms }) => ("Cookie", *ttl_ms),
    };
    format!("Some(::comatype::CacheSpec {{ mode: ::comatype::CacheMode::{mode}, ttl_ms: {ttl} }})")
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role) -> Result<String, String> {
    let mut g = Gen { names, prefix: "super::types::", extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();
    let has_req_headers = !ep.request_headers.is_empty();

    if !ep.params.is_empty() {
        body.push_str(&g.struct_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
    }
    if !ep.search.is_empty() {
        body.push_str(&g.struct_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
    }
    if let Some(b) = &ep.body {
        body.push_str(&g.named("Body", b, Mode::Json).map_err(ctx)?);
    }
    if has_req_headers {
        body.push_str(&g.struct_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let fields: String =
            ctx_wrappers.iter().map(|w| format!("pub {}: super::init::{}Ctx,\n", snake(&w.name), pascal(&w.name))).collect();
        body.push_str(&format!("/// 有効なラッパーが足した値\n#[derive(Debug, Clone)]\npub struct Ctx {{\n{fields}}}\n\n"));
    }
    // Whole request
    let mut req_fields: Vec<(&str, &str)> = Vec::new();
    if !ep.params.is_empty() {
        req_fields.push(("params", "Params"));
    }
    if !ep.search.is_empty() {
        req_fields.push(("search", "Search"));
    }
    if has_req_headers {
        req_fields.push(("headers", "RequestHeaders"));
    }
    if ep.body.is_some() {
        req_fields.push(("body", "Body"));
    }
    if role == Role::Server {
        req_fields.push(("ctx", "Ctx"));
    }
    let has = |n: &str| req_fields.iter().any(|(f, _)| *f == n);
    let fields: String = req_fields.iter().map(|(n, t)| format!("pub {n}: {t},\n")).collect();
    let req_derive = if role == Role::Client { "Debug, Clone, Default" } else { "Debug, Clone" };
    body.push_str(&format!("/// リクエスト全体\n#[derive({req_derive})]\npub struct Request {{\n{fields}}}\n\n"));

    // Response
    let cookie = ep.cookie && svc.cookie.is_some();
    let mut variants = String::new();
    for r in &ep.responses {
        let c = r.status;
        let mut payload = Vec::new();
        if let Some(b) = &r.body {
            body.push_str(&g.named(&format!("S{c}Res"), b, Mode::Json).map_err(ctx)?);
            body.push('\n');
            payload.push(format!("S{c}Res"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.struct_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            payload.push(format!("S{c}Headers"));
        }
        variants.push_str(&if payload.is_empty() { format!("S{c},\n") } else { format!("S{c}({}),\n", payload.join(", ")) });
    }
    body.push_str(&format!("/// 全ステータスのレスポンス\n#[derive(Debug, Clone)]\npub enum Response {{\n{variants}}}\n\n"));
    if role == Role::Server && cookie {
        body.push_str("/// `Response` に cookie を足したもの（`.into()` で cookie なしにも、`.with_cookie(..)` で発行にもできる）\npub type Reply = ::comatype::s::Reply<Response>;\n\n");
    }

    // Descriptor
    let arg = if !ep.params.is_empty() || !ep.search.is_empty() || has_req_headers {
        "Request"
    } else if ep.body.is_some() {
        "Body"
    } else {
        "::comatype::NoArg"
    };
    let (arg_ty, req_ty, res_ty) = match role {
        Role::Client => (arg, "()", "Response"),
        Role::Server => ("()", "Request", if cookie { "Reply" } else { "Response" }),
    };
    let cookie_def = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_rs(c),
        _ => String::new(),
    };
    let (build_request, parse_response, parse_request, build_response) = match role {
        Role::Client => ("Some(build_request)", "Some(parse_response)", "None", "None"),
        Role::Server => ("None", "None", "Some(parse_request)", "Some(build_response)"),
    };
    body.push_str(&format!(
        "/// path とメソッド\npub static ENDPOINT: ::comatype::Endpoint<{arg_ty}, {req_ty}, {res_ty}> = ::comatype::Endpoint {{\nmethod: {},\npath: {},\nmodule: {},\nbase_url: {},\nwraps: &[{}],\ncookie: {},\ncookie_def: {},\ncache: {},\ncache_headers: &[{}],\nbuild_request: {build_request},\nparse_response: {parse_response},\nparse_request: {parse_request},\nbuild_response: {build_response},\n}};\n\n",
        rs_string(&ep.method),
        rs_string(&ep.path),
        rs_string(&ep.module),
        svc.base_url.as_ref().map_or("None".to_string(), |u| format!("Some({})", rs_string(u))),
        ep.wraps.iter().map(|w| rs_string(w)).collect::<Vec<_>>().join(", "),
        ep.cookie,
        if cookie_def.is_empty() { "None".to_string() } else { format!("Some({cookie_def})") },
        cache_rs(ep),
        if ep.cache.is_some() { ep.request_headers.iter().map(|h| rs_string(&h.name)).collect::<Vec<_>>().join(", ") } else { String::new() },
    ));

    match role {
        Role::Client => {
            let mut f = format!("fn build_request(arg: &{arg}) -> ::comatype::Result<::comatype::RawRequest> {{\nlet mut raw = ::comatype::RawRequest::new({}, {});\n", rs_string(&ep.method), rs_string(&ep.path));
            if arg == "Request" {
                if has("params") {
                    f.push_str(&format!(
                        "::comatype::Validate::validate(&arg.params, \"\")?;\n::comatype::wire::fill_path(&mut raw, &[{}])?;\n",
                        wire_items(&ep.params, "arg.params")
                    ));
                }
                if has("search") {
                    f.push_str(&format!(
                        "::comatype::Validate::validate(&arg.search, \"\")?;\n::comatype::wire::add_query(&mut raw, &[{}]);\n",
                        wire_items(&ep.search, "arg.search")
                    ));
                }
                if has("headers") {
                    f.push_str(&format!(
                        "::comatype::Validate::validate(&arg.headers, \"\")?;\n::comatype::wire::set_headers(&mut raw.headers, &[{}]);\n",
                        wire_items(&ep.request_headers, "arg.headers")
                    ));
                }
                if has("body") {
                    f.push_str("::comatype::wire::set_body(&mut raw, &arg.body)?;\n");
                }
            } else if arg == "Body" {
                f.push_str("::comatype::wire::set_body(&mut raw, arg)?;\n");
            }
            f.push_str("Ok(raw)\n}\n\n");
            body.push_str(&f);

            let mut p =
                String::from("fn parse_response(raw: &::comatype::RawResponse) -> ::comatype::Result<Response> {\nmatch raw.status {\n");
            for r in &ep.responses {
                let c = r.status;
                p.push_str(&format!("{c} => {{\n"));
                let mut payload = Vec::new();
                if r.body.is_some() {
                    p.push_str(&format!("let body = ::comatype::wire::decode_response_body::<S{c}Res>(raw)?.ok_or_else(|| ::comatype::error::fail_path(\"body\", \"必須です\"))?;\n"));
                    payload.push("body");
                }
                if !r.headers.is_empty() {
                    p.push_str(&format!(
                        "let headers = {};\n::comatype::Validate::validate(&headers, \"\")?;\n",
                        wire_build(&format!("S{c}Headers"), &r.headers, "::comatype::wire::header_values_of(raw)", true)
                    ));
                    payload.push("headers");
                }
                p.push_str(&if payload.is_empty() {
                    format!("Ok(Response::S{c})\n")
                } else {
                    format!("Ok(Response::S{c}({}))\n", payload.join(", "))
                });
                p.push_str("}\n");
            }
            p.push_str("_ => Err(::comatype::Error::UnexpectedStatus { status: raw.status, body: raw.body.clone() }),\n}\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            let mut f = String::from("fn parse_request(raw: &::comatype::RawRequest) -> ::comatype::Result<Request> {\n");
            let mut inits = Vec::new();
            if has("params") {
                f.push_str(&format!(
                    "let params = {};\n::comatype::Validate::validate(&params, \"\")?;\n",
                    wire_build("Params", &ep.params, "::comatype::wire::param_values_of(raw)", false)
                ));
                inits.push("params");
            }
            if has("search") {
                f.push_str(&format!(
                    "let search = {};\n::comatype::Validate::validate(&search, \"\")?;\n",
                    wire_build("Search", &ep.search, "::comatype::wire::query_values_of(raw)", false)
                ));
                inits.push("search");
            }
            if has("headers") {
                f.push_str(&format!(
                    "let headers = {};\n::comatype::Validate::validate(&headers, \"\")?;\n",
                    wire_build("RequestHeaders", &ep.request_headers, "::comatype::wire::request_header_values_of(raw)", true)
                ));
                inits.push("headers");
            }
            if has("body") {
                f.push_str("let body: Body = ::comatype::wire::get_body(raw)?;\n");
                inits.push("body");
            }
            if has("ctx") {
                let cs: String = ctx_wrappers
                    .iter()
                    .map(|w| {
                        format!(
                            "{}: ::comatype::ctx_value::<super::init::{}Ctx>(raw, {})?,\n",
                            snake(&w.name),
                            pascal(&w.name),
                            rs_string(&w.name)
                        )
                    })
                    .collect();
                f.push_str(&format!("let ctx = Ctx {{\n{cs}}};\n"));
                inits.push("ctx");
            }
            f.push_str(&format!("Ok(Request {{ {} }})\n}}\n\n", inits.join(", ")));
            body.push_str(&f);

            let mut b = format!("fn build_response(reply: {res_ty}) -> ::comatype::Result<::comatype::RawResponse> {{\n");
            if cookie {
                b.push_str("let (res, cookie) = (reply.response, reply.cookie);\n");
            } else {
                b.push_str("let res = reply;\n");
            }
            b.push_str("let mut out = match res {\n");
            for r in &ep.responses {
                let c = r.status;
                let mut pat = Vec::new();
                let mut st = format!("let mut out = ::comatype::RawResponse::new({c});\n");
                if r.body.is_some() {
                    pat.push("body");
                    st.push_str("::comatype::wire::set_response_body(&mut out, &body)?;\n");
                }
                if !r.headers.is_empty() {
                    pat.push("headers");
                    st.push_str(&format!(
                        "::comatype::Validate::validate(&headers, \"\")?;\n::comatype::wire::set_headers(&mut out.headers, &[{}]);\n",
                        wire_items(&r.headers, "headers")
                    ));
                }
                let pattern = if pat.is_empty() { format!("Response::S{c}") } else { format!("Response::S{c}({})", pat.join(", ")) };
                b.push_str(&format!("{pattern} => {{\n{st}out\n}}\n"));
            }
            b.push_str("};\n");
            if cookie {
                b.push_str("::comatype::s::apply_cookie(&mut out, ENDPOINT.cookie_def.as_ref(), cookie.as_ref())?;\n");
            }
            b.push_str("Ok(out)\n}\n");
            body.push_str(&b);
        }
    }

    Ok(format!("{HEADER}\n//! {} — {} {}\n\n{body}", ep.file, ep.method.to_uppercase(), ep.path))
}

// ---- init.rs ----

fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role) -> Result<String, String> {
    let mut g = Gen { names, prefix: "super::types::", extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut fields = String::new();
    let mut entries = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let (p, f) = (pascal(&w.name), snake(&w.name));
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("/// ラッパー {} が足す値（ハンドラの req.ctx.{f}）\n", w.name));
                body.push_str(&g.struct_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            body.push_str(&g.named(&format!("S{c}Res"), b, Mode::Json)?);
                            body.push_str(&format!("\n/// ラッパー {} が返せるステータス {c} のレスポンス\npub fn s{c}(body: S{c}Res) -> ::comatype::RawResponse {{\n::comatype::RawResponse::json({c}, Some(&body))\n}}\n\n", w.name));
                        }
                        None => body.push_str(&format!("/// ラッパー {} が返せるステータス {c} のレスポンス\npub fn s{c}() -> ::comatype::RawResponse {{\n::comatype::RawResponse::json::<()>({c}, None)\n}}\n\n", w.name)),
                    }
                }
                fields.push_str(&format!("pub {f}: ::comatype::s::ComatypeWrap<{ctx_name}>,\n"));
                entries.push_str(&format!("m.insert({}, ::comatype::s::adapt({}, self.{f}));\n", rs_string(&w.name), rs_string(&w.name)));
            }
            Role::Client => {
                fields.push_str(&format!("pub {f}: ::comatype::c::ComatypeWrap,\n"));
                entries.push_str(&format!("m.insert({}, self.{f});\n", rs_string(&w.name)));
            }
        }
    }
    let (set, wrap_ty) = match role {
        Role::Server => ("s", "::comatype::s::ServerWrap"),
        Role::Client => ("c", "::comatype::c::ComatypeWrap"),
    };
    body.push_str(&format!(
        "/// init.comat の `wrapper` ごとの実装。{set}::init に渡す\npub struct Wrappers {{\n{fields}}}\n\nimpl ::comatype::{set}::WrapperSet for Wrappers {{\nfn comatype_wrappers(self) -> std::collections::BTreeMap<&'static str, {wrap_ty}> {{\nlet mut m = std::collections::BTreeMap::new();\n{entries}m\n}}\n}}\n"
    ));
    Ok(format!("{HEADER}\n//! init.comat から生成\n\n{body}"))
}

