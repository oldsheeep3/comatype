const KEYWORDS: &[&str] = &[
    "break",
    "case",
    "chan",
    "const",
    "continue",
    "default",
    "defer",
    "else",
    "fallthrough",
    "for",
    "func",
    "go",
    "goto",
    "if",
    "import",
    "interface",
    "map",
    "package",
    "range",
    "return",
    "select",
    "struct",
    "switch",
    "type",
    "var",
];

const INITIALISMS: &[&str] = &[
    "id", "uid", "uuid", "url", "uri", "api", "http", "https", "ip", "json", "html", "xml", "sql", "ui", "tcp", "udp", "ttl", "cpu", "ssl",
    "tls", "rpc", "guid", "ascii", "eof", "uri",
];

/// `user/put__id` → `user_put_id` (Go package name)
pub fn package_name(module: &str) -> String {
    let n = module
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|w| !w.is_empty())
        .map(|w| w.to_ascii_lowercase())
        .collect::<Vec<_>>()
        .join("_");
    let n = if n.chars().next().is_none_or(|c| c.is_ascii_digit()) { format!("p_{n}") } else { n };
    if KEYWORDS.contains(&n.as_str()) {
        format!("{n}_")
    } else {
        n
    }
}

/// Splits into words (at separators and camelCase humps)
fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            continue;
        }
        let prev_lower = i > 0 && chars[i - 1].is_ascii_lowercase();
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_ascii_lowercase());
        let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
        if c.is_ascii_uppercase() && !cur.is_empty() && (prev_lower || (prev_upper && next_lower)) {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

/// Exported name (ID, URL, etc. are upper-cased following Go conventions)
pub fn pascal(s: &str) -> String {
    let out: String = words(s)
        .iter()
        .map(|w| {
            let l = w.to_ascii_lowercase();
            if INITIALISMS.contains(&l.as_str()) {
                l.to_ascii_uppercase()
            } else {
                let mut cs = w.chars();
                let f = cs.next().unwrap();
                f.to_ascii_uppercase().to_string() + cs.as_str()
            }
        })
        .collect();
    if out.chars().next().is_none_or(|c| c.is_ascii_digit()) {
        format!("F{out}")
    } else {
        out
    }
}

fn tag_quote(s: &str) -> Result<String, String> {
    if s.contains('`') {
        return Err(format!("Go の構造体タグに ` は使えません: {s}"));
    }
    Ok(format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")))
}

fn go_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"))
}

/// Whether `word.` is used (not as part of another identifier)
fn uses(body: &str, word: &str) -> bool {
    let pat = format!("{word}.");
    let b = body.as_bytes();
    let mut from = 0;
    while let Some(i) = body[from..].find(&pat) {
        let s = from + i;
        let ok = s == 0 || !(b[s - 1].is_ascii_alphanumeric() || b[s - 1] == b'_' || b[s - 1] == b'.');
        if ok {
            return true;
        }
        from = s + pat.len();
    }
    false
}

// ---- Types ----

struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    /// Prefix when referring to a type in another package (`types.`). Empty inside the types package
    prefix: &'a str,
    /// Declarations of named types created along the way
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone)]
struct GoTy {
    ty: String,
    /// Types that can be nil (slices, json.RawMessage)
    nilable: bool,
    /// `T | null`
    nullable: bool,
    /// Constraints added to the struct tag (min / max / pattern / oneof)
    tags: Vec<(String, String)>,
}

impl GoTy {
    fn plain(ty: &str) -> Self {
        GoTy { ty: ty.into(), nilable: false, nullable: false, tags: vec![] }
    }
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// json tag (body)
    Json,
    /// wire tag (path, query, headers). Scalars and their arrays only
    Wire,
    /// No tag (ctx)
    Plain,
}

impl<'a> Gen<'a> {
    fn ty(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<GoTy, String> {
        match t {
            Type::Scalar { name, constraint } => {
                let (ty, nilable) = match name.as_str() {
                    "string" => ("string", false),
                    "bool" => ("bool", false),
                    "int" => ("int", false),
                    "email" => ("comatype.Email", false),
                    "phone" => ("comatype.Phone", false),
                    "uuid" => ("comatype.Uuid", false),
                    "uuidv4" => ("comatype.Uuidv4", false),
                    "uuidv7" => ("comatype.Uuidv7", false),
                    "date" => ("comatype.Date", false),
                    "datetime" => ("time.Time", false),
                    "time" => ("comatype.Time", false),
                    "int64" => ("comatype.Int64", false),
                    "decimal" => ("comatype.Decimal", false),
                    "url" => ("comatype.Url", false),
                    "bytes" => ("[]byte", true),
                    _ => ("json.RawMessage", true),
                };
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                let mut g = GoTy { ty: ty.into(), nilable, nullable: false, tags: vec![] };
                match constraint {
                    Some(Constraint::Range { min, max }) => {
                        if let Some(m) = min {
                            g.tags.push(("min".into(), m.to_string()));
                        }
                        if let Some(m) = max {
                            g.tags.push(("max".into(), m.to_string()));
                        }
                    }
                    Some(Constraint::Pattern { value }) => g.tags.push(("pattern".into(), value.clone())),
                    None => {}
                }
                Ok(g)
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(GoTy::plain(&format!("{}{}", self.prefix, name)))
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.struct_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(GoTy::plain(&name))
            }
            Type::Array { item } => {
                let inner = self.ty(item, &format!("{hint}Item"), mode)?;
                if inner.nullable {
                    return Err("null を含む配列の要素は Go では未対応です".into());
                }
                Ok(GoTy { ty: format!("[]{}", inner.ty), nilable: true, nullable: false, tags: inner.tags })
            }
            Type::Union { variants } => {
                let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
                if non_null.len() != variants.len() && non_null.len() == 1 {
                    let mut inner = self.ty(non_null[0], hint, mode)?;
                    inner.nullable = true;
                    if !inner.nilable {
                        inner.ty = format!("*{}", inner.ty);
                    }
                    return Ok(inner);
                }
                if non_null.len() == variants.len() && variants.iter().all(|v| matches!(v, Type::Literal { .. })) {
                    let vals: Vec<&str> =
                        variants.iter().map(|v| if let Type::Literal { value } = v { value.as_str() } else { "" }).collect();
                    if vals.iter().any(|v| v.contains('|')) {
                        return Err("リテラルのユニオンの値に `|` は使えません".into());
                    }
                    let mut g = GoTy::plain("string");
                    g.tags.push(("oneof".into(), vals.join("|")));
                    return Ok(g);
                }
                Err("Go ではユニオン型を表せません（`T | null` と、文字列リテラルだけのユニオンに対応しています）".into())
            }
            Type::Literal { value } => {
                let mut g = GoTy::plain("string");
                g.tags.push(("oneof".into(), value.clone()));
                Ok(g)
            }
            Type::Null => Err("null だけの型は Go では未対応です".into()),
        }
    }

    fn is_enum(&self, id: &str) -> bool {
        self.names.get(&format!("enum:{id}")).is_some()
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    fn struct_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut lines = Vec::new();
        let mut seen = BTreeSet::new();
        for f in fields {
            let fname = pascal(&f.name);
            if !seen.insert(fname.clone()) {
                return Err(format!("{name}: フィールド名 {fname} が重複します（{}）", f.name));
            }
            let g = self.ty(&f.ty, &format!("{name}{fname}"), mode).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            let optional = f.optional || (mode == Mode::Wire && g.nullable);
            let (ty, omit) = match mode {
                Mode::Wire => (if optional && !g.ty.starts_with('*') { format!("*{}", g.ty) } else { g.ty.clone() }, false),
                _ => {
                    if f.optional {
                        (if g.nilable || g.ty.starts_with('*') { g.ty.clone() } else { format!("*{}", g.ty) }, true)
                    } else {
                        (g.ty.clone(), false)
                    }
                }
            };
            let mut tags = Vec::new();
            match mode {
                Mode::Json => tags.push(format!("json:{}", tag_quote(&format!("{}{}", f.name, if omit { ",omitempty" } else { "" }))?)),
                Mode::Wire => tags.push(format!("wire:{}", tag_quote(&f.name)?)),
                Mode::Plain => {}
            }
            if mode != Mode::Plain {
                for (k, v) in &g.tags {
                    tags.push(format!("{k}:{}", tag_quote(v)?));
                }
            }
            let tag = if tags.is_empty() { String::new() } else { format!(" `{}`", tags.join(" ")) };
            lines.push(format!("\t{fname} {ty}{tag}\n"));
        }
        Ok(format!("type {name} struct {{\n{}}}\n", lines.concat()))
    }

    /// Named declaration: an object becomes a struct, anything else an alias
    fn named(&mut self, name: &str, t: &Type, mode: Mode) -> Result<String, String> {
        self.used_names.insert(name.to_string());
        let mut out = String::new();
        let decl = match t {
            Type::Object { fields } => self.struct_decl(name, fields, mode)?,
            _ => {
                let g = self.ty(t, name, mode)?;
                format!("type {name} = {}\n", g.ty)
            }
        };
        for e in self.extra.drain(..) {
            out.push_str(&e);
            out.push('\n');
        }
        out.push_str(&decl);
        Ok(out)
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        // Use the declared name as is (only the first letter is upper-cased to export it)
        let name = {
            let mut cs = nt.name.chars();
            cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
        };
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("Go の型名 `{name}` が {prev} と {id} で重複しています"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

fn imports(body: &str, import_path: &str, runtime: &[&str]) -> String {
    let mut std = Vec::new();
    for (word, path) in [("json", "encoding/json"), ("fmt", "fmt"), ("time", "time")] {
        if uses(body, word) {
            std.push(format!("\t\"{path}\"\n"));
        }
    }
    let mut ext = Vec::new();
    if uses(body, "comatype") {
        ext.push(format!("\t\"{RUNTIME}/comatype\"\n"));
    }
    for r in runtime {
        ext.push(format!("\t\"{RUNTIME}/{r}\"\n"));
    }
    if uses(body, "types") {
        ext.push(format!("\t\"{import_path}/types\"\n"));
    }
    if uses(body, "comatype_init") {
        ext.push(format!("\tcomatype_init \"{import_path}/init\"\n"));
    }
    let mut groups = Vec::new();
    if !std.is_empty() {
        groups.push(std.concat());
    }
    if !ext.is_empty() {
        groups.push(ext.concat());
    }
    if groups.is_empty() {
        String::new()
    } else {
        format!("import (\n{})\n\n", groups.join("\n"))
    }
}

// ---- types/types.go ----

fn types_file(svc: &Service) -> Result<String, String> {
    let names = type_names(svc)?;
    let mut g = Gen { names: &names, prefix: "", extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = g.struct_decl(name, fields, Mode::Json)?;
                for e in g.extra.drain(..) {
                    body.push_str(&e);
                    body.push('\n');
                }
                body.push_str(&decl);
                body.push('\n');
            }
            TypeDef::Enum { values } => {
                let mut consts = String::new();
                let mut cases = Vec::new();
                for v in values {
                    let c = format!("{name}{}", pascal(v));
                    consts.push_str(&format!("\t{c} {name} = {}\n", go_string(v)));
                    cases.push(c);
                }
                body.push_str(&format!(
                    "type {name} string\n\nconst (\n{consts})\n\nfunc (v {name}) Validate() error {{\n\tswitch v {{\n\tcase {}:\n\t\treturn nil\n\t}}\n\treturn fmt.Errorf(\"{} のどれかにしてください\")\n}}\n\n",
                    cases.join(", "),
                    values.join(" | ")
                ));
            }
        }
    }
    let imp = imports(&body, "", &[]);
    Ok(format!("{HEADER}\npackage types\n\n{imp}{}", body.trim_end().to_string() + "\n"))
}

// ---- Status and request ----

fn request_arg(ep: &Endpoint) -> &'static str {
    if !ep.params.is_empty() || !ep.search.is_empty() {
        "Request"
    } else if ep.body.is_some() {
        "Body"
    } else {
        "comatype.NoArg"
    }
}

fn cookie_def_go(c: &CookieDef) -> String {
    let mut parts = vec![format!("Name: {}", go_string(&c.name))];
    if c.settings.get("httpOnly").map(String::as_str) == Some("true") {
        parts.push("HTTPOnly: true".into());
    }
    if c.settings.get("secure").map(String::as_str) == Some("true") {
        parts.push("Secure: true".into());
    }
    for (k, f) in [("sameSite", "SameSite"), ("path", "Path"), ("domain", "Domain")] {
        if let Some(v) = c.settings.get(k) {
            parts.push(format!("{f}: {}", go_string(v)));
        }
    }
    if let Some(v) = c.settings.get("maxAge") {
        parts.push(format!("MaxAge: comatype.Ptr({v})"));
    }
    format!("&comatype.CookieDef{{{}}}", parts.join(", "))
}

fn endpoint_file(svc: &Service, ep: &Endpoint, role: Role, import_path: &str) -> Result<String, String> {
    let names = type_names(svc)?;
    let pkg = package_name(&ep.module);
    let mut g = Gen { names: &names, prefix: "types.", extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();

    // Request
    let mut req_fields: Vec<(String, String)> = Vec::new(); // (field name, type)
    if !ep.params.is_empty() {
        body.push_str(&g.struct_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
        body.push('\n');
        req_fields.push(("Params".into(), "Params".into()));
    }
    if !ep.search.is_empty() {
        body.push_str(&g.struct_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
        body.push('\n');
        req_fields.push(("Search".into(), "Search".into()));
    }
    if let Some(b) = &ep.body {
        let decl = g.named("Body", b, Mode::Json).map_err(ctx)?;
        body.push_str(&decl);
        body.push('\n');
        req_fields.push(("Body".into(), "Body".into()));
    }
    if !ep.request_headers.is_empty() {
        body.push_str(&g.struct_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
        body.push('\n');
        req_fields.push(("Headers".into(), "RequestHeaders".into()));
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let embeds: String = ctx_wrappers.iter().map(|w| format!("\tcomatype_init.{}Ctx\n", pascal(&w.name))).collect();
        body.push_str(&format!("// Ctx は、有効なラッパーが足した値\ntype Ctx struct {{\n{embeds}}}\n\n"));
        req_fields.push(("Ctx".into(), "Ctx".into()));
    }
    let fields: String = req_fields.iter().map(|(n, t)| format!("\t{n} {t}\n")).collect();
    body.push_str(&format!("// Request はリクエスト全体\ntype Request struct {{\n{fields}}}\n\n"));

    // Response
    let cookie = ep.cookie && svc.cookie.is_some();
    let mut resp_fields = String::new();
    let mut ctor = String::new();
    for r in &ep.responses {
        let c = r.status;
        let (res, hdr) = (format!("S{c}Res"), format!("S{c}Headers"));
        if let Some(b) = &r.body {
            let decl = g.named(&res, b, Mode::Json).map_err(ctx)?;
            body.push_str(&decl);
            body.push('\n');
            resp_fields.push_str(&format!("\tS{c} *{res}\n"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.struct_decl(&hdr, &r.headers, Mode::Wire).map_err(ctx)?);
            body.push('\n');
            resp_fields.push_str(&format!("\tS{c}Headers *{hdr}\n"));
        }
        if role == Role::Server {
            // Only required headers become constructor arguments (optional headers are attached with WithS200Headers)
            let required = r.headers.iter().any(|h| !h.optional);
            let (args, init) = match (r.body.is_some(), required) {
                (true, true) => (format!("body *{res}, headers *{hdr}"), format!("S{c}: body, S{c}Headers: headers")),
                (true, false) => (format!("body *{res}"), format!("S{c}: body")),
                (false, true) => (format!("_ *comatype.NoArg, headers *{hdr}"), format!("S{c}Headers: headers")),
                (false, false) => (String::new(), String::new()),
            };
            let sep = if init.is_empty() { "" } else { ", " };
            ctor.push_str(&format!("// S{c} はステータス {c} のレスポンスを作る\nfunc S{c}({args}) Response {{\n\treturn Response{{Status: {c}{sep}{init}}}\n}}\n\n"));
            if !r.headers.is_empty() {
                ctor.push_str(&format!("// WithS{c}Headers はステータス {c} のレスポンスヘッダを付ける\nfunc (r Response) WithS{c}Headers(h *{hdr}) Response {{\n\tr.S{c}Headers = h\n\treturn r\n}}\n\n"));
            }
        }
    }
    if role == Role::Server && cookie {
        resp_fields.push_str("\t// Cookie は発行する cookie（WithCookie / ClearCookie で付ける）\n\tCookie *comatype.CookieValue\n");
    }
    body.push_str(&format!(
        "// Response は全ステータスのレスポンス。Status のフィールドだけが入る\ntype Response struct {{\n\tStatus int\n{resp_fields}}}\n\n"
    ));
    body.push_str(&ctor);
    if role == Role::Server && cookie {
        body.push_str("// WithCookie は init.comat の cookie を発行する\nfunc (r Response) WithCookie(value string, opts ...comatype.CookieOption) Response {\n\tv := &comatype.CookieValue{Value: value}\n\tfor _, o := range opts {\n\t\to(v)\n\t}\n\tr.Cookie = v\n\treturn r\n}\n\n// ClearCookie は cookie を削除する\nfunc (r Response) ClearCookie() Response {\n\tr.Cookie = &comatype.CookieValue{Delete: true}\n\treturn r\n}\n\n");
    }
    let has = |n: &str| req_fields.iter().any(|(f, _)| f == n);

    // Descriptor
    let arg = request_arg(ep);
    let cookie_def = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => Some(cookie_def_go(c)),
        _ => None,
    };
    if let Some(d) = &cookie_def {
        body.push_str(&format!("var cookieDef = {d}\n\n"));
    }
    let mut desc = format!(
        "// Endpoint は path とメソッド\nvar Endpoint = &comatype.Endpoint[{arg}, Request, Response]{{\n\tMethod: {},\n\tPath: {},\n\tModule: {},\n",
        go_string(&ep.method),
        go_string(&ep.path),
        go_string(&ep.module)
    );
    if let Some(u) = &svc.base_url {
        desc.push_str(&format!("\tBaseURL: {},\n", go_string(u)));
    }
    desc.push_str(&format!("\tWraps: []string{{{}}},\n", ep.wraps.iter().map(|w| go_string(w)).collect::<Vec<_>>().join(", ")));
    desc.push_str(&format!("\tCookie: {},\n", ep.cookie));
    if let Some(c) = &ep.cache {
        use comatype_core::ast::CacheMode;
        let (mode, ttl) = match c {
            CacheMode::Off => ("off", 0),
            CacheMode::Memory { ttl_ms } => ("memory", *ttl_ms),
            CacheMode::Cookie { ttl_ms } => ("cookie", *ttl_ms),
        };
        desc.push_str(&format!("\tCache: &comatype.CacheSpec{{Mode: \"{mode}\", TTLMillis: {ttl}}},\n"));
        let names: Vec<String> = ep.request_headers.iter().map(|h| go_string(&h.name)).collect();
        desc.push_str(&format!("\tCacheHeaders: []string{{{}}},\n", names.join(", ")));
    }
    if cookie_def.is_some() {
        desc.push_str("\tCookieDef: cookieDef,\n");
    }
    match role {
        Role::Client => desc.push_str("\tBuildRequest: buildRequest,\n\tParseResponse: parseResponse,\n"),
        Role::Server => desc.push_str("\tParseRequest: parseRequest,\n\tBuildResponse: buildResponse,\n"),
    }
    desc.push_str("}\n\n");
    body.push_str(&desc);

    match role {
        Role::Client => {
            // arg → RawRequest
            let mut f = format!(
                "func buildRequest(arg {arg}) (*comatype.RawRequest, error) {{\n\traw := comatype.NewRawRequest({}, {})\n",
                go_string(&ep.method),
                go_string(&ep.path)
            );
            if arg == "Request" {
                for (name, call) in [("Params", "SetParams"), ("Search", "SetQuery"), ("Headers", "SetHeaders"), ("Body", "SetBody")] {
                    if has(name) {
                        f.push_str(&format!("\tif err := comatype.{call}(raw, &arg.{name}); err != nil {{\n\t\treturn nil, err\n\t}}\n"));
                    }
                }
            } else if arg == "Body" {
                f.push_str("\tif err := comatype.SetBody(raw, &arg); err != nil {\n\t\treturn nil, err\n\t}\n");
            } else {
                f.push_str("\t_ = arg\n");
            }
            f.push_str("\treturn raw, nil\n}\n\n");
            body.push_str(&f);
            // RawResponse → Response
            let mut p = String::from("func parseResponse(raw *comatype.RawResponse) (Response, error) {\n\tres := Response{Status: raw.Status}\n\tswitch raw.Status {\n");
            for r in &ep.responses {
                let c = r.status;
                p.push_str(&format!("\tcase {c}:\n"));
                if r.body.is_some() {
                    p.push_str(&format!("\t\tvar v S{c}Res\n\t\tok, err := comatype.DecodeResponseBody(raw, &v)\n\t\tif err != nil {{\n\t\t\treturn res, err\n\t\t}}\n\t\tif ok {{\n\t\t\tres.S{c} = &v\n\t\t}}\n"));
                }
                if !r.headers.is_empty() {
                    p.push_str(&format!("\t\tvar h S{c}Headers\n\t\tif err := comatype.DecodeHeader(raw.Header, &h); err != nil {{\n\t\t\treturn res, err\n\t\t}}\n\t\tres.S{c}Headers = &h\n"));
                }
            }
            p.push_str("\tdefault:\n\t\treturn res, &comatype.UnexpectedStatusError{Status: raw.Status, Body: raw.Body}\n\t}\n\treturn res, nil\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            // RawRequest → Request
            let mut f = String::from("func parseRequest(raw *comatype.RawRequest) (Request, error) {\n\tvar req Request\n");
            for (name, call) in [("Params", "GetParams"), ("Search", "GetQuery"), ("Headers", "GetHeaders"), ("Body", "GetBody")] {
                if has(name) {
                    f.push_str(&format!("\tif err := comatype.{call}(raw, &req.{name}); err != nil {{\n\t\treturn req, err\n\t}}\n"));
                }
            }
            for w in &ctx_wrappers {
                let p = pascal(&w.name);
                f.push_str(&format!("\treq.Ctx.{p}Ctx = comatype.CtxValue[comatype_init.{p}Ctx](raw, {})\n", go_string(&w.name)));
            }
            f.push_str("\treturn req, nil\n}\n\n");
            body.push_str(&f);
            // Response → RawResponse
            let mut b = String::from("func buildResponse(r Response) (comatype.RawResponse, error) {\n\tout := comatype.NewRawResponse(r.Status)\n\tswitch r.Status {\n");
            for r in &ep.responses {
                let c = r.status;
                b.push_str(&format!("\tcase {c}:\n"));
                if r.body.is_some() {
                    b.push_str(&format!("\t\tif r.S{c} != nil {{\n\t\t\tif err := comatype.SetResponseBody(&out, r.S{c}); err != nil {{\n\t\t\t\treturn out, err\n\t\t\t}}\n\t\t}}\n"));
                }
                if !r.headers.is_empty() {
                    b.push_str(&format!("\t\tif r.S{c}Headers != nil {{\n\t\t\tif err := comatype.EncodeHeader(out.Header, r.S{c}Headers); err != nil {{\n\t\t\t\treturn out, err\n\t\t\t}}\n\t\t}}\n"));
                }
            }
            b.push_str(&format!("\tdefault:\n\t\treturn out, fmt.Errorf(\"s%d は {} に宣言されていません\", r.Status)\n\t}}\n", ep.module));
            if cookie {
                b.push_str("\tif r.Cookie != nil {\n\t\tline, err := comatype.SerializeSetCookie(cookieDef, r.Cookie)\n\t\tif err != nil {\n\t\t\treturn out, err\n\t\t}\n\t\tout.SetCookies = append(out.SetCookies, line)\n\t}\n");
            }
            b.push_str("\treturn out, nil\n}\n");
            body.push_str(&b);
        }
    }

    let imp = imports(&body, import_path, &[]);
    Ok(format!("{HEADER}\n// {} — {} {}\npackage {pkg}\n\n{imp}{body}", ep.file, ep.method.to_uppercase(), ep.path))
}

// ---- init/init.go ----

fn init_file(svc: &Service, role: Role, import_path: &str) -> Result<String, String> {
    let names = type_names(svc)?;
    let mut g = Gen { names: &names, prefix: "types.", extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut fields = String::new();
    let mut entries = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let p = pascal(&w.name);
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("// {ctx_name} は、ラッパー {} が足す値（ハンドラの req.Ctx.{ctx_name}）\n", w.name));
                body.push_str(&g.struct_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            body.push_str(&g.named(&format!("S{c}Res"), b, Mode::Json)?);
                            body.push_str(&format!("\n// S{c} はラッパー {} が返せるステータス {c} のレスポンス\nfunc S{c}(body *S{c}Res) comatype.RawResponse {{\n\treturn comatype.JSONResponse({c}, body)\n}}\n\n", w.name));
                        }
                        None => body.push_str(&format!("// S{c} はラッパー {} が返せるステータス {c} のレスポンス\nfunc S{c}() comatype.RawResponse {{\n\treturn comatype.JSONResponse({c}, nil)\n}}\n\n", w.name)),
                    }
                }
                fields.push_str(&format!("\t{p} s.ComatypeWrap[{ctx_name}]\n"));
                entries.push_str(&format!("\t\t{}: s.Adapt({}, w.{p}),\n", go_string(&w.name), go_string(&w.name)));
            }
            Role::Client => {
                fields.push_str(&format!("\t{p} c.ComatypeWrap\n"));
                entries.push_str(&format!("\t\t{}: w.{p},\n", go_string(&w.name)));
            }
        }
    }
    let (set, ty) = match role {
        Role::Server => ("s", "comatype.ServerWrap"),
        Role::Client => ("c", "c.ComatypeWrap"),
    };
    body.push_str(&format!(
        "// Wrappers は init.comat の `wrapper` ごとの実装。{}.Init に渡す\ntype Wrappers struct {{\n{fields}}}\n\n// ComatypeWrappers は {}.Init が読む\nfunc (w Wrappers) ComatypeWrappers() map[string]{ty} {{\n\treturn map[string]{ty}{{\n{entries}\t}}\n}}\n",
        set, set
    ));
    let imp = imports(&body, import_path, &[set]);
    Ok(format!("{HEADER}\n// init.comat から生成\npackage comatype_init\n\n{imp}{body}"))
}

