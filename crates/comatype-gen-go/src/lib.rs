//! Generates Go code from the IR.
//!
//! Output (under `<out>`; the package import path is `import_path`):
//!   types/types.go        named types (structs, enums)                  package types
//!   init/init.go          wrappers, ctx, wrapper statuses              package comatype_init
//!   <module>/endpoint.go  one per endpoint (e.g. user/put__id/)        package user_put_id
//!
//! The contents of init and endpoint differ between client and server (matching the runtime's c / s).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "// Code generated by comatype generate. DO NOT EDIT.\n";
const RUNTIME: &str = "github.com/oldsheeep3/comatype/packages/go";

pub fn generate(svc: &Service, role: Role, import_path: &str) -> Result<Vec<GenFile>, String> {
    let mut files = vec![GenFile { path: "types/types.go".into(), content: types_file(svc)? }];
    files.push(GenFile { path: "init/init.go".into(), content: init_file(svc, role, import_path)? });
    for ep in &svc.endpoints {
        let top = ep.module.split('/').next().unwrap_or("");
        if top == "types" || top == "init" {
            return Err(format!(
                "{} は Go では生成先のディレクトリ `{top}` が types / init と衝突します（ファイルかディレクトリの名前を変えてください）",
                ep.file
            ));
        }
        files.push(GenFile { path: format!("{}/endpoint.go", ep.module), content: endpoint_file(svc, ep, role, import_path)? });
    }
    Ok(files)
}

