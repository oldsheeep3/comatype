//! Generates Kotlin code from the IR (data classes + sealed interfaces). The runtime is Java's `comatype` package (packages/java).
//!
//! Output (under `<out>`; `<out>` is the directory of a Kotlin package; default `src/main/kotlin/comatype/gen`):
//!   Types.kt            named types (data classes, enums)
//!   Init.kt             wrappers, ctx, wrapper statuses
//!   <Module>.kt         one per endpoint (e.g. UserPutId.kt; module names are PascalCase)
//!
//! The contents of Init and the endpoints differ between client and server (matching the runtime's C / S).

use comatype_core::ast::Constraint;
use comatype_core::ir::*;
use std::collections::{BTreeMap, BTreeSet};

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Role {
    Client,
    Server,
}

#[derive(Debug)]
pub struct GenFile {
    /// Path relative to `<out>`
    pub path: String,
    pub content: String,
}

const HEADER: &str = "// Code generated by comatype generate. DO NOT EDIT.\n@file:Suppress(\"UNUSED_VARIABLE\", \"UNUSED_PARAMETER\", \"RedundantVisibilityModifier\", \"unused\", \"UNCHECKED_CAST\")\n";

pub fn generate(svc: &Service, role: Role, package: &str) -> Result<Vec<GenFile>, String> {
    let names = type_names(svc)?;
    let mut files = vec![
        GenFile { path: "Types.kt".into(), content: types_file(svc, &names, package)? },
        GenFile { path: "Init.kt".into(), content: init_file(svc, &names, role, package)? },
    ];
    let mut seen: BTreeMap<String, &str> = BTreeMap::new();
    for ep in &svc.endpoints {
        let m = module_class(&ep.module);
        if m == "Types" || m == "Init" {
            return Err(format!("{} は Kotlin では生成先のオブジェクト名 `{m}` が Types / Init と衝突します（ファイルかディレクトリの名前を変えてください）", ep.file));
        }
        if let Some(prev) = seen.insert(m.clone(), &ep.file) {
            return Err(format!("{} と {prev} が同じオブジェクト名 `{m}` になります", ep.file));
        }
        files.push(GenFile { path: format!("{m}.kt"), content: endpoint_file(svc, &names, ep, role, package)? });
    }
    for f in &mut files {
        f.content = reindent(&f.content);
    }
    Ok(files)
}

/// Fixes indentation by brace depth (the generated fragments carry no indentation for nesting)
fn reindent(code: &str) -> String {
    let mut depth: i32 = 0;
    let mut out = String::new();
    for line in code.lines() {
        let t = line.trim();
        if t.is_empty() {
            out.push('\n');
            continue;
        }
        let opens = t.matches('{').count() as i32;
        let closes = t.matches('}').count() as i32;
        let leading = t.chars().take_while(|c| *c == '}' || *c == ')').filter(|c| *c == '}').count() as i32;
        let d = (depth - leading).max(0);
        // Comment lines (/// and * ) are aligned to their own column
        out.push_str(&"    ".repeat(d as usize));
        out.push_str(if t.starts_with('*') { &line.trim_end()[line.len() - line.trim_start().len()..] } else { t });
        out.push('\n');
        depth = (depth + opens - closes).max(0);
    }
    out
}

// ---- Names ----

const KEYWORDS: &[&str] = &[
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null", "object", "package", "return", "super",
    "this", "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while", "by", "catch", "constructor", "delegate", "dynamic", "field", "file",
    "finally", "get", "import", "init", "param", "property", "receiver", "set", "setparam", "value", "where",
];

pub fn words(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let chars: Vec<char> = s.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        if !c.is_ascii_alphanumeric() {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            continue;
        }
        let prev_lower = i > 0 && chars[i - 1].is_ascii_lowercase();
        let next_lower = chars.get(i + 1).map_or(false, |n| n.is_ascii_lowercase());
        let prev_upper = i > 0 && chars[i - 1].is_ascii_uppercase();
        if c.is_ascii_uppercase() && !cur.is_empty() && (prev_lower || (prev_upper && next_lower)) {
            out.push(std::mem::take(&mut cur));
        }
        cur.push(c);
    }
    if !cur.is_empty() {
        out.push(cur);
    }
    out
}

fn cap(w: &str) -> String {
    let mut cs = w.chars();
    cs.next().map(|f| f.to_ascii_uppercase().to_string() + cs.as_str()).unwrap_or_default()
}

pub fn pascal(s: &str) -> String {
    let out: String = words(s).iter().map(|w| cap(&w.to_ascii_lowercase())).collect::<Vec<_>>().concat();
    if out.chars().next().map_or(true, |c| c.is_ascii_digit()) { format!("V{out}") } else { out }
}

/// `user/put__id` → `UserPutId`
pub fn module_class(module: &str) -> String {
    let out: String = module.split(|c: char| !c.is_ascii_alphanumeric()).filter(|w| !w.is_empty()).map(cap).collect();
    if out.chars().next().map_or(true, |c| c.is_ascii_digit()) { format!("M{out}") } else { out }
}

/// Property name (camelCase)
pub fn camel(s: &str) -> String {
    let mut out = String::new();
    for (i, w) in words(s).iter().enumerate() {
        let w = w.to_ascii_lowercase();
        out.push_str(&if i == 0 { w } else { cap(&w) });
    }
    if out.chars().next().map_or(true, |c| c.is_ascii_digit()) {
        out = format!("f{}", cap(&out));
    }
    if KEYWORDS.contains(&out.as_str()) { format!("{out}_") } else { out }
}

pub fn constant(s: &str) -> String {
    let out = words(s).iter().map(|w| w.to_ascii_uppercase()).collect::<Vec<_>>().join("_");
    if out.chars().next().map_or(true, |c| c.is_ascii_digit()) { format!("V_{out}") } else { out }
}

fn kstr(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '"' => o.push_str("\\\""),
            '$' => o.push_str("\\$"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

// ---- Types ----

struct Gen<'a> {
    names: &'a BTreeMap<String, String>,
    /// Prefix when referring to a type in another object (`Types.`). Empty inside Types
    prefix: &'a str,
    extra: Vec<String>,
    used_names: BTreeSet<String>,
}

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    Json,
    Wire,
    Plain,
}

fn strip_null(t: &Type) -> (&Type, bool) {
    if let Type::Union { variants } = t {
        let non_null: Vec<&Type> = variants.iter().filter(|v| !matches!(v, Type::Null)).collect();
        if non_null.len() == 1 && non_null.len() != variants.len() {
            return (non_null[0], true);
        }
    }
    (t, false)
}

fn literal_union(t: &Type) -> Option<Vec<String>> {
    match t {
        Type::Literal { value } => Some(vec![value.clone()]),
        Type::Union { variants } if variants.iter().all(|v| matches!(v, Type::Literal { .. })) => {
            Some(variants.iter().map(|v| if let Type::Literal { value } = v { value.clone() } else { String::new() }).collect())
        }
        _ => None,
    }
}

fn scalar_ty(name: &str) -> &'static str {
    match name {
        "string" => "String",
        "bool" => "Boolean",
        "int" | "int64" => "Long",
        "email" => "comatype.Email",
        "phone" => "comatype.Phone",
        "uuid" | "uuidv4" | "uuidv7" => "java.util.UUID",
        "date" => "java.time.LocalDate",
        "datetime" => "java.time.Instant",
        "time" => "java.time.LocalTime",
        "decimal" => "java.math.BigDecimal",
        "url" => "java.net.URI",
        "bytes" => "ByteArray",
        _ => "Any",
    }
}

impl<'a> Gen<'a> {
    fn is_enum(&self, id: &str) -> bool {
        self.names.contains_key(&format!("enum:{id}"))
    }

    fn unique(&mut self, hint: &str) -> String {
        let mut n = hint.to_string();
        let mut i = 2;
        while !self.used_names.insert(n.clone()) {
            n = format!("{hint}{i}");
            i += 1;
        }
        n
    }

    /// Kotlin type (the caller adds `?` for nullable)
    fn kty(&mut self, t: &Type, hint: &str, mode: Mode) -> Result<String, String> {
        match t {
            Type::Scalar { name, .. } => {
                if mode == Mode::Wire && matches!(name.as_str(), "bytes" | "json") {
                    return Err(format!("{name} は path・クエリ・ヘッダには使えません"));
                }
                Ok(scalar_ty(name).to_string())
            }
            Type::Ref { id, .. } => {
                let name = self.names.get(id).ok_or_else(|| format!("未知の型 {id}"))?;
                if mode == Mode::Wire && !self.is_enum(id) {
                    return Err(format!("{name} はオブジェクトなので path・クエリ・ヘッダには使えません"));
                }
                Ok(format!("{}{}", self.prefix, name))
            }
            Type::Object { fields } => {
                if mode == Mode::Wire {
                    return Err("オブジェクトは path・クエリ・ヘッダには使えません".into());
                }
                let name = self.unique(hint);
                let decl = self.class_decl(&name, fields, mode)?;
                self.extra.push(decl);
                Ok(name)
            }
            Type::Array { item } => {
                if strip_null(item).1 {
                    return Err("null を含む配列の要素は Kotlin では未対応です".into());
                }
                Ok(format!("List<{}>", self.kty(item, &format!("{hint}Item"), mode)?))
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if literal_union(t).is_some() {
                    return Ok("String".into());
                }
                Err("Kotlin ではユニオン型を表せません（`T | null` と、文字列リテラルだけのユニオンに対応しています）".into())
            }
            Type::Null => Err("null だけの型は Kotlin では未対応です".into()),
        }
    }

    fn dec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "comatype.Codec::string",
                "bool" => "comatype.Codec::bool",
                "int" => "comatype.Codec::integer",
                "int64" => "comatype.Codec::int64",
                "email" => "comatype.Codec::email",
                "phone" => "comatype.Codec::phone",
                "uuid" => "comatype.Codec::uuid",
                "uuidv4" => "comatype.Codec::uuidv4",
                "uuidv7" => "comatype.Codec::uuidv7",
                "date" => "comatype.Codec::date",
                "datetime" => "comatype.Codec::datetime",
                "time" => "comatype.Codec::time",
                "decimal" => "comatype.Codec::decimal",
                "url" => "comatype.Codec::url",
                "bytes" => "comatype.Codec::bytes",
                _ => "comatype.Codec::json",
            }
            .to_string(),
            Type::Ref { id, .. } => format!("{}{}.Companion::decode", self.prefix, self.names.get(id).cloned().unwrap_or_default()),
            Type::Array { item } => format!("comatype.Codec.Decoder {{ j, p -> comatype.Codec.list(j, p, {}) }}", self.dec(item)),
            _ => "comatype.Codec::string".into(),
        }
    }

    fn wdec(&self, t: &Type) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "string" => "comatype.Wire::string",
                "bool" => "comatype.Wire::bool",
                "int" | "int64" => "comatype.Wire::integer",
                "email" => "comatype.Wire::email",
                "phone" => "comatype.Wire::phone",
                "uuid" => "comatype.Wire::uuid",
                "uuidv4" => "comatype.Wire::uuidv4",
                "uuidv7" => "comatype.Wire::uuidv7",
                "date" => "comatype.Wire::date",
                "datetime" => "comatype.Wire::datetime",
                "time" => "comatype.Wire::time",
                "decimal" => "comatype.Wire::decimal",
                "url" => "comatype.Wire::url",
                _ => "comatype.Wire::string",
            }
            .to_string(),
            Type::Ref { id, .. } => format!("{}{}.Companion::parse", self.prefix, self.names.get(id).cloned().unwrap_or_default()),
            _ => "comatype.Wire::string".into(),
        }
    }

    /// Expression that turns a Kotlin value into a JSON tree (`e` is assumed non-null)
    fn enc(&self, t: &Type, e: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, .. } => match name.as_str() {
                "int64" => format!("comatype.Codec.int64({e})"),
                "decimal" => format!("comatype.Codec.decimal({e})"),
                "time" => format!("comatype.Codec.time({e})"),
                "bytes" => format!("comatype.Codec.bytes({e})"),
                "email" | "phone" => format!("{e}.value()"),
                "uuid" | "uuidv4" | "uuidv7" | "date" | "datetime" | "url" => format!("{e}.toString()"),
                _ => e.to_string(),
            },
            Type::Ref { .. } | Type::Object { .. } => format!("{e}.encode()"),
            Type::Array { item } => {
                let x = format!("x{depth}");
                format!("comatype.Codec.list({e}) {{ {x} -> {} }}", self.enc(item, &x, depth + 1))
            }
            _ => e.to_string(),
        }
    }

    fn vstmts(&self, t: &Type, var: &str, path: &str, depth: usize) -> String {
        match t {
            Type::Scalar { name, constraint } => {
                let mut s = String::new();
                match name.as_str() {
                    "email" | "phone" => s.push_str(&format!("{var}.validate({path})\n")),
                    "uuidv4" => s.push_str(&format!("comatype.Check.uuidVersion({path}, {var}, 4)\n")),
                    "uuidv7" => s.push_str(&format!("comatype.Check.uuidVersion({path}, {var}, 7)\n")),
                    _ => {}
                }
                match constraint {
                    Some(Constraint::Range { min, max }) => {
                        let opt = |v: &Option<i64>| v.map_or("null".to_string(), |n| format!("{n}L"));
                        match name.as_str() {
                            "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" => {
                                s.push_str(&format!("comatype.Check.len({path}, comatype.Wire.str({var}), {}, {})\n", opt(min), opt(max)))
                            }
                            "int" | "int64" => s.push_str(&format!("comatype.Check.range({path}, {var}.toDouble(), {}, {})\n", opt(min), opt(max))),
                            "decimal" => s.push_str(&format!("comatype.Check.range({path}, {var}, {}, {})\n", opt(min), opt(max))),
                            _ => {}
                        }
                    }
                    Some(Constraint::Pattern { value }) => {
                        if matches!(name.as_str(), "string" | "email" | "phone" | "url" | "date" | "time" | "datetime" | "uuid" | "uuidv4" | "uuidv7" | "decimal") {
                            s.push_str(&format!("comatype.Check.pattern({path}, comatype.Wire.str({var}), {})\n", kstr(value)));
                        }
                    }
                    None => {}
                }
                s
            }
            Type::Ref { id, .. } => {
                if self.is_enum(id) {
                    String::new()
                } else {
                    format!("{var}.validate({path})\n")
                }
            }
            Type::Object { .. } => format!("{var}.validate({path})\n"),
            Type::Array { item } => {
                let (i, it) = (format!("i{depth}"), format!("item{depth}"));
                let inner = self.vstmts(item, &it, &format!("{path} + \"[\" + {i} + \"]\""), depth + 1);
                if inner.is_empty() {
                    String::new()
                } else {
                    format!("for (({i}, {it}) in {var}.withIndex()) {{\n{inner}}}\n")
                }
            }
            Type::Union { .. } | Type::Literal { .. } => {
                if let Some(vals) = literal_union(t) {
                    let list = vals.iter().map(|v| kstr(v)).collect::<Vec<_>>().join(", ");
                    return format!("comatype.Check.oneOf({path}, {var}, {list})\n");
                }
                String::new()
            }
            Type::Null => String::new(),
        }
    }

    fn class_decl(&mut self, name: &str, fields: &[Field], mode: Mode) -> Result<String, String> {
        let mut params = Vec::new();
        let mut checks = String::new();
        let mut puts = String::new();
        let mut args = Vec::new();
        let mut seen = BTreeSet::new();
        for f in fields {
            let fname = camel(&f.name);
            if !seen.insert(fname.clone()) {
                return Err(format!("{name}: フィールド名 {fname} が重複します（{}）", f.name));
            }
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let ty = self.kty(inner, &format!("{name}{}", pascal(&f.name)), mode).map_err(|e| format!("{name}.{}: {e}", f.name))?;
            let default = if f.optional { " = null" } else { "" };
            params.push(format!("val {fname}: {ty}{}{default}", if opt { "?" } else { "" }));
            let path = format!("comatype.ValidationException.join(path, {})", kstr(&f.name));
            let body = self.vstmts(inner, &fname, &path, 0);
            if !body.is_empty() {
                if opt {
                    checks.push_str(&format!("if ({fname} != null) {{\n{body}}}\n"));
                } else {
                    checks.push_str(&body);
                }
            }
            if mode == Mode::Json {
                let e = self.enc(inner, &fname, 0);
                if f.optional {
                    puts.push_str(&format!("if ({fname} != null) m[{}] = {e}\n", kstr(&f.name)));
                } else if nullable {
                    puts.push_str(&format!("m[{}] = if ({fname} == null) null else {e}\n", kstr(&f.name)));
                } else {
                    puts.push_str(&format!("m[{}] = {e}\n", kstr(&f.name)));
                }
                let d = self.dec(inner);
                let call = if f.optional {
                    format!("comatype.Codec.opt(m, {}, path, {d})", kstr(&f.name))
                } else if nullable {
                    format!("comatype.Codec.req(m, {}, path, comatype.Codec.nullable({d}))", kstr(&f.name))
                } else {
                    format!("comatype.Codec.req(m, {}, path, {d})", kstr(&f.name))
                };
                args.push(format!("{fname} = {call}"));
            }
        }
        let implements = if mode == Mode::Json { " : comatype.JsonType" } else { "" };
        let mut body = String::new();
        if mode == Mode::Json {
            body.push_str(&format!("override fun validate(path: String) {{\n{checks}}}\n\n"));
            body.push_str(&format!("override fun encode(): Any? {{\nval m = java.util.LinkedHashMap<String, Any?>()\n{puts}return m\n}}\n\n"));
            body.push_str(&format!(
                "companion object {{\n    @JvmStatic\n    fun decode(j: Any?, path: String): {name} {{\n        val m = comatype.Codec.`object`(j, path)\n        val v = {name}({})\n        v.validate(path)\n        return v\n    }}\n}}\n",
                args.join(", ")
            ));
        } else if mode == Mode::Wire {
            body.push_str(&format!("fun validate(path: String) {{\n{checks}}}\n"));
        }
        let class = if fields.is_empty() { format!("class {name}") } else { format!("data class {name}({})", params.join(", ")) };
        if body.is_empty() {
            Ok(format!("{class}{implements}\n"))
        } else {
            Ok(format!("{class}{implements} {{\n{}}}\n", indent(body.trim_end())))
        }
    }

    fn named_object(&mut self, name: &str, t: &Type) -> Result<Option<String>, String> {
        self.used_names.insert(name.to_string());
        match t {
            Type::Object { fields } => {
                let decl = self.class_decl(name, fields, Mode::Json)?;
                let mut out = String::new();
                for e in self.extra.drain(..) {
                    out.push_str(&e);
                    out.push('\n');
                }
                out.push_str(&decl);
                Ok(Some(out))
            }
            _ => Ok(None),
        }
    }
}

fn type_names(svc: &Service) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    let mut by_name: BTreeMap<String, &str> = BTreeMap::new();
    for (id, nt) in &svc.types {
        let name = cap(&nt.name);
        if let Some(prev) = by_name.insert(name.clone(), id) {
            return Err(format!("Kotlin の型名 `{name}` が {prev} と {id} で重複しています"));
        }
        out.insert(id.clone(), name);
        if matches!(nt.def, TypeDef::Enum { .. }) {
            out.insert(format!("enum:{id}"), "1".into());
        }
    }
    Ok(out)
}

fn indent(s: &str) -> String {
    s.lines().map(|l| if l.is_empty() { String::new() } else { format!("    {l}") }).collect::<Vec<_>>().join("\n") + "\n"
}

// ---- Types.kt ----

fn types_file(svc: &Service, names: &BTreeMap<String, String>, package: &str) -> Result<String, String> {
    let mut g = Gen { names, prefix: "", extra: vec![], used_names: names.values().cloned().collect() };
    let mut body = String::new();
    for (id, nt) in &svc.types {
        let name = &names[id];
        match &nt.def {
            TypeDef::Object { fields } => {
                let decl = g.class_decl(name, fields, Mode::Json)?;
                for e in g.extra.drain(..) {
                    body.push_str(&e);
                    body.push('\n');
                }
                body.push_str(&decl);
                body.push('\n');
            }
            TypeDef::Enum { values } => {
                let mut consts = Vec::new();
                let mut seen = BTreeSet::new();
                for v in values {
                    let c = constant(v);
                    if !seen.insert(c.clone()) {
                        return Err(format!("{name}: enum の値 {c} が重複します（{v}）"));
                    }
                    consts.push(format!("{c}({})", kstr(v)));
                }
                let all = values.join(" | ");
                body.push_str(&format!(
                    "enum class {name}(private val wireValue: String) : comatype.Wire.WireEnum {{\n    {};\n\n    override fun wire(): String = wireValue\n\n    fun validate(path: String) {{}}\n\n    fun encode(): Any? = wireValue\n\n\
                     \x20   companion object {{\n        @JvmStatic\n        fun parse(s: String): {name} =\n            entries.firstOrNull {{ it.wireValue == s }} ?: throw IllegalArgumentException({})\n\n\
                     \x20       @JvmStatic\n        fun decode(j: Any?, path: String): {name} =\n            try {{\n                parse(comatype.Codec.string(j, path))\n            }} catch (e: IllegalArgumentException) {{\n                throw comatype.ValidationException(path, e.message ?: \"\")\n            }}\n    }}\n}}\n\n",
                    consts.join(",\n    "),
                    kstr(&format!("{all} のどれかにしてください"))
                ));
            }
        }
    }
    Ok(format!("{HEADER}package {package}\n\nobject Types {{\n{}}}\n", indent(body.trim_end())))
}

