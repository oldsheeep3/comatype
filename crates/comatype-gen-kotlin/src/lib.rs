fn cookie_def_kt(c: &CookieDef) -> String {
    let get = |k: &str| c.settings.get(k).map(String::as_str);
    let opt_s = |v: Option<&str>| v.map_or("null".to_string(), kstr);
    format!(
        "comatype.CookieDef({}, {}, {}, {}, {}, {}, {})",
        kstr(&c.name),
        get("httpOnly") == Some("true"),
        get("secure") == Some("true"),
        opt_s(get("sameSite")),
        opt_s(get("path")),
        opt_s(get("domain")),
        get("maxAge").map_or("null".to_string(), |v| format!("{v}L")),
    )
}

fn body_codec(g: &mut Gen, label: &str, t: &Type, ty: &str) -> String {
    let (inner, nullable) = strip_null(t);
    let _ = nullable;
    let v = g.vstmts(inner, "v", "\"\"", 0);
    let enc = g.enc(inner, "v", 0);
    let dec = match inner {
        Type::Object { .. } => format!("{ty}.Companion::decode"),
        _ => g.dec(inner),
    };
    format!(
        "private fun encode{label}(v: {ty}): ByteArray {{\n{}    return comatype.Codec.encodeValue({enc})\n}}\n\n\
         private fun decode{label}(b: ByteArray, path: String): {ty} =\n    comatype.Codec.decode(b, path, {dec})\n\n",
        v.lines().map(|l| format!("    {l}\n")).collect::<String>()
    )
}

fn wire_pairs(fields: &[Field], var: &str) -> String {
    fields.iter().map(|f| format!("{}, {var}.{}", kstr(&f.name), camel(&f.name))).collect::<Vec<_>>().join(", ")
}

fn wire_build(name: &str, fields: &[Field], g: &Gen, values: &str, split: bool) -> String {
    let args: Vec<String> = fields
        .iter()
        .map(|f| {
            let (inner, nullable) = strip_null(&f.ty);
            let opt = f.optional || nullable;
            let vals = values.replace("{}", &kstr(&f.name));
            let call = match inner {
                Type::Array { item } => format!("comatype.Wire.readList({vals}, {}, {split}, {opt}, {})", kstr(&f.name), g.wdec(item)),
                _ if opt => format!("comatype.Wire.readOpt({vals}, {}, {split}, {})", kstr(&f.name), g.wdec(inner)),
                _ => format!("comatype.Wire.read({vals}, {}, {split}, {})", kstr(&f.name), g.wdec(inner)),
            };
            format!("{} = {call}", camel(&f.name))
        })
        .collect();
    format!("{name}({})", args.join(", "))
}

/// The `cache` setting (GET / QUERY only)
fn cache_kt(ep: &Endpoint) -> String {
    use comatype_core::ast::CacheMode;
    let (mode, ttl) = match &ep.cache {
        None => return String::new(),
        Some(CacheMode::Off) => ("off", 0),
        Some(CacheMode::Memory { ttl_ms }) => ("memory", *ttl_ms),
        Some(CacheMode::Cookie { ttl_ms }) => ("cookie", *ttl_ms),
    };
    let names: Vec<String> = ep.request_headers.iter().map(|h| kstr(&h.name)).collect();
    format!(".cache(comatype.CacheSpec(\"{mode}\", {ttl}L), java.util.List.of({}))", names.join(", "))
}

fn endpoint_file(svc: &Service, names: &BTreeMap<String, String>, ep: &Endpoint, role: Role, package: &str) -> Result<String, String> {
    let class = module_class(&ep.module);
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let ctx = |e: String| format!("{}: {e}", ep.file);
    let mut body = String::new();
    let mut codecs = String::new();
    let has_req_headers = !ep.request_headers.is_empty();

    if !ep.params.is_empty() {
        body.push_str(&g.class_decl("Params", &ep.params, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    if !ep.search.is_empty() {
        body.push_str(&g.class_decl("Search", &ep.search, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let mut body_ty = String::new();
    if let Some(b) = &ep.body {
        g.used_names.insert("Body".into());
        if let Some(decl) = g.named_object("Body", b).map_err(ctx)? {
            body.push_str(&decl);
            body.push('\n');
            body_ty = "Body".into();
        } else {
            let (inner, _) = strip_null(b);
            body_ty = g.kty(inner, "Body", Mode::Json).map_err(ctx)?;
        }
        codecs.push_str(&body_codec(&mut g, "Body", b, &body_ty));
    }
    if has_req_headers {
        body.push_str(&g.class_decl("RequestHeaders", &ep.request_headers, Mode::Wire).map_err(ctx)?);
        body.push('\n');
    }
    let ctx_wrappers: Vec<&Wrapper> = ep.wraps.iter().filter_map(|w| svc.wrappers.iter().find(|x| &x.name == w)).collect();
    if role == Role::Server {
        let comps: Vec<String> = ctx_wrappers.iter().map(|w| format!("val {}: Init.{}Ctx", camel(&w.name), pascal(&w.name))).collect();
        body.push_str(&if comps.is_empty() { "/** 有効なラッパーが足した値 */\nclass Ctx\n\n".to_string() } else { format!("/** 有効なラッパーが足した値 */\ndata class Ctx({})\n\n", comps.join(", ")) });
    }
    let all_optional = |fs: &[Field]| fs.iter().all(|f| f.optional || strip_null(&f.ty).1);
    let mut req_comps: Vec<(&str, String, String)> = Vec::new(); // (name, type, default)
    if !ep.params.is_empty() {
        req_comps.push(("params", "Params".into(), String::new()));
    }
    if !ep.search.is_empty() {
        let d = if all_optional(&ep.search) { " = Search()" } else { "" };
        req_comps.push(("search", "Search".into(), d.into()));
    }
    if has_req_headers {
        let d = if all_optional(&ep.request_headers) { " = RequestHeaders()" } else { "" };
        req_comps.push(("headers", "RequestHeaders".into(), d.into()));
    }
    if ep.body.is_some() {
        req_comps.push(("body", body_ty.clone(), String::new()));
    }
    if role == Role::Server {
        req_comps.push(("ctx", "Ctx".into(), String::new()));
    }
    let has = |n: &str| req_comps.iter().any(|(f, _, _)| *f == n);
    body.push_str(&format!(
        "/** リクエスト全体 */\n{}\n\n",
        if req_comps.is_empty() {
            "class Request".to_string()
        } else {
            format!("data class Request({})", req_comps.iter().map(|(n, t, d)| format!("val {n}: {t}{d}")).collect::<Vec<_>>().join(", "))
        }
    ));

    let cookie = ep.cookie && svc.cookie.is_some();
    let mut variants = String::new();
    for r in &ep.responses {
        let c = r.status;
        let mut comps = Vec::new();
        if let Some(b) = &r.body {
            let label = format!("S{c}Res");
            let (inner, _) = strip_null(b);
            let ty = if let Some(decl) = g.named_object(&label, b).map_err(ctx)? {
                body.push_str(&decl);
                body.push('\n');
                label.clone()
            } else {
                g.kty(inner, &label, Mode::Json).map_err(ctx)?
            };
            codecs.push_str(&body_codec(&mut g, &format!("S{c}"), b, &ty));
            comps.push(format!("val body: {ty}"));
        }
        if !r.headers.is_empty() {
            body.push_str(&g.class_decl(&format!("S{c}Headers"), &r.headers, Mode::Wire).map_err(ctx)?);
            body.push('\n');
            let d = if all_optional(&r.headers) { format!(" = S{c}Headers()") } else { String::new() };
            comps.push(format!("val headers: S{c}Headers{d}"));
        }
        variants.push_str(&if comps.is_empty() { format!("object S{c} : Response\n") } else { format!("data class S{c}({}) : Response\n", comps.join(", ")) });
    }
    body.push_str(&format!("/** 全ステータスのレスポンス */\nsealed interface Response\n\n{variants}\n"));

    let arg = if has("params") || has("search") || has("headers") {
        "Request".to_string()
    } else if ep.body.is_some() {
        body_ty.clone()
    } else {
        "comatype.NoArg".to_string()
    };
    let res_ty = if role == Role::Server && cookie { "comatype.S.Reply<Response>".to_string() } else { "Response".to_string() };
    let wraps = if ep.wraps.is_empty() { "java.util.List.of<String>()".to_string() } else { format!("java.util.List.of({})", ep.wraps.iter().map(|w| kstr(w)).collect::<Vec<_>>().join(", ")) };
    let base = svc.base_url.as_ref().map_or("null".to_string(), |u| kstr(u));
    let cd = match (&svc.cookie, ep.cookie) {
        (Some(c), true) => cookie_def_kt(c),
        _ => "null".to_string(),
    };
    match role {
        Role::Client => body.push_str(&format!(
            "/** path とメソッド */\nval ENDPOINT: comatype.Endpoint<{arg}, Void, Response> = comatype.Endpoint.client(\n    {}, {}, {}, {base}, {wraps}, {}, {cd},\n    {{ a: {arg} -> buildRequest(a) }}, {{ r: comatype.RawResponse -> parseResponse(r) }}){}\n\n",
            kstr(&ep.method),
            kstr(&ep.path),
            kstr(&ep.module),
            ep.cookie,
            cache_kt(ep)
        )),
        Role::Server => body.push_str(&format!(
            "/** path とメソッド */\nval ENDPOINT: comatype.Endpoint<Void, Request, {res_ty}> = comatype.Endpoint.server(\n    {}, {}, {}, {base}, {wraps}, {}, {cd},\n    {{ r: comatype.RawRequest -> parseRequest(r) }}, {{ r: {res_ty} -> buildResponse(r) }}){}\n\n",
            kstr(&ep.method),
            kstr(&ep.path),
            kstr(&ep.module),
            ep.cookie,
            cache_kt(ep)
        )),
    }
    body.push_str(&codecs);

    match role {
        Role::Client => {
            let mut f = format!("private fun buildRequest(arg: {arg}): comatype.RawRequest {{\n    val raw = comatype.RawRequest({}, {})\n", kstr(&ep.method), kstr(&ep.path));
            if arg == "Request" {
                if has("params") {
                    f.push_str(&format!("    arg.params.validate(\"\")\n    comatype.Wire.fillPath(raw, {})\n", wire_pairs(&ep.params, "arg.params")));
                }
                if has("search") {
                    f.push_str(&format!("    arg.search.validate(\"\")\n    comatype.Wire.addQuery(raw, {})\n", wire_pairs(&ep.search, "arg.search")));
                }
                if has("headers") {
                    f.push_str(&format!("    arg.headers.validate(\"\")\n    comatype.Wire.setHeaders(raw.headers, {})\n", wire_pairs(&ep.request_headers, "arg.headers")));
                }
                if has("body") {
                    f.push_str("    raw.body = encodeBody(arg.body)\n    raw.headers.set(\"Content-Type\", \"application/json\")\n");
                }
            } else if arg != "comatype.NoArg" {
                f.push_str("    raw.body = encodeBody(arg)\n    raw.headers.set(\"Content-Type\", \"application/json\")\n");
            }
            f.push_str("    return raw\n}\n\n");
            body.push_str(&f);

            let mut p = String::from("private fun parseResponse(raw: comatype.RawResponse): Response {\n    return when (raw.status) {\n");
            for r in &ep.responses {
                let c = r.status;
                let mut inner = String::new();
                let mut args = Vec::new();
                if r.body.is_some() {
                    inner.push_str(&format!("if (raw.body.isEmpty()) throw comatype.ValidationException(\"body\", \"必須です\")\nval body = decodeS{c}(raw.body, \"body\")\n"));
                    args.push("body = body");
                }
                if !r.headers.is_empty() {
                    inner.push_str(&format!(
                        "val headers = {}\nheaders.validate(\"\")\n",
                        wire_build(&format!("S{c}Headers"), &r.headers, &g, "comatype.Wire.headerValues(raw.headers, {})", true)
                    ));
                    args.push("headers = headers");
                }
                let ctor = if args.is_empty() { format!("S{c}") } else { format!("S{c}({})", args.join(", ")) };
                p.push_str(&format!("        {c} -> {{\n{}            {ctor}\n        }}\n", inner.lines().map(|l| format!("            {l}\n")).collect::<String>()));
            }
            p.push_str("        else -> throw comatype.ComatypeException.UnexpectedStatus(raw.status, raw.body)\n    }\n}\n");
            body.push_str(&p);
        }
        Role::Server => {
            let mut f = String::from("private fun parseRequest(raw: comatype.RawRequest): Request {\n");
            let mut inits = Vec::new();
            if has("params") {
                f.push_str(&format!("    val params = {}\n    params.validate(\"\")\n", wire_build("Params", &ep.params, &g, "comatype.Wire.paramValues(raw, {})", false)));
                inits.push("params = params");
            }
            if has("search") {
                f.push_str(&format!("    val search = {}\n    search.validate(\"\")\n", wire_build("Search", &ep.search, &g, "comatype.Wire.queryValues(raw, {})", false)));
                inits.push("search = search");
            }
            if has("headers") {
                f.push_str(&format!(
                    "    val headers = {}\n    headers.validate(\"\")\n",
                    wire_build("RequestHeaders", &ep.request_headers, &g, "comatype.Wire.headerValues(raw.headers, {})", true)
                ));
                inits.push("headers = headers");
            }
            if has("body") {
                f.push_str("    if (raw.body.isEmpty()) throw comatype.ValidationException(\"body\", \"必須です\")\n    val body = decodeBody(raw.body, \"body\")\n");
                inits.push("body = body");
            }
            if has("ctx") {
                let cs: Vec<String> = ctx_wrappers
                    .iter()
                    .map(|w| format!("{} = comatype.S.ctx(raw, {}, Init.{}Ctx::class.java)", camel(&w.name), kstr(&w.name), pascal(&w.name)))
                    .collect();
                f.push_str(&format!("    val ctx = Ctx({})\n", cs.join(", ")));
                inits.push("ctx = ctx");
            }
            f.push_str(&format!("    return Request({})\n}}\n\n", inits.join(", ")));
            body.push_str(&f);

            let mut b = format!("private fun buildResponse(reply: {res_ty}): comatype.RawResponse {{\n");
            b.push_str(if cookie { "    val res: Response = reply.response()\n" } else { "    val res: Response = reply\n" });
            b.push_str("    val out: comatype.RawResponse = when (res) {\n");
            for r in &ep.responses {
                let c = r.status;
                let pat = if r.body.is_none() && r.headers.is_empty() { format!("is S{c}") } else { format!("is S{c}") };
                let mut st = format!("val o = comatype.RawResponse({c})\n");
                if r.body.is_some() {
                    st.push_str(&format!("o.body = encodeS{c}(res.body)\no.headers.set(\"Content-Type\", \"application/json\")\n"));
                }
                if !r.headers.is_empty() {
                    st.push_str(&format!("res.headers.validate(\"\")\ncomatype.Wire.setHeaders(o.headers, {})\n", wire_pairs(&r.headers, "res.headers")));
                }
                st.push_str("o\n");
                b.push_str(&format!("        {pat} -> {{\n{}        }}\n", st.lines().map(|l| format!("            {l}\n")).collect::<String>()));
            }
            b.push_str("    }\n");
            if cookie {
                b.push_str("    comatype.S.applyCookie(out, ENDPOINT.cookieDef, reply.cookie())\n");
            }
            b.push_str("    return out\n}\n");
            body.push_str(&b);
        }
    }

    Ok(format!(
        "{HEADER}package {package}\n\n/** {} — {} {} */\nobject {class} {{\n{}}}\n",
        ep.file,
        ep.method.to_uppercase(),
        ep.path,
        indent(body.trim_end())
    ))
}

// ---- Init.kt ----

fn init_file(svc: &Service, names: &BTreeMap<String, String>, role: Role, package: &str) -> Result<String, String> {
    let mut g = Gen { names, prefix: "Types.", extra: vec![], used_names: BTreeSet::new() };
    let mut body = String::new();
    let mut comps = Vec::new();
    let mut entries = String::new();
    let mut seen_status: BTreeMap<u16, &str> = BTreeMap::new();
    for w in &svc.wrappers {
        let (p, f) = (pascal(&w.name), camel(&w.name));
        match role {
            Role::Server => {
                let ctx_name = format!("{p}Ctx");
                body.push_str(&format!("/** ラッパー {} が足す値（ハンドラの req.ctx.{f}） */\n", w.name));
                body.push_str(&g.class_decl(&ctx_name, &w.ctx, Mode::Plain)?);
                body.push('\n');
                for r in &w.responses {
                    if let Some(prev) = seen_status.insert(r.status, &w.name) {
                        return Err(format!("wrapper `{}` と `{prev}` が同じ s{} を宣言しています", w.name, r.status));
                    }
                    let c = r.status;
                    match &r.body {
                        Some(b) => {
                            let label = format!("S{c}Res");
                            let (inner, _) = strip_null(b);
                            let ty = if let Some(decl) = g.named_object(&label, b)? {
                                body.push_str(&decl);
                                body.push('\n');
                                label.clone()
                            } else {
                                g.kty(inner, &label, Mode::Json)?
                            };
                            let v = g.vstmts(inner, "body", "\"\"", 0);
                            let enc = g.enc(inner, "body", 0);
                            body.push_str(&format!(
                                "/** ラッパー {} が返せるステータス {c} のレスポンス */\nfun s{c}(body: {ty}): comatype.RawResponse {{\n{}    val r = comatype.RawResponse({c})\n    r.body = comatype.Codec.encodeValue({enc})\n    r.headers.set(\"Content-Type\", \"application/json\")\n    return r\n}}\n\n",
                                w.name,
                                v.lines().map(|l| format!("    {l}\n")).collect::<String>()
                            ));
                        }
                        None => body.push_str(&format!("/** ラッパー {} が返せるステータス {c} のレスポンス */\nfun s{c}(): comatype.RawResponse = comatype.RawResponse({c})\n\n", w.name)),
                    }
                }
                comps.push(format!("val {f}: comatype.ktx.SWrap<{ctx_name}>"));
                entries.push_str(&format!("m[{}] = comatype.ktx.adaptSuspend({}, {f})\n", kstr(&w.name), kstr(&w.name)));
            }
            Role::Client => {
                comps.push(format!("val {f}: comatype.ktx.CWrap"));
                entries.push_str(&format!("m[{}] = {f}\n", kstr(&w.name)));
            }
        }
    }
    let (set, wrap_ty) = match role {
        Role::Server => ("SWrapperSet", "comatype.S.ServerWrap"),
        Role::Client => ("CWrapperSet", "comatype.ktx.CWrap"),
    };
    let set_name = if role == Role::Server { "S" } else { "CK" };
    body.push_str(&format!(
        "/** init.comat の `wrapper` ごとの実装（suspend の関数）。{set_name}.init に渡す */\nclass Wrappers({}) : comatype.ktx.{set} {{\n    override fun comatypeWrappers(): Map<String, {wrap_ty}> {{\n        val m = java.util.LinkedHashMap<String, {wrap_ty}>()\n{}        return m\n    }}\n}}\n",
        comps.join(", "),
        indent(&indent(&entries))
    ));
    Ok(format!("{HEADER}package {package}\n\n/** init.comat から生成 */\nobject Init {{\n{}}}\n", indent(body.trim_end())))
}

